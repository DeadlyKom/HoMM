
                    ifndef _INPUT_CHECK_KEY_STATE_
                    define _INPUT_CHECK_KEY_STATE_
; -----------------------------------------
; проверить состояние виртуальной клавиши
; In :
;   A  - "виртуальная клавиша"
; Out :
;   A  - исходная "виртуальная клавиша"
;   флаг Z установлен, если "виртуальная клавиша" нажата
; Corrupt :
;   BC, AF
; Note:
;
;   диапазоны кодов "виртуальных клавиш"
;   +-----------+---------+--------------------------------------+
;   | Hex       | Decimal | Назначение                           |
;   +-----------+---------+--------------------------------------+
;   | #00       |       0 | VK_NONE                              |
;   | #01-#28   |    1-40 | простые клавиши                       |
;   | #29-#50   |   41-80 | CS + основная клавиша                 |
;   | #51-#78   |  81-120 | SS + основная клавиша                 |
;   | #79-#7F   | 121-127 | не используются                      |
;   | #80-#BF   | 128-191 | область Kempston-джойстика            |
;   | #C0-#FF   | 192-255 | область Kempston-мыши                 |
;   +-----------+---------+--------------------------------------+
;   коды джойстика, #80, #88, #90, #98, #A0, #A8, #B0, #B8
;   коды кнопок мыши, #C1 левая, #C2 правая, #C4 средняя
; -----------------------------------------
CheckKeyState:  PUSH HL
                LD HL, .RET
                LD (.VK), A

                ; проверка отсутствия назначенной клавиши
                OR A
                JR Z, .NoKey                                                    ; переход, если отсутствует "виртуальная клавиша"

                ; -----------------------------------------
                ;      7    6    5    4    3    2    1    0
                ;   +----+----+----+----+----+----+----+----+
                ;   | IA | K6 | K5 | K4 | K3 | K2 | K1 | K0 |
                ;   +----+----+----+----+----+----+----+----+
                ;
                ;   IA      [7]     - флаг, принадлежности инпута
                ;                       0 - клавиатура
                ;                       1 - дополнительный Kempston-мышь/джойстик
                ;   K6-K0   [6-0]   - клавиша
                ; -----------------------------------------

                ; проверка старшего бита типа устройства
                JP M, .IsKempston                                               ; переход, если задан Kempston-джойстик или мышь

.Keyboard       ; -----------------------------------------
                ; клавиатура
                ; -----------------------------------------
                
                ; проверка номера простой клавиши
                CP VK_BASIC_MAX
                JP C, Keyboard.CheckKeyState                                    ; переход, если задана простая клавиша

                ; расчёт основной клавиши сочетания с Caps Shift
                LD B, VK_CAPS_SHIFT
                SUB VK_BASIC_COUNT

                ; проверка принадлежности к сочетаниям с Caps Shift
                CP VK_BASIC_MAX
                JR C, .CheckMod                                                 ; переход, если требуется Caps Shift

                ; расчёт основной клавиши сочетания с Symbol Shift
                SUB VK_BASIC_COUNT

                ; проверка границы сочетаний с Symbol Shift
                CP VK_BASIC_MAX
                JR NC, .NoKey                                                   ; переход, если код клавиатуры недопустим
                LD B, VK_SYMBOL_SHIFT

.CheckMod       ; проверка нажатия клавиши модификатора
                PUSH AF                                                         ; сохранение основной клавиши перед проверкой модификатора
                LD A, B
                LD HL, .CheckBase
                JP Keyboard.CheckKeyState

.CheckBase      ; проверка результата опроса модификатора
                POP BC                                                          ; восстановление основной клавиши без изменения результата опроса
                JR NZ, .RET                                                     ; переход, если требуемый модификатор отпущен

                ; проверка основной клавиши существующим обработчиком
                LD A, B
                LD HL, .RET
                JP Keyboard.CheckKeyState

.NoKey          ; формирование результата, "виртуальная клавиша" не нажата
                XOR A                                                           ; VK_NONE
                INC A

.VK             EQU $+1
.RET            LD A, #00
                POP HL
                RET

.IsKempston     ; -----------------------------------------
                ; Kempston-мышь/джойстик инпут
                ; -----------------------------------------

                ; -----------------------------------------
                ;      7    6    5    4    3    2    1    0
                ;   +----+----+----+----+----+----+----+----+
                ;   | 1  | KI | .. | .. | .. | .. | .. | .. |
                ;   +----+----+----+----+----+----+----+----+
                ;
                ;   KI      [6]     - флаг, принадлежности инпута
                ;                       0 - Kempston-джойстик
                ;                       1 - Kempston-мышь
                ; -----------------------------------------

                ; проверка принадлежности инпута
                BIT KEMPSTON_INPUT_BIT, A
                JP Z, Kempston.CheckKeyState                                    ; переход, если Kempston-джойстик
                
                ifdef ENABLE_MOUSE
                JP Mouse.CheckKeyState
                else
                JR .NoKey
                endif

                endif ; ~_INPUT_CHECK_KEY_STATE_