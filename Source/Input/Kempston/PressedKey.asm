
                    ifndef _INPUT_KEMPSTON_PRESSED_KEY_STATE_
                    define _INPUT_KEMPSTON_PRESSED_KEY_STATE_
; -----------------------------------------
; получить код первого нажатого направления или кнопки Kempston-джойстика
; In:
; Out:
;   E  - "виртуальная клавиша"
;   если была нажата клавиша флаг переполнения установлен
; Corrupt:
;   DE, AF
; Note:
;   учитываются доступность джойстика и режим опроса 5 или 8 кнопок
;   при нескольких нажатиях выбирается младший установленный бит порта #1F
; -----------------------------------------
GetPressedKey:  ; проверка наличия кемстон джойстика
                CHECK_HARD_INPUT_FLAG_A HARD_INPUT_KEMPSTON_BIT
                JR Z, .Skip                                                     ; переход, т.к. кемпстон не поддерживается

                ; тип кемпстон джойстика 5 или 8 кнопочный
                CHECK_FLAG_A HARD_INPUT_KEMPSTON_BUTTON_BIT
                LD D, #05
                JR Z, $+4
                LD D, #08

                LD E, VK_KEMPSTON_RIGHT
                XOR A
                IN A, (#1F)
.NextBit        RRA
                JR C, .Found                                                    ; переход, если найдена нажатая кнопка
                INC E
                DEC D
                JR NZ, .NextBit

.Skip           OR A
                RET
.Found          ; формирование кода кнопки из её номера
                LD A, E
                AND %00000111
                RLCA
                RLCA
                RLCA
                OR KEMPSTON_JOYSTICK
                LD E, A
                SCF
                RET
; -----------------------------------------
; ожидать нажатое направление или кнопку Kempston-джойстика
; In:
; Out:
;   E  - "виртуальная клавиша"
;   если была нажата клавиша флаг переполнения установлен
;   Z  - флаг, установлен при недоступном джойстике и сброшен при нажатии
; Corrupt:
;   DE, AF
; Note:
;   при недоступном джойстике возврат немедленный, E и флаг переполнения сохраняются
;   при доступном джойстике опрос выполняется после HALT
;   для ожидания нужны разрешённые прерывания и их источник
;   уже удерживаемое направление или кнопка также завершает ожидание
; -----------------------------------------
WaitPressedKey: ; проверка наличия кемстон джойстика
                CHECK_HARD_INPUT_FLAG_A HARD_INPUT_KEMPSTON_BIT
                RET Z
                
                HALT
                CALL GetPressedKey
                RET C
                JR WaitPressedKey
; -----------------------------------------
; ожидать отпускания всех опрашиваемых направлений и кнопок Kempston
; In:
; Out:
;   флаг переполнения сброшен после отпускания всех опрашиваемых кнопок
;   Z  - флаг, установлен при недоступном джойстике
; Corrupt:
;   DE, AF
; Note:
;   при недоступном джойстике возврат немедленный, E и флаг переполнения сохраняются
;   при доступном джойстике состояние Z не определено контрактом
;   опрос выполняется после HALT, нужны разрешённые прерывания и их источник
;   учитывается режим опроса 5 или 8 кнопок
; -----------------------------------------
WaitReleasedKey ; проверка наличия кемстон джойстика
                CHECK_HARD_INPUT_FLAG_A HARD_INPUT_KEMPSTON_BIT
                RET Z
                
                HALT
                CALL GetPressedKey
                RET NC
                JR WaitReleasedKey
; -----------------------------------------
; прочитать порт Kempston-джойстика с текущим наложением маски
; In:
; Out:
;   A  - значение порта #1F с установленными по маске D битами при доступном джойстике
;   флаг переполнения установлен при недоступном джойстике и сброшен иначе
;   Z  - флаг, установлен при недоступном джойстике и сброшен иначе
; Corrupt:
;   DE, AF
; Note:
;   маска D равна #1F для режима 5 кнопок и #FF для режима 8 кнопок
;   текущая инструкция OR D всегда сбрасывает Z при доступном джойстике
;   результат Z не показывает наличие нажатия
; -----------------------------------------
AnyKeyPressed:  ; проверка наличия кемстон джойстика
                CHECK_HARD_INPUT_FLAG_A HARD_INPUT_KEMPSTON_BIT
                SCF
                RET Z                                                           ; выход, т.к. кемпстон не поддерживается

                ; тип кемпстон джойстика 5 или 8 кнопочный
                CHECK_FLAG_A HARD_INPUT_KEMPSTON_BUTTON_BIT
                LD D, %00011111
                JR Z, $+4
                LD D, %11111111
                
                XOR A
                IN A, (#1F)
                OR D
                RET

                endif ; ~_INPUT_KEMPSTON_PRESSED_KEY_STATE_
