
                    ifndef _INPUT_KEYBOARD_PRESSED_KEY_STATE_
                    define _INPUT_KEYBOARD_PRESSED_KEY_STATE_
; -----------------------------------------
; получить код первой нажатой клавиши клавиатуры
; In:
; Out:
;   E  - "виртуальная клавиша"
;   если была нажата клавиша флаг переполнения установлен
; Corrupt:
;   DE, BC, AF
; Note:
;   SerdjukSVS (C)
; -----------------------------------------
GetPressedKey:  LD DE, #0501
                LD BC, #FEFE
.NextPort       IN A, (C)
                CPL
.NextBit        RRA
                RET C
                INC E
                DEC D
                JR NZ, .NextBit
                RLC B
                RET NC
                LD D, #05
                JR .NextPort
; -----------------------------------------
; получить клавишу и сохранить состояния модификаторов клавиатуры
; In:
; Out:
;   HL - GameState.Input
;   A' - состояния нажатия symbol (1 бит) и caps shift (0 бит)
;        GameState.Input хранит копию
;   E  - "виртуальная клавиша"
;   если была нажата клавиша флаг переполнения установлен
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   CS и SS исключены из выбора клавиши и не образуют код сочетания
;   в GameState.Input обновляются только биты 0 CS и 1 SS
;   остальные биты GameState.Input сохраняются
; -----------------------------------------
GetVirtualKey:  ; инициализация
                LD DE, #0402
                LD BC, #FEFE
                IN A, (C)
                CPL

                ; #FEFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  V |  C |  X |  Z | CS |
                ;   +----+----+----+----+----+----+----+----+

                LD L, A                                                         ; сохранение сосояние caps shift
                RRA                                                             ; пропуск состояния caps shift

.NextBit_FEFE   RRA
                JR C, .CheckSS
                INC E
                DEC D
                JR NZ, .NextBit_FEFE

                LD H, #06                                                       ; пройти 6 портов

                ; #FDFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  G |  F |  D |  S |  A |
                ;   +----+----+----+----+----+----+----+----+
                ; #FBFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  T |  R |  E |  W |  Q |
                ;   +----+----+----+----+----+----+----+----+
                ; #F7FE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  5 |  4 |  3 |  2 |  1 |
                ;   +----+----+----+----+----+----+----+----+
                ; #EFFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  6 |  7 |  8 |  9 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ; #DFFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  Y |  U |  I |  O |  P |
                ;   +----+----+----+----+----+----+----+----+
                ; #BFFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  H |  J |  K |  L | EN |
                ;   +----+----+----+----+----+----+----+----+
.NextPort       LD D, #05
                RLC B                                                           ; следующий порт
                IN A, (C)
                CPL
                

.NextBit        RRA
                JR C, .CheckSS
                INC E
                DEC D
                JR NZ, .NextBit
                DEC H
                JR NZ, .NextPort

.CheckSS        ; #7FFE
                ;   +----+----+----+----+----+----+----+----+
                ;   |  7 |  6 |  5 |  4 |  3 |  2 |  1 |  0 |
                ;   +----+----+----+----+----+----+----+----+
                ;   | .. | .. | .. |  B |  N |  M | SS | SP |
                ;   +----+----+----+----+----+----+----+----+
                LD B, #7F
                IN A, (C)
                CPL

                LD H, A                                                         ; сохранение сосояние symbol shift
                JR C, .IsPressed

                ; 0 бит
                RRA
                JR C, .IsPressed
                ; 1 бит
                INC E
                RRA                                                             ; пропуск состояния symbol shift
                ; 2 бит
                INC E
                RRA
                JR C, .IsPressed
                ; 3 бит
                INC E
                RRA
                JR C, .IsPressed
                ; 4 бит
                INC E
                RRA
                JR C, .IsPressed

                LD E, VK_NONE

.IsPressed      EX AF, AF'
                LD A, L
                XOR H
                AND %11111101
                XOR H

                ; сохранение состояния SS и CS во флагах
                INPUT_FLAGS
                XOR (HL)
                AND %00000011
                XOR (HL)
                LD (HL), A
                EX AF, AF'

                RET
; -----------------------------------------
; ожидать нажатую клавишу клавиатуры
; In:
; Out:
;   E  - "виртуальная клавиша"
;   если была нажата клавиша флаг переполнения установлен
; Corrupt:
;   DE, BC, AF
; Note:
;   опрос выполняется после HALT, нужны разрешённые прерывания и их источник
;   уже удерживаемая клавиша также завершает ожидание
; -----------------------------------------
WaitPressedKey: HALT
                CALL GetPressedKey
                RET C
                JR WaitPressedKey
; -----------------------------------------
; ожидать отпускания всех клавиш клавиатуры
; In:
; Out:
;   флаг переполнения сброшен после отпускания всех клавиш
; Corrupt:
;   DE, BC, AF
; Note:
;   опрос выполняется после HALT, нужны разрешённые прерывания и их источник
;   проверяются все 40 клавиш, включая CS и SS
;   значение E при возврате не является результатом выбора клавиши
; -----------------------------------------
WaitReleasedKey HALT
                CALL GetPressedKey
                RET NC
                JR WaitReleasedKey
; -----------------------------------------
; проверить наличие нажатых клавиш клавиатуры
; In:
; Out:
;   A  - маска нажатий по пяти столбцам всех полустрок
;   Z  - флаг, сброшен при наличии хотя бы одной нажатой клавиши
;   флаг переполнения сброшен при возврате
; Corrupt:
;   AF
; Note:
;   опрашиваются все полустроки, включая CS и SS
;   номер отдельной клавиши не определяется
; -----------------------------------------
AnyKeyPressed:  XOR A
                IN A, (#FE)
                CPL
                AND %00011111
                RET

                endif ; ~_INPUT_KEYBOARD_PRESSED_KEY_STATE_
