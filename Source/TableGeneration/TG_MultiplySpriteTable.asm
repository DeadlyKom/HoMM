                ifndef _TABLE_GENERATION_MULTIPLY_SPRITE_TABLE_
                define _TABLE_GENERATION_MULTIPLY_SPRITE_TABLE_

                module Tables
; -----------------------------------------
; генерация таблицы для расчёта размера спрайта
; In:
; Out:
; Corrupt:
; Note:
;   AR = 0, размер пикселей с масками
;   AR = 1, полный размер данных с масками и атрибутами
;   LD_ATTR содержит 10 байт на знакоместо, OR & XOR ATTR содержит 18 байт
;
;   специальные значения ячеек таблицы:
;   #00 трактуется Memcpy.Sprite как количество копируемых байт, равное 256
;   #FF обозначает недопустимый размер OR & XOR ATTR 32x32, требующий 288 байт
;
; AR = 0, без атрибутов
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | AR | R4 | R3 | R2 | R1 | R0 | W1 | W0 |
;   +----+----+----+----+----+----+----+----+
;
;   AR      [7]         - равен 0 (атрибуты не учитываются)
;   R4-R0   [6..2]      - высота в пикселях минус один (1-32 строки)
;   W1,W0   [1,0]       - исходная ширина спрайта в знакоместах минус один
;
; AR = 1, с атрибутами
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | AR | R4 | R3 | MD | .. | .. | W1 | W0 |
;   +----+----+----+----+----+----+----+----+
;
;   AR      [7]         - равен 1 (атрибуты учитываются)
;   R4,R3   [6,5]       - высота в знакоместах минус один (1-4 знакоместа)
;                         высота кратна 8 пикселям
;   MD      [4]         - режим расчёта размера, 0 для LD_ATTR, 1 для OR & XOR ATTR
;           [3,2]       - не используются, значение не влияет на табличный размер
;   W1,W0   [1,0]       - исходная ширина спрайта в знакоместах минус один
;
;   размер таблицы 256 байт
; -----------------------------------------
TG_MulSprTable: LD HL, Adr.MultiplySprite

                ; генерация размеров пикселей с масками для AR = 0
                LD D, #20
                LD C, #01
.RowLoop        ; расчёт размера одного столбца пикселей с масками
                LD A, C
                ADD A, A
                LD E, A
                LD B, #04
                XOR A
.WidthLoop      ADD A, E
                LD (HL), A

                INC L
                DJNZ .WidthLoop

                INC C
                DEC D
                JR NZ, .RowLoop                                                 ; переход, если рассчитаны не все высоты в пикселях

                ; генерация полных размеров данных с атрибутами для AR = 1
.AttrLoop       ; расчёт высоты в знакоместах из битов 6 и 5 индекса
                LD A, L
                RLCA
                RLCA
                RLCA
                AND #03
                INC A

                ; расчёт размера одного столбца знакомест с масками и атрибутами
                ADD A, A
                LD D, A                                                         ; два байта маски и атрибута на знакоместо
                ADD A, A
                ADD A, A                                                        ; восемь байт пикселей на знакоместо

                ; проверка наличия масок пикселей в режиме OR & XOR ATTR
                BIT 4, L
                JR Z, .AttrWidth                                                ; переход, если выбран LD_ATTR без масок пикселей
                ADD A, A                                                        ; шестнадцать байт пикселей и масок на знакоместо
.AttrWidth      ADD A, D
                LD E, A

                ; расчёт полного размера данных по ширине спрайта
                LD A, L
                AND #03
                INC A
                LD B, A
                XOR A
.AttrMul        ADD A, E
                DJNZ .AttrMul

                ; проверка переполнения размера данных спрайта
                JR NC, .AttrStore                                               ; переход, если размер данных спрайта помещается в байт
                LD A, #FF                                                       ; признак недопустимого размера спрайта

                ; сохранение размера для текущего индекса, биты 3 и 2 не участвуют в расчёте
.AttrStore      LD (HL), A
                INC L
                JR NZ, .AttrLoop                                                ; переход, если заполнены не все индексы с атрибутами

                RET

                display " - Multiply sprite table generator:\t\t\t", /A, TG_MulSprTable, "\t= busy [ ", /D, $-TG_MulSprTable, " byte(s)  ]"
                endmodule

                endif ; ~ _TABLE_GENERATION_MULTIPLY_SPRITE_TABLE_
