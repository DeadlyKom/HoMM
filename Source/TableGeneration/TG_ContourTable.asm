                ifndef _TABLE_GENERATION_CONTOUR_TABLE_
                define _TABLE_GENERATION_CONTOUR_TABLE_
; -----------------------------------------
; объединение готового сдвига с накопленным фрагментом
; In:
;   E   - индекс исходного байта
;   C   - накопленный фрагмент
; Out:
;   C   - объединённый фрагмент
; Corrupt:
;   D, C, AF
; Note:
; -----------------------------------------
CONTOUR_TG_OR   macro Offset?
                ; выбор готового сдвига по смещению Offset? в существующей ShiftTable
                LD D, HIGH (Adr.ShiftTable + Offset?)                           ; выбор части существующей таблицы сдвигов
                LD A, (DE)                                                      ; готовый сдвинутый фрагмент исходного байта
                OR C                                                            ; объединение фрагментов расширения
                LD C, A                                                         ; накопленный фрагмент результата
                endm
; -----------------------------------------
; генерация трёх частей расширения заданного радиуса
; In:
;   HL  - начало 768 байт, выровненное на 256 байт
;   Radius? - радиус расширения, 1..3
; Out:
;   HL  - адрес сразу после сформированной части таблицы
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   части по 256 байт расположены в порядке 0, +1, -1
; -----------------------------------------
CONTOUR_TG_RAD  macro Radius?
.Loop           LD E, L                                                         ; индекс исходного байта для всех его фрагментов

                ; -----------------------------------------
                ; расширение внутри текущего байта
                ; -----------------------------------------
                LD C, L                                                         ; исходная маска текущего байта
.Shift          defl #0000
                dup Radius?
                CONTOUR_TG_OR .Shift                                            ; добавление сдвига вправо
                CONTOUR_TG_OR #0D00 - .Shift                                    ; добавление сдвига влево
.Shift          = .Shift + #0200
                edup
                LD (HL), C                                                      ; готовое расширение внутри текущего байта

                ; -----------------------------------------
                ; перенос в следующий байт
                ; -----------------------------------------
                INC H                                                           ; переход к части таблицы +1
                LD C, #00                                                       ; начальное значение переноса
.Shift          defl #0000
                dup Radius?
                CONTOUR_TG_OR #0C00 - .Shift                                    ; добавление переноса в байт +1
.Shift          = .Shift + #0200
                edup
                LD (HL), C                                                      ; готовый перенос в следующий байт

                ; -----------------------------------------
                ; перенос в предыдущий байт
                ; -----------------------------------------
                INC H                                                           ; переход к части переноса в предыдущий байт
                LD C, #00                                                       ; начальное значение переноса
.Shift          defl #0000
                dup Radius?
                CONTOUR_TG_OR #0100 + .Shift                                    ; добавление переноса в байт -1
.Shift          = .Shift + #0200
                edup
                LD (HL), C                                                      ; готовый перенос в предыдущий байт
                DEC H                                                           ; переход к части таблицы +1
                DEC H                                                           ; переход к части таблицы 0
                INC L                                                           ; следующее значение исходного байта
                JR NZ, .Loop                                                    ; переход, если обработаны не все 256 значений

                ; -----------------------------------------
                ; адрес после сформированной части таблицы
                ; -----------------------------------------
                INC H                                                           ; пропуск части 0
                INC H                                                           ; пропуск части +1
                INC H                                                           ; пропуск части -1
                endm

                module Tables
; -----------------------------------------
; генерация общей таблицы квадратного расширения
; In:
;   HL  - начало 2304 байт, выровненное на 256 байт
; Out:
;   HL  - адрес сразу после всей сформированной таблицы
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   +#0000 - 0, +1, -1 радиуса 1, 768 байт
;   +#0300 - 0, +1, -1 радиуса 2, 768 байт
;   +#0600 - 0, +1, -1 радиуса 3, 768 байт
;   +#0900 - адрес после таблицы
;   существующая ShiftTable должна быть предварительно заполнена
;   область назначения не пересекается с существующей ShiftTable
; -----------------------------------------
TG_Contour:     ; формирование всех частей общей таблицы

                ; -----------------------------------------
                ; три части расширения радиуса 1
                ; -----------------------------------------
                CONTOUR_TG_RAD 1

                ; -----------------------------------------
                ; три части расширения радиуса 2
                ; -----------------------------------------
                CONTOUR_TG_RAD 2

                ; -----------------------------------------
                ; три части расширения радиуса 3
                ; -----------------------------------------
                CONTOUR_TG_RAD 3

                RET

                display " - Contour table generator:\t\t\t\t", /A, TG_Contour, "\t= busy [ ", /D, $-TG_Contour, " byte(s) ]"
                endmodule

                endif                                                           ; ~ _TABLE_GENERATION_CONTOUR_TABLE_
