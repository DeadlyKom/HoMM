                ifndef _TABLE_GENERATION_BAYER_GRADIENT_
                define _TABLE_GENERATION_BAYER_GRADIENT_

                module Tables
; -----------------------------------------
; генерация горизонтальной текстуры Bayer 256x8
; In:
;   HL - адрес выходного буфера размером 256 байт, выровненный по границе 256 байт
; Out:
;   восемь строк текстуры по 32 байта
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   старший бит байта соответствует левому пикселю
;   единичный бит соответствует светлому пикселю
; -----------------------------------------
TG_BayerGradient:
                ; инициализация
                LD (.TextureAdr), HL                                            ; установка адреса первого байта выходной текстуры
                XOR A                                                           ; установка начальной координаты X

.Column         ; сохранение X для продолжения внешнего цикла
                PUSH AF
                LD E, A

                ; -----------------------------------------
                ; расчёт исходного уровня
                ;   s = floor(65 * X / 255)
                ; -----------------------------------------

                ; сохранение X для последующего сложения
                LD C, A                                                         ; координата X, диапазон 0..255
                LD B, #00

                ; размещение младших двух битов X в позициях 7..6
                RRCA
                RRCA
                LD L, A

                ; получение старшего байта произведения X * 64
                AND #3F
                LD H, A

                ; получение младшего байта произведения X * 64
                LD A, L
                AND #C0
                LD L, A

                ; расчёт HL = X * 64 + X
                ADD HL, BC

                ; деление на 255, проверка H + L >= 255 через перенос суммы H + L + 1
                LD A, H
                INC A
                ADD A, L

                ; расчёт частного H плюс перенос, B содержит ноль
                LD A, H
                ADC A, B                                                        ; floor(65 * X / 255), диапазон 0..65
                
                ; -----------------------------------------
                ; коррекция уровня заполнения с учётом зенитов, дня 13 часов и ночи 11 часов
                ;   v = clamp(153 * s - 1248, 0, 7488)
                ;   Result = floor((4 * v + min(v, 3328)) / 512)
                ; -----------------------------------------
                CALL .Correct
                LD C, A

                ; расчёт адреса Bayer8[0][X & 7]
                LD A, E
                AND #07
                LD E, A
                LD D, #00
                LD HL, .Bayer8
                ADD HL, DE
                EX DE, HL

                ; выбор выходного байта в первой строке текстуры
.TextureAdr     EQU $+1
                LD HL, #0000

                ; подготовка обработки восьми строк текущего столбца
                LD B, #08

.Pixel          ; сравнение порога Bayer с рассчитанным уровнем
                LD A, (DE)
                CP C

                ; добавление светлого пикселя при Bayer8[Y][X & 7] < Level
                RL (HL)

                ; расчёт адреса того же байта в следующей строке текстуры
                LD A, L
                ADD A, #20
                LD L, A
                JR NC, .TextureRowReady                                         ; переход, если адрес строки текстуры не пересёк границу страницы и старший байт не требует изменения

                ; учёт переноса в старший байт адреса текстуры
                INC H

.TextureRowReady; расчёт адреса того же столбца в следующей строке Bayer
                LD A, E
                ADD A, #08
                LD E, A
                JR NC, .BayerRowReady                                           ; переход, если адрес строки Bayer не пересёк границу страницы и старший байт не требует изменения

                ; учёт переноса в старший байт адреса Bayer
                INC D

.BayerRowReady  DJNZ .Pixel

                ; восстановление X и переход к следующему столбцу
                POP AF
                INC A
                RET Z                                                           ; выход, если после обработки X = 255 координата переполнилась

                ; проверка завершения очередной группы из восьми столбцов
                LD E, A
                AND #07
                JR NZ, .SameByte                                                ; переход, если X не кратен восьми и нужно продолжить заполнение текущего байта

                ; переход к следующему выходному байту после восьми столбцов
                LD HL, .TextureAdr
                INC (HL)

.SameByte       ; восстановление X для расчёта следующего столбца
                LD A, E
                JR .Column
; -----------------------------------------
; коррекция уровня заполнения
; In:
;   A - исходный уровень s, диапазон 0..65
; Out:
;   A - скорректированный уровень, диапазон 0..65
; Corrupt:
;   HL, BC, AF
; Note:
;   v = clamp(153 * s - 1248, 0, 7488)
;   Result = floor((4 * v + min(v, 3328)) / 512)
; -----------------------------------------
.Correct        ; проверка нижней границы, значение v равно нулю при s < 9
                CP #09
                JR C, .CorrectZero                                              ; переход, если s < 9 и нужно вернуть ноль

                ; проверка верхней границы, значение v равно 7488 при s >= 58
                CP #3A
                JR NC, .CorrectFull                                             ; переход, если s >= 58 и нужно вернуть уровень 65

                ; сохранение исходного s в BC
                LD C, A
                LD B, #00

                ; расчёт 2s, максимальный промежуточный результат равен 114
                ADD A, A
                LD L, A
                LD H, B

                ; расчёт 16s из 2s
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL

                ; расчёт 17s = 16s + s
                ADD HL, BC

                ; сохранение 17s для последующего сложения
                LD C, L
                LD B, H

                ; расчёт 136s = 17s * 8
                ADD HL, HL  ; x2
                ADD HL, HL  ; x4
                ADD HL, HL  ; x8

                ; расчёт 153s = 136s + 17s
                ADD HL, BC

                ; расчёт v = 153s - 1248
                LD BC, #04E0
                ; OR A
                SBC HL, BC

                ; проверка части формулы min(v, 3328)
                LD A, H
                CP #0D
                JR C, .CorrectLow                                               ; переход, если v < 3328 и нужно рассчитать 5v

                ; расчёт числителя 4v + 3328 при v >= 3328
                ADD HL, HL  ; x2
                ADD HL, HL  ; x4
                LD BC, #0D00
                ADD HL, BC

.CorrectResult  ; деление числителя на 512
                ; floor(HL / 512) = H >> 1
                LD A, H
                SRL A
                RET

.CorrectLow     ; сохранение v для расчёта 5v = 4v + v
                LD B, H
                LD C, L

                ; расчёт числителя 5v при v < 3328
                ADD HL, HL  ; x2
                ADD HL, HL  ; x4
                ADD HL, BC  ; x5
                JR .CorrectResult                                               ; переход к общему делению результата на 512

.CorrectZero    ; установка полностью тёмного уровня
                XOR A
                RET

.CorrectFull    ; установка максимального доступного уровня 65
                LD A, #41
                RET

.Bayer8         ; исходные пороги Bayer 8x8, построчно
                DB  0, 32,  8, 40,  2, 34, 10, 42
                DB 48, 16, 56, 24, 50, 18, 58, 26
                DB 12, 44,  4, 36, 14, 46,  6, 38
                DB 60, 28, 52, 20, 62, 30, 54, 22
                DB  3, 35, 11, 43,  1, 33,  9, 41
                DB 51, 19, 59, 27, 49, 17, 57, 25
                DB 15, 47,  7, 39, 13, 45,  5, 37
                DB 63, 31, 55, 23, 61, 29, 53, 21

                display " - Bayer gradient generator:\t\t\t", /A, TG_BayerGradient, "\t= busy [ ", /D, $-TG_BayerGradient, " byte(s)  ]"
                endmodule

                endif ; ~ _TABLE_GENERATION_BAYER_GRADIENT_
