                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                ; переход к следующей строке спрайта
                INC L                                                           ; переход к последнему XOR-байту строки
                INC L                                                           ; переход к OR-байту следующей строки

                ; проверка конца спрайта по границе общего буфера
                JP NZ, .Row                                                  ; переход, если остались необработанные строки

                RET
; -----------------------------------------
; горизонтальное расширение маски спрайта, 4 знакоместа
; In:
;   HL  - адрес спрайта
;   D   - старший байт базового адреса таблицы расширения
;   DE' - адрес записи во временный буфер внешней маски
; Out:
; Corrupt:
;   HL, DE, BC, AF, DE'
; Note:
;   радиус внешнего расширения 1 пиксель
;   конец данных спрайта совпадает с границей 256 байт
; -----------------------------------------
Expand32        ; обработка строк спрайта
                EX DE, HL                                                       ; адрес спрайта в DE, адрес таблицы в HL

.Row            ; -----------------------------------------
                ; обработка первого OR-байта спрайта
                ; -----------------------------------------
                LD A, (DE)                                                      ; чтение OR-байта спрайта
                LD L, A                                                         ; индекс данных сдвига
                LD C, (HL)                                                      ; чтение данных сдвига 0
                INC H                                                           ; переход к части таблицы +1
                LD B, (HL)                                                      ; чтение данных сдвига +1

                ; -----------------------------------------
                ; обработка второго OR-байта спрайта
                ; -----------------------------------------
                INC E                                                           ; переход к XOR-байту спрайта
                INC E                                                           ; переход к следующему OR-байту спрайта
                LD A, (DE)                                                      ; чтение OR-байта спрайта
                LD L, A                                                         ; индекс данных сдвига
                INC H                                                           ; переход к части таблицы -1
                LD A, (HL)                                                      ; чтение данных сдвига -1
                OR C                                                            ; объединение данных для байта 1

                ; запись первого байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                DEC H                                                           ; переход к части таблицы +1
                LD C, (HL)                                                      ; чтение данных сдвига +1
                DEC H                                                           ; переход к части таблицы 0
                LD A, (HL)                                                      ; чтение данных сдвига 0
                OR B                                                            ; объединение данных для байта 2
                LD B, A

                ; -----------------------------------------
                ; обработка третьего OR-байта спрайта
                ; -----------------------------------------
                INC E                                                           ; переход к XOR-байту спрайта
                INC E                                                           ; переход к следующему OR-байту спрайта
                LD A, (DE)                                                      ; чтение OR-байта спрайта
                LD L, A                                                         ; индекс данных сдвига
                LD A, (HL)                                                      ; чтение данных сдвига 0
                OR C                                                            ; объединение данных для байта 3
                LD C, A
                INC H                                                           ; переход к части таблицы +1
                INC H                                                           ; переход к части таблицы -1
                LD A, (HL)                                                      ; чтение данных сдвига -1
                OR B                                                            ; объединение данных для байта 2

                ; запись второго байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                DEC H                                                           ; переход к части таблицы +1
                LD B, (HL)                                                      ; чтение данных сдвига +1

                ; -----------------------------------------
                ; обработка четвёртого OR-байта спрайта
                ; -----------------------------------------
                INC E                                                           ; переход к XOR-байту спрайта
                INC E                                                           ; переход к следующему OR-байту спрайта
                LD A, (DE)                                                      ; чтение OR-байта спрайта
                LD L, A                                                         ; индекс данных сдвига
                INC H                                                           ; переход к части таблицы -1
                LD A, (HL)                                                      ; чтение данных сдвига -1
                OR C                                                            ; объединение данных для байта 3

                ; запись третьего байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                DEC H                                                           ; переход к части таблицы +1
                DEC H                                                           ; переход к части таблицы 0
                LD A, (HL)                                                      ; чтение данных сдвига 0
                OR B                                                            ; объединение данных для байта 4

                ; запись четвёртого байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                ; переход к следующей строке спрайта
                INC E                                                           ; переход к последнему XOR-байту строки
                INC E                                                           ; переход к OR-байту следующей строки

