                module Radius_1
; -----------------------------------------
; горизонтальное расширение маски спрайта, 1 знакоместо
; In:
;   HL  - адрес спрайта
;   D   - старший байт базового адреса таблицы расширения
;   DE' - адрес записи во временный буфер внешней маски
; Out:
; Corrupt:
;   HL, DE, AF, DE'
; Note:
;   радиус внешнего расширения 1 пиксель
;   конец данных спрайта совпадает с границей 256 байт
; -----------------------------------------
Expand8         ; обработка строк спрайта

.Row            ; -----------------------------------------
                ; обработка первого OR-байта спрайта
                ; -----------------------------------------
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                LD A, (DE)                                                      ; чтение данных сдвига 0

                ; запись первого байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                ; переход к следующей строке спрайта
                INC L                                                           ; переход к последнему XOR-байту строки
                INC L                                                           ; переход к OR-байту следующей строки

                ; проверка конца спрайта по границе общего буфера
                JP NZ, .Row                                                   ; переход, если остались необработанные строки

                RET
; -----------------------------------------
; горизонтальное расширение маски спрайта, 2 знакоместа
; In:
;   HL  - адрес спрайта
;   D   - старший байт базового адреса таблицы расширения
;   DE' - адрес записи во временный буфер внешней маски
; Out:
; Corrupt:
;   HL, DE, BC, AF, DE'
; Note:
;   радиус внешнего расширения 1 пиксель
;   конец данных спрайта совпадает с границей 256 байт
; -----------------------------------------
Expand16        ; обработка строк спрайта
.Row            ; -----------------------------------------
                ; обработка первого OR-байта спрайта
                ; -----------------------------------------
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                LD A, (DE)                                                      ; чтение данных сдвига 0
                LD C, A
                INC D                                                           ; переход к части таблицы +1
                LD A, (DE)                                                      ; чтение данных сдвига +1
                LD B, A

                ; -----------------------------------------
                ; обработка второго OR-байта спрайта
                ; -----------------------------------------
                INC L                                                           ; переход к XOR-байту спрайта
                INC L                                                           ; переход к следующему OR-байту спрайта
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                INC D                                                           ; переход к части таблицы -1
                LD A, (DE)                                                      ; чтение данных сдвига -1
                OR C                                                            ; объединение данных для байта 1

                ; запись первого байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                DEC D                                                           ; переход к части таблицы +1
                DEC D                                                           ; переход к части таблицы 0
                LD A, (DE)                                                      ; чтение данных сдвига 0
                OR B                                                            ; объединение данных для байта 2

                ; запись второго байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                ; переход к следующей строке спрайта
                INC L                                                           ; переход к последнему XOR-байту строки
                INC L                                                           ; переход к OR-байту следующей строки

                ; проверка конца спрайта по границе общего буфера
                JP NZ, .Row                                                  ; переход, если остались необработанные строки

                RET
; -----------------------------------------
; горизонтальное расширение маски спрайта, 3 знакоместа
; In:
;   HL  - адрес спрайта
;   D   - старший байт базового адреса таблицы расширения
;   DE' - адрес записи во временный буфер внешней маски
; Out:
; Corrupt:
;   HL, DE, BC, AF, DE'
; Note:
;   радиус внешнего расширения 1 пиксель
;   конец данных спрайта совпадает с границей 256 байт
; -----------------------------------------
Expand24        ; обработка строк спрайта

.Row            ; -----------------------------------------
                ; обработка первого OR-байта спрайта
                ; -----------------------------------------
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                LD A, (DE)                                                      ; чтение данных сдвига 0
                LD C, A
                INC D                                                           ; переход к части таблицы +1
                LD A, (DE)                                                      ; чтение данных сдвига +1
                LD B, A

                ; -----------------------------------------
                ; обработка второго OR-байта спрайта
                ; -----------------------------------------
                INC L                                                           ; переход к XOR-байту спрайта
                INC L                                                           ; переход к следующему OR-байту спрайта
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                INC D                                                           ; переход к части таблицы -1
                LD A, (DE)                                                      ; чтение данных сдвига -1
                OR C                                                            ; объединение данных для байта 1

                ; запись первого байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

                DEC D                                                           ; переход к части таблицы +1
                LD A, (DE)                                                      ; чтение данных сдвига +1
                LD C, A
                DEC D                                                           ; переход к части таблицы 0
                LD A, (DE)                                                      ; чтение данных сдвига 0
                OR B                                                            ; объединение данных для байта 2
                LD B, A

                ; -----------------------------------------
                ; обработка третьего OR-байта спрайта
                ; -----------------------------------------
                INC L                                                           ; переход к XOR-байту спрайта
                INC L                                                           ; переход к следующему OR-байту спрайта
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                INC D                                                           ; переход к части таблицы +1
                INC D                                                           ; переход к части таблицы -1
                LD A, (DE)                                                      ; чтение данных сдвига -1
                OR B                                                            ; объединение данных для байта 2

                ; запись второго байта во временный буфер
                EXX
                LD (DE), A
                INC E                                                           ; следующий байт во временном буфере внешней маски
                EXX

