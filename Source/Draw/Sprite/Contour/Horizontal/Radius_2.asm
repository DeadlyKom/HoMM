                LD C, A
                INC D                                                           ; переход к части таблицы +1
                LD A, (DE)                                                      ; чтение данных сдвига +1
                LD B, A

                ; -----------------------------------------
                ; обработка второго OR-байта спрайта
                ; -----------------------------------------
                INC L                                                           ; переход к XOR-байту спрайта
                INC L                                                           ; переход к следующему OR-байту спрайта
                LD E, (HL)                                                      ; чтение OR-байта спрайта
                LD A, E                                                         ; исходный OR-байт для внешней маски
                EXX
