                ifndef _DRAW_SPRITE_CONTOUR_BOUNDS_
                define _DRAW_SPRITE_CONTOUR_BOUNDS_
; -----------------------------------------
; допустимое вертикальное окно текущей строки
; In:
;   A   - радиус окна
;   IXH - номер строки
;   IXL - размер спрайта по вертикали в пикселях
;   IYH - размер спрайта по горизонтали в знакоместах
; Out:
;   C   - отрицательное смещение к первой допустимой строке
;   A   - количество допустимых строк
; Corrupt:
;   C, AF, HL', B'
; Note:
; -----------------------------------------
Bounds:         EXX                                                             ; переход к размерам и номеру рабочей строки
                LD H, A                                                         ; радиус текущего окна

                ; проверка количества доступных строк сверху
                LD A, IXH                                                       ; расстояние от верхней границы
                CP H
                JR C, .Above                                                    ; переход, если верхняя граница ближе радиуса

                LD A, H                                                         ; полный радиус сверху
.Above          LD L, A                                                         ; допустимое количество строк сверху

                ; расчёт расстояния до нижней границы
                LD A, IXL                                                       ; размер спрайта по вертикали
                SUB IXH                                                         ; количество строк от текущей до конца
                DEC A                                                           ; расстояние до последней строки

                ; проверка количества доступных строк снизу
                CP H
                JR C, .Below                                                    ; переход, если нижняя граница ближе радиуса

                LD A, H                                                         ; полный радиус снизу
.Below          ADD A, L                                                        ; суммарное количество соседних строк
                INC A                                                           ; включение текущей строки в окно
                PUSH AF

                ; проверка отсутствия смещения от верхней строки
                LD A, L                                                         ; количество строк для смещения
                OR A
                JR Z, .Offset                                                   ; переход, если смещение вверх равно нулю

                ; расчёт индекса таблицы по количеству строк и размеру спрайта по горизонтали
                DEC A
                ADD A, A    ; x2
                ADD A, A    ; x4
                LD B, A                                                         ; поле количества строк минус один
                LD A, IYH
                DEC A
                OR B
                LD L, A
                LD H, HIGH Adr.MultiplySprite

                ; расчёт смещения вверх без учёта XOR-байтов
                LD A, (HL)                                                      ; размер пар OR/XOR для выбранных строк и размера спрайта по горизонтали
                SRL A                                                           ; размер строк рабочей маски
.Offset         NEG

                ; возврат смещения и количества строк
                EXX
                LD C, A
                POP AF
                RET

                endif ; ~ _DRAW_SPRITE_CONTOUR_BOUNDS_
