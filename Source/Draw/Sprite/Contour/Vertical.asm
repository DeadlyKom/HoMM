                ifndef _DRAW_SPRITE_CONTOUR_VERTICAL_
                define _DRAW_SPRITE_CONTOUR_VERTICAL_
; -----------------------------------------
; вертикальное расширение и запись контура только в OR
; In:
;   HL  - адрес спрайта
;   DE  - адрес внутренней маски
;   DE' - размер спрайта по горизонтали в знакоместах
;   IXH - номер строки
;   IXL - размер спрайта по вертикали в пикселях
;   IYH - размер спрайта по горизонтали в знакоместах
; Out:
; Corrupt:
;   L, E, BC, AF, HL', B', AF', IXH
; Note:
; -----------------------------------------
Vertical:       ; обработка строк маски спрайта
.Row            ; подготовка внешнего окна текущей строки
.Outer          EQU $+1
                LD A, #00
                CALL Bounds

                ; расчёт перехода к нужному числу строк из семи
                ADD A, A    ; x2
                XOR %00001110
                LD (.OuterJump), A

                ; подготовка смещения к первой строке окна
                LD A, C
                LD (.OuterOffset), A

                ; переход к внутреннему окну или сразу к обработке столбцов
.Window         EQU $+1
                JP #0000

.InnerWindow    ; подготовка внутреннего окна для фаз 1 и 2
.Inner          EQU $+1
                LD A, #00
                CALL Bounds

                ; расчёт перехода к нужному числу строк из семи
                ADD A, A    ; x2
                XOR %00001110
                LD (ScanInner.Jump), A

                ; подготовка смещения к первой строке окна
                LD A, C
                LD (ScanInner.Offset), A

.Columns        LD B, IYH                                                       ; число столбцов строки
.Column         ; подготовка адреса текущего байта внешней маски
                PUSH DE
                EXX
                POP HL

                ; расчёт адреса первой строки внешнего окна
.OuterOffset    EQU $+1
                LD A, #00
                ADD A, L
                LD L, A
                SET 7, L                                                        ; переход к внешней маске

                XOR A
.OuterJump      EQU $+1
                JR $

                CONTOUR_V_SCAN
                EXX
.Apply          EQU $+1                                                         ; добавление контура выбранным обработчиком
                CALL #0000

                INC E                                                           ; следующий столбец маски
                INC L                                                           ; пропуск OR-байта
                INC L                                                           ; пропуск XOR-байта

                DJNZ .Column

                ; проверка конца спрайта по границе общего буфера
                RET Z                                                           ; выход, если обработана последняя строка спрайта

                ; подготовка номера следующей строки
                INC IXH
                LD A, IXH

                ; проверка достижения строки с уже подготовленными полными окнами
.MiddleStart    EQU $+1
                CP #00
                JP C, .Row                                                      ; переход, если верхняя граница ещё изменяет окна

                ; проверка входа в нижнюю границу спрайта
.MiddleEnd      EQU $+1
                CP #00
                JP C, .Columns                                                  ; переход, если полные окна можно использовать повторно
                JP .Row
; -----------------------------------------
; объединение внутреннего вертикального окна
; In:
;   DE  - адрес текущего байта внутренней маски
;   DE' - размер спрайта по горизонтали в знакоместах
; Out:
;   A   - внутреннее расширение
; Corrupt:
;   AF, HL'
; -----------------------------------------
ScanInner:      ; подготовка адреса текущего байта маски
                PUSH DE
                EXX
                POP HL

                ; расчёт адреса первой допустимой строки окна
.Offset         EQU $+1
                LD A, #00
                ADD A, L
                LD L, A
                XOR A
.Jump           EQU $+1
                JR $
                CONTOUR_V_SCAN
                EXX
                RET
; -----------------------------------------
; добавление внешнего расширения первой фазы
; In:
;   A   - внешнее расширение
;   HL  - адрес исходного OR-байта
; Out:
; Corrupt:
;   AF
; -----------------------------------------
ApplySimple:    OR (HL)
                LD (HL), A                                                      ; запись OR-байта
                RET
; -----------------------------------------
; добавление кольца между двумя вложенными расширениями
; In:
;   A   - внешнее расширение
;   HL  - адрес исходного OR-байта
; Out:
; Corrupt:
;   C, AF, HL', AF'
; Note:
; -----------------------------------------
ApplyRing:      EX AF, AF'                                                      ; сохранение внешнего расширения
                CALL ScanInner                                                  ; внутреннее вертикальное расширение
                LD C, A                                                         ; внутренняя маска текущего байта
                EX AF, AF'

                ; выделение кольца, внутренняя маска является подмножеством внешней
                ; Outer - Inner эквивалентно Outer AND NOT Inner
                SUB C                                                           ; кольцо между вложенными расширениями
                OR (HL)
                LD (HL), A                                                      ; запись OR-байта
                RET

                endif ; ~ _DRAW_SPRITE_CONTOUR_VERTICAL_
