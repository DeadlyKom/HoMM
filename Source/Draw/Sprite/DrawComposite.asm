
                ifndef _DRAW_SPRITE_DRAW_COMPOSITE_
                define _DRAW_SPRITE_DRAW_COMPOSITE_
; -----------------------------------------
; отображение композитного спрайта
; In:
;   HL - адрес на структуру FSpritesRef
;       ; -----------------------------------------
;       ;      7    6    5    4    3    2    1    0
;       ;   +----+----+----+----+----+----+----+----+
;       ;   | 0  | 0  | N5 | N4 | N3 | N2 | N1 | N0 |
;       ;   +----+----+----+----+----+----+----+----+
;       ;
;       ;   N5-N0   [5..0]      - количество спрайтов
;       ; -----------------------------------------
;   E  - хранит значение FSpritesRef.Num (все флаги обнулены)
;   A  - счётчик анимации
; Out:
; Corrupt:
; Node:
; -----------------------------------------
DrawComposite:  ; сохранение счётчика, от которого будет отталкиватьяс выбор анимации
                LD (.InputCounter), A

                ; переключение на страницу расположения списка FSpritesRef
                INC L                                                           ; пропуск FSpritesRef.Num

                ; чтение страницы расположения данных о структурах
                LD C, (HL)                                                      ; FSpritesRef.Data.Page
                INC L

                ; чтение адреса расположения массива структур
                LD A, (HL)
                INC L
                LD H, (HL)
                LD L, A

                LD B, E                                                         ; количество спрайтов

.DrawLoop       PUSH BC

                LD A, C
                SET_PAGE_A                                                      ; установка страницы спрайта

                ; HL - адрес структуры FSprite/FSpritesRef
                BIT SPRITE_REF_BIT, (HL)
                JR Z, .DrawSprite                                               ; спрайт является простым спрайтом (FSprite)

                ; -----------------------------------------
                ; спрайт имеет анимации, необходимо выбрать анимацию
                ; -----------------------------------------

                ; получение количества анимаций в списке 
                LD A, (HL)
                AND ~(SPRITE_REF | SPRITE_CS)
                LD E, A

                ; -----------------------------------------
                ; деление D на E
                ; In:
                ;   D - делимое
                ;   E - делитель
                ; Out:
                ;   D - результат деления   (D / E)
                ;   A - остаток             (D % E)
                ; Corrupt:
                ;   D, AF
                ; Note:
                ;   https://www.smspower.org/Development/DivMod
                ;   количество кадров анимации желательно задавать степенью двойки,
                ;   иначе при переполнении FTick.Objects может нарушиться последовательность кадров
                ;
                ;   ограничение не является блокирующим: переполнение происходит один раз в 256 тиков объектов
                ;   период = 256 * (DURATION.OBJECT_TICK + 1) / 50 секунд
                ;   при текущем DURATION.OBJECT_TICK = #08 - примерно раз в 46 секунд
                ; -----------------------------------------
.InputCounter   EQU $+1
                LD D, #00
                CALL Math.Div8x8                                                ; mod
                SCF                                                             ; указываем на использование FSpritesRef,
                                                                                ; необходимо выбрать спрайт
.DrawSprite     ; копирование структуры
                SPRITE_DE SPRITE_TEMP_IDX
                rept FSprite
                LDI
                endr
                PUSH HL
                SPRITE_HL SPRITE_TEMP_IDX
                
                ; -----------------------------------------
                ;   HL - адрес спрайта FSprite/FSpritesRef
                ;   флаг переполнения указывает на структуру FSpritesRef в регистровой паре HL,
                ;   a в аккумуляторе хранится индекс спрайта
                ; Out:
                ; Corrupt:
                ; Note:
                ; -----------------------------------------

                ; ToDo: объединять GameState.SpriteBound всех фактически нарисованных частей
                ; - каждый рисующий путь перезаписывает эту область, поэтому объектный
                ;    Draw.StoreBound сохраняет границы только последней нарисованной части
                ; - возможны неполный перенос экранных блоков и остатки при движении или удалении
                ; - учесть полностью отсечённые части и случай, когда не нарисована ни одна часть
                ; - учитывать общий результат отсечения, а не результат только последней части
                ;    флаг переполнения установлен, если видна хотя бы одна часть
                ;    флаг переполнения сброшен, если все части полностью отсечены
                ; - сохранить старую область объекта для invalidation
                ; - при необходимости нового буфера его размещение согласовать с пользователем
                ; - в просмотренных ресурсах активные composite не найдены, артефакт не подтверждён
                CALL Draw.SpriteClipping
                POP HL

                POP BC
                DJNZ .DrawLoop

                RET
                display " - Draw function 'Composite':\t\t\t\t", /A, DrawComposite, "\t= busy [ ", /D, $-DrawComposite, " byte(s)  ]"

                endif ; ~ _DRAW_SPRITE_DRAW_COMPOSITE_
