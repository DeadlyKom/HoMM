
                ifndef _DRAW_FONT_GET_WIDTH_
                define _DRAW_FONT_GET_WIDTH_
; -----------------------------------------
; расчёт ширины строки в пикселях с учётом кернинга
; In:
;   DE - адрес строки в общей памяти
; Out:
;   E  - ширина строки в пикселях
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ необходимо включить страницу шрифта
; -----------------------------------------
GetWidth:       ; получение адреса строки из DE
                EX DE, HL

                ; сброс ширины строки и профиля предыдущего глифа
                LD DE, #0000

.Loop           ; проверка завершения строки
                LD A, (HL)
                OR A
                JR Z, .Finish                                                   ; переход, если строка закончилась

                ; сохранение адреса следующего символа
                INC HL
                PUSH HL

                ; расчёт адреса относительного смещения глифа в таблице
                SUB #20
                ADD A, LOW (Adr.Font >> 1)
                LD L, A
                ADC A, HIGH (Adr.Font >> 1)
                SUB L
                LD H, A
                ADD HL, HL  ; x2

                ; получение адреса глифа из относительного смещения
                LD C, (HL)
                INC HL
                LD B, (HL)
                ADD HL, BC

                ; чтение высоты и ширины глифа
                LD A, (HL)
                INC HL
                LD C, (HL)

                ; проверка отсутствия спрайта символа
                OR A
                JR Z, .Blank                                                    ; переход, если глиф не содержит спрайт

                ; чтение профиля перекрытия текущего глифа
                INC HL
                LD B, (HL)

                ; расчёт суммы верхних свободных областей соседних глифов
                LD A, D
                RRCA
                RRCA
                AND %00000011
                LD H, A
                LD A, B
                RLCA
                RLCA
                AND %00000011
                ADD A, H
                LD H, A

                ; расчёт суммы нижних свободных областей соседних глифов
                LD A, D
                AND %00000011
                LD L, A
                LD A, B
                RRCA
                RRCA
                RRCA
                RRCA
                AND %00000011
                ADD A, L

                ; выбор меньшего перекрытия для верхней и нижней областей
                CP H
                JR C, .Overlap                                                  ; переход, если нижнее перекрытие меньше верхнего

                LD A, H

.Overlap        ; уменьшение ширины строки на перекрытие соседних глифов
                NEG
                ADD A, E
                LD E, A
                LD D, B                                                         ; D - профиль предыдущего глифа
                JR .Advance

.Blank          ; сброс профиля перекрытия для символа без спрайта
                LD D, #00

.Advance        ; расчёт позиции после текущего символа по правилу вывода шрифта
                LD A, C
                ADD A, E
                DEC A
                LD E, A
                POP HL
                JR .Loop

.Finish         ; проверка наличия ширины перед учётом последнего пикселя
                LD A, E
                OR A
                RET Z                                                           ; выход, если строка не занимает пикселей

                INC E
                RET

                endif ; ~_DRAW_FONT_GET_WIDTH_
