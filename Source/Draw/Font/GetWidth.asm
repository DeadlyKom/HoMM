
                ifndef _DRAW_FONT_GET_WIDTH_
                define _DRAW_FONT_GET_WIDTH_
; -----------------------------------------
; расчёт ширины строки в пикселях с учётом кернинга
; In:
;   DE - адрес строки в общей памяти
; Out:
;   E  - ширина строки в пикселях
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ необходимо включить страницу шрифта
; -----------------------------------------
GetWidth:       ; получение адреса строки и сброс ширины с профилем предыдущего глифа
                EX DE, HL
                LD DE, #0000

.Loop           ; проверка завершения строки
                LD A, (HL)
                OR A
                JR Z, .Finish                                                   ; переход, если строка закончилась

                ; сохранение адреса следующего символа
                INC HL
                PUSH HL

                ; расчёт адреса относительного смещения глифа в таблице
                SUB #20
                LD L, A
                LD H, HIGH (Adr.Font >> 1)
                ADD HL, HL  ; x2

                ; получение адреса глифа из относительного смещения
                LD C, (HL)
                INC HL
                LD B, (HL)
                ADD HL, BC

                ; чтение высоты и ширины глифа
                LD A, (HL)
                INC HL                                                          ; переход к полю FFontGlyph.Width
                LD C, (HL)

                ; проверка отсутствия спрайта символа
                OR A
                JR Z, .Blank                                                    ; переход, если глиф не содержит спрайт

                ; чтение профиля перекрытия текущего глифа
                INC HL                                                          ; переход к полю FFontGlyph.SpacingProfile
                LD B, (HL)

                ; проверка отсутствия нижнего перекрытия соседних глифов
                LD A, B
                XOR D
                AND %00110000
                XOR D
                AND %00110011
                JR Z, .Overlap                                                  ; переход, если нижнее перекрытие равно нулю

                ; расчёт суммы нижних свободных областей из упакованной пары
                LD L, A
                RRCA
                RRCA
                RRCA
                RRCA
                ADD A, L
                AND %00000111
                LD H, A                                                         ; H - нижнее перекрытие в пикселях

                ; расчёт суммы верхних свободных областей соседних глифов
                LD A, D
                RRCA
                RRCA
                AND %00000011
                LD L, A
                LD A, B
                RLCA
                RLCA
                AND %00000011
                ADD A, L

                ; выбор меньшего перекрытия для верхней и нижней областей
                CP H
                JR C, .Overlap                                                  ; переход, если верхнее перекрытие меньше нижнего

                LD A, H

.Overlap        ; сохранение профиля текущего глифа для следующего символа
                LD D, B

.Advance        ; накопление ширины с вычетом перекрытия и межсимвольного пикселя
                CPL
                ADD A, C
                ADD A, E
                LD E, A

                ; восстановление адреса следующего символа
                POP HL
                JP .Loop

.Blank          ; сброс профиля после символа без спрайта
                LD D, A
                JP .Advance

.Finish         ; проверка наличия ширины перед учётом последнего пикселя
                LD A, E
                OR A
                RET Z                                                           ; выход, если строка не занимает пикселей

                INC E
                RET

                endif ; ~_DRAW_FONT_GET_WIDTH_
