
                ifndef _DRAW_FONT_COLOR_GLYPH_
                define _DRAW_FONT_COLOR_GLYPH_
; -----------------------------------------
; окраска знакомест глифа и отображение его спрайта
; In:
;   HL - адрес спрайта OR & XOR
;   DE - положение глифа в пикселях (D - y, E - x)
;   GameState.FontSize - ширина и высота глифа в пикселях
; Out:
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF', IX, IY
; Note:
;   ℹ️ необходимо включить страницу шрифта
;   атрибут устанавливается методом Draw.ColorString
; -----------------------------------------
Draw.Color.Glyph:; сохранение параметров для последующего отображения глифа
                PUSH HL
                PUSH DE

                ; проверка пиксельного сдвига глифа относительно знакоместа
                LD A, E
                AND #07
                LD B, A
                LD A, #FF
                JR Z, .MasksReady                                               ; переход, если глиф выровнен по знакоместу

                ; расчёт адреса младшей части сдвига байта #FF в существующей таблице
                PUSH HL                                                         ; сохранение адреса спрайта на время чтения таблицы
                LD A, B
                ADD A, A    ; x2
                NEG
                ADD A, (HIGH Adr.ShiftTable) + 15
                LD H, A
                LD L, #FF
                LD A, (HL)                                                      ; чтение маски левой части байта
                POP HL                                                          ; восстановление адреса спрайта

.MasksReady     ; сохранение масок левой и правой частей байта
                LD (.LeftMask), A
                CPL
                LD (.RightMask), A

                ; расчёт количества столбцов спрайта в знакоместах
                LD A, (GameState.FontSize + FSize.Width)
                DEC A
                SRL A
                SRL A
                SRL A
                INC A
                LD (.Columns), A
                LD C, A                                                         ; C - количество столбцов спрайта

                ; расчёт смещения до начала следующего ряда атрибутов
                LD A, #20
                SUB C
                LD (.NextAttrStep), A

                ; расчёт шага между XOR-байтами соседних пиксельных строк
                LD A, C
                ADD A, A    ; x2
                LD (.Stride), A

                ; расчёт смещения от конца последнего столбца к началу следующего ряда спрайта
                SUB #02
                LD (.SourceBack), A

                ; чтение полной высоты глифа
                LD A, (GameState.FontSize + FSize.Height)
                LD B, A                                                         ; B - количество оставшихся пиксельных строк

                ; расчёт количества пиксельных строк до следующего ряда знакомест
                LD A, D
                CPL
                AND #07
                INC A
                LD C, A

                ; проверка высоты первого ряда относительно оставшейся высоты глифа
                LD A, B
                CP C
                JR C, $+3                                                       ; переход, если глиф заканчивается до следующего ряда знакомест
                LD A, C
                LD C, A                                                         ; сохранение количества пиксельных строк первого ряда

                ; расчёт смещения входа в развёрнутый цикл, по два байта на строку
                NEG
                ADD A, #08
                ADD A, A                                                        ; x2
                LD (.Rows), A

                ; расчёт пиксельного адреса начала глифа по экранным таблицам
                PUSH HL
                LD H, HIGH Adr.ScrAdrTable
                LD L, D
                LD A, (HL)
                INC H                                                           ; переход к таблице старших байтов пиксельного адреса
                LD D, (HL)
                INC H                                                           ; переход к таблице горизонтальных смещений
                LD L, E
                OR (HL)
                LD E, A

                ; преобразование старшего байта пиксельного адреса в адрес атрибутов
                LD L, D
                LD H, HIGH Adr.ScrAttrAdrTable
                LD D, (HL)

                ; выбор основного или теневого экрана по текущему состоянию вывода
                LD A, (GameState.Screen)
                XOR D
                AND #80
                XOR D
                LD D, A
                POP HL

                ; сохранение счётчиков и адреса атрибутов в альтернативном банке регистров
                INC HL                                                          ; переход к XOR-байту первого столбца
                PUSH HL
                EX DE, HL
                EXX
                POP HL

                ; установка шага между XOR-байтами соседних пиксельных строк
.Stride         EQU $+1
                LD DE, #0000

                ; установка атрибута правого знакоместа из общего параметра цвета
                LD A, (.Attribute)
                LD (.RightAttribute), A

.Group          ; подготовка обхода столбцов текущего ряда знакомест
.Columns        EQU $+1
                LD C, #00

.Column         ; сохранение адреса XOR-байта начала столбца
                PUSH HL

                XOR A                                                           ; сброс накопленных пикселей столбца
.Rows           EQU $+1
                JR .Read                                                        ; вход в развёрнутый цикл согласно количеству пиксельных строк ряда

                ; -----------------------------------------
.Read           ; объединение XOR-байтов столбца в пределах одного ряда знакомест
                rept 8
                OR (HL)
                ADD HL, DE
                endr
                ; -----------------------------------------

                ; переход к счётчикам высоты и адресу атрибутов
                EXX
                LD D, A                                                         ; D - объединённые пиксели столбца

                ; проверка пикселей в левом экранном знакоместе
.LeftMask       EQU $+1
                AND #FF
                JR Z, .SkipLeft                                                 ; переход, если в левое знакоместо не попали пиксели глифа

                ; окраска левого знакоместа заданным атрибутом
.Attribute      EQU $+1
                LD (HL), #00

.SkipLeft       ; проверка пикселей в соседнем экранном знакоместе
                INC HL
                LD A, D
.RightMask      EQU $+1
                AND #00
                JR Z, .SkipRight                                                ; переход, если в соседнее знакоместо не попали пиксели глифа

                ; окраска соседнего знакоместа заданным атрибутом
.RightAttribute EQU $+1
                LD (HL), #00

.SkipRight      ; проверка оставшихся столбцов текущего ряда
                EXX
                DEC C
                JR Z, .LastColumn                                               ; переход, если все столбцы текущего ряда обработаны

                ; подготовка адреса XOR-байта следующего столбца
                POP HL
                INC HL                                                          ; переход к OR-маске следующего столбца
                INC HL                                                          ; переход к XOR-байту следующего столбца
                JP .Column

.LastColumn     POP AF                                                          ; удаление сохранённого адреса последнего столбца из стека

                ; расчёт адреса XOR-байта начала следующего ряда спрайта
                LD A, L
.SourceBack     EQU $+1
                SUB #00
                LD L, A
                JR NC, .SourceReady                                             ; переход, если младший байт адреса вычислен без заёма

                DEC H                                                           ; коррекция старшего байта адреса после заёма

.SourceReady    ; проверка оставшейся высоты глифа
                EXX
                LD A, B
                SUB C
                LD B, A
                JR Z, .Finish                                                   ; переход, если все пиксельные строки глифа обработаны

                ; расчёт адреса начала следующего ряда атрибутов
                LD A, L
.NextAttrStep   EQU $+1
                ADD A, #00
                LD L, A
                JR NC, .NextGroup                                               ; переход, если следующий ряд находится в той же странице атрибутов

                INC H                                                           ; переход к следующей странице атрибутов

.NextGroup      ; проверка высоты следующего ряда относительно восьми пиксельных строк
                LD A, B
                CP #08
                JR C, .GroupSizeReady                                           ; переход, если осталось менее восьми пиксельных строк

                LD A, #08

.GroupSizeReady ; сохранение количества пиксельных строк следующего ряда
                LD C, A

                ; расчёт смещения входа в развёрнутый цикл, по два байта на строку
                NEG
                ADD A, #08
                ADD A, A    ; x2
                LD (.Rows), A
                EXX
                JP .Group

.Finish         ; восстановление параметров и отображение глифа обычным методом
                EXX
                POP DE
                POP HL
                ; JP Draw.Glyph                                                   ; inclide идёт следом 

                endif ; ~_DRAW_FONT_COLOR_GLYPH_
