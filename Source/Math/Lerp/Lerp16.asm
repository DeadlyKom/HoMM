
                ifndef _MATH_LERP_16_
                define _MATH_LERP_16_

                module Math
; -----------------------------------------
; линейная интерполяция двух 16-битных беззнаковых значений
; In:
;   HL - начальное значение
;   DE - конечное значение
;   A  - коэффициент интерполяции [0..255]
; Out:
;   HL - результат интерполяции
; Corrupt:
;   DE, BC, AF
; Note:
;   смещение равно abs(конец - начало) * коэффициент / 255
;   дробная часть смещения отбрасывается
;   при коэффициенте 0 возвращается начальное значение
;   при коэффициенте 255 возвращается конечное значение
; -----------------------------------------
Lerp16:         ; сохранение коэффициента и начального значения
                LD C, A
                PUSH HL

                ; расчёт разности начального и конечного значений
                OR A
                SBC HL, DE
                PUSH AF

                ; проверка знака разности
                JR NC, .Scale                                                   ; переход, если начальное значение не меньше конечного

                ; расчёт модуля отрицательной разности
                XOR A
                SUB L
                LD L, A
                SBC A, A
                SUB H
                LD H, A

.Scale          ; подготовка расстояния и коэффициента
                EX DE, HL
                LD A, C

                ; расчёт 24-битного произведения расстояния на коэффициент
                CALL Math.Mul16x8_24

                ; разделение произведения на старшее слово и младший байт
                LD E, L
                LD L, H
                LD H, A
                PUSH HL

                ; расчёт суммы старшего слова и младшего байта
                LD D, #00
                ADD HL, DE

                ; расчёт частного от деления суммы на 255
                LD E, H
                LD A, H
                ADD A, L

                ; проверка превышения порога коррекции частного
                JR C, .Round                                                    ; переход, если сумма байтов больше 255

                ; проверка достижения порога коррекции частного
                CP #FF
                JR NZ, .Result                                                  ; переход, если сумма байтов меньше 255

.Round          ; увеличение частного с учётом переноса в старший байт
                INC DE

.Result         ; расчёт полного частного от деления произведения на 255
                POP HL
                ADD HL, DE

                ; восстановление начального значения и направления
                EX DE, HL
                POP AF
                POP HL

                ; проверка направления интерполяции
                JR C, .Add                                                      ; переход, если конечное значение больше начального

                ; расчёт координаты при уменьшении значения
                OR A
                SBC HL, DE
                RET

.Add            ; расчёт координаты при увеличении значения
                ADD HL, DE
                RET

                display " - Lerp 16:\t\t\t\t\t\t", /A, Lerp16, "\t= busy [ ", /D, $-Lerp16, " byte(s)  ]"
                endmodule

                endif ; ~_MATH_LERP_16_
