
                ifndef _UTILITIES_GET_LENGTH_STRING_
                define _UTILITIES_GET_LENGTH_STRING_
; -----------------------------------------
; определение длины строки с учётом завершающего нуля
; In:
;   HL - адрес строки
; Out:
;   BC - длина строки в байтах, включая завершающий ноль
; Corrupt:
;   BC, AF
; Note:
;   ℹ️ код расположен в "общей памяти"
;   адрес исходной строки в HL сохраняется
; -----------------------------------------
GetLength:      ; сохранение адреса начала строки
                PUSH HL

                ; подготовка нулевого символа и счётчика длины строки
                XOR A
                LD B, A
                LD C, A

.Loop           ; определение завершающего нуля с накоплением отрицательной длины
                CPI
                JR NZ, .Loop                                                    ; переход, если завершающий ноль ещё не найден

                ; преобразование отрицательного счётчика в длину строки
                SUB C
                LD C, A
                SBC A, A
                SUB B
                LD B, A

                ; восстановление адреса исходной строки
                POP HL
                RET

                endif ; ~_UTILITIES_GET_LENGTH_STRING_
