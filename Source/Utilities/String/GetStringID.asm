
                ifndef _UTILITIES_STRING_GET_STRING_ID_
                define _UTILITIES_STRING_GET_STRING_ID_
; -----------------------------------------
; получение адреса строки по индексу (без таблицы адресов)
; In:
;   HL - адрес массива строк с нулевым окончанием
;   A  - индекс строки, начиная с нуля
; Out:
;   HL - адрес строки с указанным индексом
; Corrupt:
;   HL, D, BC, AF
; Note:
;   ℹ️ код расположен в "общей памяти"
;   строки размещены последовательно, каждая завершается нулём
; -----------------------------------------
GetStringID:    ; проверка индекса первой строки
                OR A
                RET Z                                                           ; выход, если требуется первая строка массива

                ; расчёт количества строк до завершающего нуля выбранной строки
                INC A
                LD D, A
                XOR A

.Loop           ; подготовка отрицательного счётчика длины очередной строки
                LD B, A
                LD C, A

.WordLoop       ; определение конца очередной строки
                CPI
                JR NZ, .WordLoop                                                ; переход, если завершающий ноль ещё не найден

                ; проверка достижения конца выбранной строки
                DEC D
                JR NZ, .Loop                                                    ; переход, если конец выбранной строки ещё не достигнут

                ; расчёт адреса начала выбранной строки по отрицательному счётчику длины
                ADD HL, BC
                RET

                endif ; ~_UTILITIES_STRING_GET_STRING_ID_
