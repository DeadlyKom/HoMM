
                ifndef _UTILITIES_STRING_COPY_
                define _UTILITIES_STRING_COPY_
; -----------------------------------------
; копирование строки
; In:
;   HL - адрес исходной строки с нулевым окончанием
;   DE - адрес буфера назначения
; Out:
;   HL - адрес байта после завершающего нуля исходной строки
;   DE - адрес свободного байта после скопированного завершающего нуля
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в "общей памяти"
; -----------------------------------------
Copy:           ; копирование символа
                LD A, (HL)
                LDI

                ; проверка завершения скопированной строки
                OR A
                RET Z                                                           ; выход, если скопирован завершающий ноль
                JR Copy

                endif ; ~_UTILITIES_STRING_COPY_
