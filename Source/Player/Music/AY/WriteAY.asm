
                ifndef _PLAYER_MUSIC_AY_WRITEAY_
                define _PLAYER_MUSIC_AY_WRITEAY_
; -----------------------------------------
; запись буфера в регистры AY начиная с R0
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   вход из Play, исполнение продолжается через SetRegisters
; -----------------------------------------
WriteAY:        XOR A
; -----------------------------------------
; запись буфера в регистры AY R0–R13
; In:
;   A - начальный номер регистра AY (R0-R13)
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   регистры R0–R12 записываются каждый тик
;   установленный бит 7 в байте R13 сохраняет текущую форму огибающей
; -----------------------------------------
SetRegisters:   ; подготовка портов AY и указателя на буфер
                LD DE, AY.PORTS_HIGH                                            ; D - старший байт порта выбора регистра, E - порта данных
                LD BC, AY.PORT_CTRL                                             ; порт выбора регистра AY
                LD HL, PlayerState.AYRegisters

                ; выбор регистра и запись его значения через порт данных AY
.Loop           OUT (C), A
                LD B, E
                OUTI
                LD B, D
                INC A

                ; проверка, дошла ли запись до регистра формы огибающей
                CP AY.R13                                                       ; номер регистра формы огибающей
                JR NZ, .Loop                                                    ; переход, если остались регистры перед регистром формы огибающей

                ; -----------------------------------------
                ; обновление формы огибающей
                ; -----------------------------------------
                ; выбор R13 и чтение его значения из буфера
                OUT (C), A
                LD A, (HL)

                ; проверка признака сохранения текущей формы огибающей
                AND A
                RET M                                                           ; выход, если форма огибающей в этом тике не менялась

                ; запись новой формы огибающей через порт данных AY
                LD B, E
                OUT (C), A
                RET

                endif ; ~ _PLAYER_MUSIC_AY_WRITEAY_
