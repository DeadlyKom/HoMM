
                ifndef _PLAYER_MUSIC_AY_PLAY_
                define _PLAYER_MUSIC_AY_PLAY_
; -----------------------------------------
; один тик проигрывания
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF, AF', IX
; Note:
;   модуль подготовлен через Initialize, вызов из прерывания с частотой 50 Гц
;   при чтении потоков и расчёте каналов SP временно указывает на данные
; -----------------------------------------
Play:           ; -----------------------------------------
                ; подготовка регистров на текущий тик
                ; -----------------------------------------
                ; обнуление суммарной поправки огибающей и микшера перед расчётом трёх каналов
                XOR A
                LD (.EnvAdjust), A
                LD (PlayerState.AYRegisters + Mixer), A

                ; #FF в R13 сохраняет текущую форму огибающей, пока команда PT3 не задаст новую
                DEC A
                LD (PlayerState.AYRegisters + EnvTp), A

                ; -----------------------------------------
                ; проверка задержки перед чтением строки
                ; -----------------------------------------
                ; между строками паттерн не читается, но орнаменты, сэмплы и эффекты продолжают работать
                LD HL, PlayerState.TickCounter
                DEC (HL)
                JR NZ, .RenderTick                                              ; переход, если до следующей строки паттерна остались тики

                ; -----------------------------------------
                ; проверка строки и конца паттерна канала A
                ; -----------------------------------------
                ; счётчик канала задаёт, сколько строк пропустить до следующей команды
                LD HL, PlayerState.ChanA + FPT3Channel.RowTicks
                DEC (HL)
                JR NZ, .CheckChannelB                                           ; переход, если канал A ещё пропускает строки

                ; чтение следующего байта канала A, ноль в начале строки завершает текущий паттерн
.PatternPtrA    EQU $+1                                                         ; операнд с адресом следующей команды паттерна канала A
                LD BC, #0000
                LD A, (BC)                                                      ; первый байт команды, ноль завершает поток канала A
                AND A
                JR NZ, .DecodeChannelA                                          ; переход, если поток паттерна канала A ещё не закончился

                ; -----------------------------------------
                ; выбор позиции в списке модуля
                ; -----------------------------------------
                ; сброс базового шума при смене паттерна, A уже равен нулю после проверки конца потока
                ; D остаётся нулём до удвоения индекса слова в таблице потоков
                LD D, A
                LD (PlayerState.NoiseBase), A

                ; чтение следующей записи списка позиций, #FF завершает список
                LD HL, (PositionPtr)
                INC HL
                LD A, (HL)
                INC A
                JR NZ, .SetPosition                                             ; переход, если запись позиции содержит номер паттерна

                ; -----------------------------------------
                ; обработка конца списка позиций
                ; In:
                ; Out:
                ;   в Setup установлен признак достижения конца списка позиций
                ; Corrupt:
                ;   HL, AF при возврате в Play
                ; Note:
                ;   если повтор разрешён, Play продолжает с позиции зацикливания
                ;   при запрете повтора CheckLoop снимает адрес возврата и завершает тик через Mute
                ; -----------------------------------------
                CALL CheckLoop
.LoopPosPtr     EQU $+1                                                         ; операнд с адресом позиции зацикливания
                LD HL, #0000
                LD A, (HL)
                INC A

                ; -----------------------------------------
                ; получение адресов потоков каналов A, B и C
                ; -----------------------------------------
.SetPosition    ; сохранение адреса выбранной позиции
                LD (PositionPtr), HL

                ; расчёт смещения первого слова в таблице потоков, два байта на запись
                DEC A                                                           ; восстановление индекса слова после проверки #FF
                ADD A, A    ; x2
                LD E, A
                RL D                                                            ; перенос от удвоения становится старшим битом смещения
.PatternTable   EQU $+1                                                         ; операнд с адресом таблицы смещений потоков паттернов
                LD HL, #0000
                ADD HL, DE
                LD DE, (RowCommands.ModuleBase)

                ; временный стек читает три слова подряд из таблицы паттернов
                ; к каждому смещению прибавляется база модуля, адрес A остаётся в BC, адреса B и C сохраняются
                LD (.ContainerSP), SP
                LD SP, HL
                POP HL
                ADD HL, DE
                LD B, H
                LD C, L
                POP HL
                ADD HL, DE
                LD (.PatternPtrB), HL
                POP HL
                ADD HL, DE
                LD (.PatternPtrC), HL
.ContainerSP    EQU $+1
                LD SP, #0000                                                    ; восстановление SP после чтения трёх смещений потоков паттерна

                ; -----------------------------------------
                ; чтение команд новой строки
                ; -----------------------------------------
.DecodeChannelA LD IX, PlayerState.ChanA + FPT3Channel.GateOffDelay

                ; -----------------------------------------
                ; декодирование строки паттерна канала A
                ; In:
                ;   BC - адрес первой команды строки в потоке паттерна
                ;   IX - адрес поля GateOffDelay в состоянии канала A
                ; Out:
                ;   BC - адрес следующей команды после строки и параметров эффектов
                ; Corrupt:
                ;   HL, DE, AF, AF'
                ; -----------------------------------------
                CALL DecodeRow
                LD (.PatternPtrA), BC                                           ; сохранение позиции чтения канала

                ; проверка, закончился ли пропуск строк канала B
.CheckChannelB  LD HL, PlayerState.ChanB + FPT3Channel.RowTicks
                DEC (HL)
                JR NZ, .CheckChannelC                                           ; переход, если канал B ещё пропускает строки

                LD IX, PlayerState.ChanB + FPT3Channel.GateOffDelay
.PatternPtrB    EQU $+1                                                         ; операнд с адресом следующей команды паттерна канала B
                LD BC, #0000

                ; -----------------------------------------
                ; декодирование строки паттерна канала B
                ; In:
                ;   BC - адрес первой команды строки в потоке паттерна
                ;   IX - адрес поля GateOffDelay в состоянии канала B
                ; Out:
                ;   BC - адрес следующей команды после строки и параметров эффектов
                ; Corrupt:
                ;   HL, DE, AF, AF'
                ; -----------------------------------------
                CALL DecodeRow
                LD (.PatternPtrB), BC                                           ; сохранение позиции чтения канала

                ; проверка, закончился ли пропуск строк канала C
.CheckChannelC  LD HL, PlayerState.ChanC + FPT3Channel.RowTicks
                DEC (HL)
                JR NZ, .ReloadRowDelay                                          ; переход, если канал C ещё пропускает строки

                LD IX, PlayerState.ChanC + FPT3Channel.GateOffDelay
.PatternPtrC    EQU $+1                                                         ; операнд с адресом следующей команды паттерна канала C
                LD BC, #0000

                ; -----------------------------------------
                ; декодирование строки паттерна канала C
                ; In:
                ;   BC - адрес первой команды строки в потоке паттерна
                ;   IX - адрес поля GateOffDelay в состоянии канала C
                ; Out:
                ;   BC - адрес следующей команды после строки и параметров эффектов
                ; Corrupt:
                ;   HL, DE, AF, AF'
                ; -----------------------------------------
                CALL DecodeRow
                LD (.PatternPtrC), BC                                           ; сохранение позиции чтения канала

                ; -----------------------------------------
                ; установка задержки перед следующей строкой
                ; -----------------------------------------
                ; перезагрузка общего счётчика после обработки строки всех трёх каналов
.Delay          EQU $+1                                                         ; операнд с числом тиков между строками паттерна
.ReloadRowDelay LD A, #00
                LD (PlayerState.TickCounter), A

                ; -----------------------------------------
                ; формирование тона и громкости трёх каналов
                ; -----------------------------------------
.RenderTick     LD IX, PlayerState.ChanA
                LD HL, (PlayerState.AYRegisters + TonA)

                ; -----------------------------------------
                ; расчёт параметров AY для канала A
                ; In:
                ;   HL - предыдущий период тона
                ;   IX - адрес начала состояния канала A
                ; Out:
                ;   HL - период тона для записи в AY
                ;   PlayerState.ChannelVolume - громкость для записи в AmplA
                ;   PlayerState.AYRegisters + Mixer - микшер с учётом текущего канала
                ; Corrupt:
                ;   DE, BC, AF, AF'
                ; -----------------------------------------
                CALL RenderChannel
                LD (PlayerState.AYRegisters + TonA), HL
                LD A, (PlayerState.ChannelVolume)
                LD (PlayerState.AYRegisters + AmplA), A

                LD IX, PlayerState.ChanB
                LD HL, (PlayerState.AYRegisters + TonB)

                ; -----------------------------------------
                ; расчёт параметров AY для канала B
                ; In:
                ;   HL - предыдущий период тона
                ;   IX - адрес начала состояния канала B
                ; Out:
                ;   HL - период тона для записи в AY
                ;   PlayerState.ChannelVolume - громкость для записи в AmplB
                ;   PlayerState.AYRegisters + Mixer - микшер с учётом текущего канала
                ; Corrupt:
                ;   DE, BC, AF, AF'
                ; -----------------------------------------
                CALL RenderChannel
                LD (PlayerState.AYRegisters + TonB), HL
                LD A, (PlayerState.ChannelVolume)
                LD (PlayerState.AYRegisters + AmplB), A

                LD IX, PlayerState.ChanC
                LD HL, (PlayerState.AYRegisters + TonC)

                ; -----------------------------------------
                ; расчёт параметров AY для канала C
                ; In:
                ;   HL - предыдущий период тона
                ;   IX - адрес начала состояния канала C
                ; Out:
                ;   HL - период тона для записи в AY
                ;   PlayerState.ChannelVolume - громкость канала C, этот байт уже является AmplC
                ;   PlayerState.AYRegisters + Mixer - микшер с учётом текущего канала
                ; Corrupt:
                ;   DE, BC, AF, AF'
                ; -----------------------------------------
                CALL RenderChannel
                LD (PlayerState.AYRegisters + TonC), HL

                ; -----------------------------------------
                ; формирование периода шума
                ; -----------------------------------------
                ; сложение базового периода шума из паттерна и поправки из сэмпла
                ; NoiseState объединяет эти байты для чтения одним словом
                LD HL, (PlayerState.NoiseState)
                LD A, H
                ADD A, L
                LD (PlayerState.AYRegisters + Noise), A

                ; -----------------------------------------
                ; формирование периода огибающей
                ; -----------------------------------------
                ; расширение знаковой поправки текущего тика до слова, E хранит байт, D получает знак
.EnvAdjust      EQU $+1                                                         ; операнд с суммарной поправкой огибающей в текущем тике
                LD A, #00
                LD E, A
                ADD A, A                                                        ; знаковый бит поправки переходит во флаг переноса
                SBC A, A                                                        ; #FF для отрицательной поправки, #00 для остальных
                LD D, A

                ; период для этого тика складывается из базы, поправки каналов и накопленного скольжения
                LD HL, (PlayerState.EnvelopeBase)
                ADD HL, DE
                LD DE, (PlayerState.EnvelopeSlide)
                ADD HL, DE
                LD (PlayerState.AYRegisters + Env), HL

                ; -----------------------------------------
                ; обновление скольжения огибающей и вывод в AY
                ; -----------------------------------------
                ; проверка счётчика скольжения, ноль означает, что скольжение выключено
                ; в этом случае A уже содержит #00 для входа в SetRegisters
                XOR A
                LD HL, PlayerState.EnvSlideTicks
                OR (HL)
                JR Z, SetRegisters                                              ; переход, если скольжение огибающей выключено

                ; проверка, истёк ли интервал до очередного шага скольжения
                DEC (HL)
                JR NZ, WriteAY                                                  ; переход, если до шага скольжения огибающей остались тики

                ; перезагрузка счётчика и прибавление шага к накопленной поправке
                ; новая поправка попадёт в период огибающей на следующем тике
.EnvSlideDelay  EQU $+1                                                         ; операнд с интервалом между шагами огибающей
                LD A, #00
                LD (HL), A
.EnvSlideStep   EQU $+1                                                         ; операнд со знаковым шагом периода огибающей
                LD HL, #0000
                ADD HL, DE
                LD (PlayerState.EnvelopeSlide), HL
                ; JP WriteAY, продолжение в WriteAY.asm

                endif ; ~ _PLAYER_MUSIC_AY_PLAY_
