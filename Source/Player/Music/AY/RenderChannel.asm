
                ifndef _PLAYER_MUSIC_AY_RENDERCHANNEL_
                define _PLAYER_MUSIC_AY_RENDERCHANNEL_
; -----------------------------------------
; формат орнамента и сэмпла
;   В обоих заголовках первый байт задаёт позицию зацикливания,
;   второй задаёт число строк. Индексы строк начинаются с нуля.
;   Строка орнамента содержит знаковую поправку номера ноты.
;   Строка сэмпла занимает четыре байта, два управляющих байта
;   и знаковая поправка периода тона младшим байтом вперёд.
;
;   первый управляющий байт
;
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | VA | VD | D4 | D3 | D2 | D1 | D0 | ED |
;   +----+----+----+----+----+----+----+----+
;
;   VA      [7]     - флаг, изменение накопленной поправки громкости
;   VD      [6]     - направление изменения громкости
;                       0 - уменьшить
;                       1 - увеличить
;   D4-D0   [5-1]   - поправка шума или знаковая поправка огибающей
;   ED      [0]     - флаг, отключение огибающей для этой строки
;
;   второй управляющий байт
;
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | ND | TA | DA | TD | V3 | V2 | V1 | V0 |
;   +----+----+----+----+----+----+----+----+
;
;   ND      [7]     - флаг, отключение шума и выбор поправки
;                       0 - прибавить поправку к периоду шума
;                       1 - выключить шум канала и прибавить поправку к периоду огибающей
;   TA      [6]     - флаг, накопление поправки периода тона
;   DA      [5]     - флаг, накопление поправки шума или огибающей
;   TD      [4]     - флаг, отключение тона
;   V3-V0   [3-0]   - громкость строки сэмпла
; -----------------------------------------

; -----------------------------------------
; расчёт параметров AY для одного канала
; In:
;   HL - предыдущий период тона
;   IX - адрес начала состояния канала
; Out:
;   HL - период тона для записи в AY
;   PlayerState.ChannelVolume - громкость канала
;   PlayerState.AYRegisters + Mixer - микшер с учётом текущего канала
; Corrupt:
;   DE, BC, AF, AF'
; Note:
;   SP временно используется для чтения орнамента, сэмпла и периода ноты
; -----------------------------------------
RenderChannel:  ; -----------------------------------------
                ; проверка состояния ноты
                ; -----------------------------------------
                ; нулевая громкость на случай, если нота канала выключена
                XOR A
                LD (PlayerState.ChannelVolume), A

                ; проверка, включена ли нота канала
                BIT PT3_NOTE_ON_BIT, (IX + FPT3Channel.Flags)
                PUSH HL
                JP Z, .UpdateMixer                                              ; переход, если нота канала выключена

                ; -----------------------------------------
                ; орнамент и номер ноты
                ; -----------------------------------------
                ; чтение заголовка и строки орнамента через временный стек
                ; сохранение указателя стека перед чтением данных
                LD (.ContainerSP), SP
                LD HL, (IX + FPT3Channel.OrnamentPtr)
                LD SP, HL
                POP DE

                ; расчёт адреса текущей строки орнамента
                LD H, A
                LD A, (IX + FPT3Channel.OrnamentPos)
                LD L, A
                ADD HL, SP
                INC A

                ; проверка, достигнут ли конец орнамента
                CP D
                JR C, .SaveOrnPos                                               ; переход, если следующая позиция орнамента меньше его длины

                LD A, E
.SaveOrnPos     LD (IX + FPT3Channel.OrnamentPos), A

                ; расчёт номера ноты с поправкой орнамента и проверка нижней границы
                LD A, (IX + FPT3Channel.Note)
                ADD A, (HL)
                JP P, .CheckNoteHigh                                            ; переход, если номер ноты после прибавления орнамента неотрицательный

                XOR A

                ; проверка верхней границы номера ноты
.CheckNoteHigh  CP PT3_CMD_NOTE_COUNT
                JR C, .ReadNotePeriod                                           ; переход, если номер ноты входит в таблицу периодов

                LD A, PT3_NOTE_LAST

.ReadNotePeriod ; расчёт смещения слова в таблице периодов
                ADD A, A    ; x2
                EX AF, AF'                                                      ; сохранение смещения ноты в A' на время чтения сэмпла

                ; -----------------------------------------
                ; сэмпл и поправка периода тона
                ; -----------------------------------------
                ; чтение двухбайтового заголовка сэмпла через временный стек
                LD HL, (IX + FPT3Channel.SamplePtr)
                LD SP, HL
                POP DE                                                          ; E - позиция зацикливания, D - число строк, SP - начало строк
                LD H, #00                                                       ; старший байт смещения строки

                ; расчёт адреса текущей строки, четыре байта на строку
                LD A, (IX + FPT3Channel.SamplePos)
                LD B, A                                                         ; исходный индекс для расчёта следующей позиции
                ADD A, A    ; x2
                ADD A, A    ; x4
                LD L, A
                ADD HL, SP
                LD SP, HL                                                       ; адрес строки для последующего чтения через POP

                ; расчёт следующей позиции, при достижении длины берётся позиция зацикливания
                LD A, B
                INC A

                ; проверка, достигнут ли конец сэмпла
                CP D
                JR C, .SaveSamplePos                                            ; переход, если следующая позиция сэмпла меньше его длины

                LD A, E
.SaveSamplePos  LD (IX + FPT3Channel.SamplePos), A

                ; чтение управляющих байтов сэмпла и расчёт поправки тона
                POP BC
                POP HL
                LD DE, (IX + FPT3Channel.ToneAdjust)
                ADD HL, DE

                ; проверка, нужно ли сохранить поправку тона для следующих строк
                BIT PT3_SAMPLE_TONE_ACC_BIT, B
                JR Z, .AddSampleTone                                            ; переход, если строка сэмпла не накапливает поправку тона

                LD (IX + FPT3Channel.ToneAdjust), HL
.AddSampleTone  EX DE, HL
                EX AF, AF'
                LD L, A
                LD H, #00

                ; -----------------------------------------
                ; период тона для текущего тика
                ; -----------------------------------------
                ; чтение периода ноты и прибавление поправок сэмпла и скольжения
                LD SP, PlayerState.NotePeriods
                ADD HL, SP
                LD SP, HL
                POP HL
                ADD HL, DE
                LD DE, (IX + FPT3Channel.ToneSlide)
                ADD HL, DE
.ContainerSP    EQU $+1
                LD SP, #0000                                                    ; восстановление SP после чтения орнамента, сэмпла и периода ноты
                EX (SP), HL

                ; -----------------------------------------
                ; скольжение тона
                ; -----------------------------------------
                ; проверка, включено ли скольжение тона
                XOR A
                OR (IX + FPT3Channel.ToneSlideTicks)
                JR Z, .CalcVolume                                               ; переход, если скольжение тона выключено

                ; проверка, пора ли применить следующий шаг скольжения
                DEC (IX + FPT3Channel.ToneSlideTicks)
                JR NZ, .CalcVolume                                              ; переход, если до шага скольжения остались тики

                ; перезапуск счётчика и прибавление шага скольжения
                LD A, (IX + FPT3Channel.ToneSlideDelay)
                LD (IX + FPT3Channel.ToneSlideTicks), A
                LD HL, (IX + FPT3Channel.ToneSlideStep)
                LD A, H
                ADD HL, DE
                LD (IX + FPT3Channel.ToneSlide), HL
                ; проверка, есть ли у скольжения целевая нота
                BIT PT3_GLISSANDO_BIT, (IX + FPT3Channel.Flags)
                JR NZ, .CalcVolume                                              ; переход, если действует глиссандо без целевой ноты

                ; выбор порядка сравнения по направлению шага портаменто
                LD DE, (IX + FPT3Channel.TargetToneDelta)
                AND A
                JR Z, .CheckSlideEnd                                            ; переход, если старший байт шага скольжения равен нулю

                EX DE, HL

                ; проверка, достигнута ли целевая нота портаменто
.CheckSlideEnd  SBC HL, DE
                JP M, .CalcVolume                                               ; переход, если портаменто ещё не достигло целевой ноты

                ; установка целевой ноты и сброс скольжения
                LD A, (IX + FPT3Channel.TargetNote)
                LD (IX + FPT3Channel.Note), A
                XOR A
                LD (IX + FPT3Channel.ToneSlideTicks), A
                LD (IX + FPT3Channel.ToneSlide), A
                LD (IX + FPT3Channel.ToneSlide + 1), A

                ; -----------------------------------------
                ; громкость канала
                ; -----------------------------------------
.CalcVolume     LD A, (IX + FPT3Channel.VolumeAdjust)                           ; расчёт поправки громкости по флагам строки сэмпла с ограничением от −15 до 15

                ; проверка, меняет ли строка сэмпла накопленную поправку громкости
                BIT PT3_SAMPLE_VOL_ADJ_BIT, C
                JR Z, .ApplyVolumeAdj                                           ; переход, если строка сэмпла не меняет поправку громкости

                ; проверка направления изменения поправки громкости
                BIT PT3_SAMPLE_VOL_UP_BIT, C
                JR Z, .LowerVolume                                              ; переход, если поправка громкости уменьшается

                ; проверка верхней границы накопленной поправки
                CP PT3_VOLUME_MAX
                JR Z, .ApplyVolumeAdj                                           ; переход, если поправка громкости уже равна 15

                INC A
                JR .SaveVolumeAdj

                ; проверка нижней границы накопленной поправки
.LowerVolume    CP -PT3_VOLUME_MAX
                JR Z, .ApplyVolumeAdj                                           ; переход, если поправка громкости уже равна −15

                DEC A
.SaveVolumeAdj  LD (IX + FPT3Channel.VolumeAdjust), A

                ; расчёт громкости строки с накопленной поправкой и проверка нижней границы
.ApplyVolumeAdj LD L, A
                LD A, B
                AND PT3_VOLUME_MAX
                ADD A, L
                JP P, .CheckVolumeMax                                           ; переход, если громкость с поправкой неотрицательна

                XOR A

                ; проверка верхней границы громкости строки
.CheckVolumeMax CP PT3_VOLUME_LEVELS
                JR C, .ReadVolume                                               ; переход, если громкость с поправкой меньше 16

                LD A, PT3_VOLUME_MAX

                ; поиск итоговой громкости по уровням канала и строки сэмпла
.ReadVolume     OR (IX + FPT3Channel.Volume)                                    ; выбор громкости AY по громкости канала и скорректированной громкости сэмпла
                LD L, A
                LD H, #00
                LD DE, PlayerState.VolumeTable
                ADD HL, DE
                LD A, (HL)

                ; проверка, запрещает ли строка сэмпла использовать огибающую
.CheckEnvelope  BIT PT3_SAMPLE_NO_ENV_BIT, C
                JR NZ, .SaveVolume                                              ; переход, если строка сэмпла отключает огибающую

                OR (IX + FPT3Channel.EnvelopeMask)
.SaveVolume     LD (PlayerState.ChannelVolume), A

                ; -----------------------------------------
                ; поправки шума и огибающей
                ; -----------------------------------------
                ; выбор назначения поправки сэмпла, шум или огибающая
                BIT PT3_SAMPLE_ENV_BIT, B
                LD A, C
                JR Z, .CalcNoise                                                ; переход, если строка сэмпла задаёт поправку шума

                ; извлечение знаковой поправки огибающей из первого управляющего байта
                RLA
                RLA
                SRA A
                SRA A
                SRA A
                ADD A, (IX + FPT3Channel.EnvelopeAdjust)                        ; учёт накопленной поправки огибающей

                ; проверка, нужно ли накопить поправку огибающей
                BIT PT3_SAMPLE_MOD_ACC_BIT, B
                JR Z, .AddEnvelope                                              ; переход, если поправка огибающей действует только в текущем тике

                LD (IX + FPT3Channel.EnvelopeAdjust), A
.AddEnvelope    LD HL, Play.EnvAdjust
                ADD A, (HL)                                                     ; сумма поправок огибающей хранится в одном байте
                LD (HL), A
                JR .CalcMixer

                ; расчёт поправки шума из управляющего байта сэмпла и накопленного значения
.CalcNoise      RRA
                ADD A, (IX + FPT3Channel.NoiseAdjust)
                LD (PlayerState.NoiseOffset), A

                ; проверка, нужно ли накопить поправку шума
                BIT PT3_SAMPLE_MOD_ACC_BIT, B
                JR Z, .CalcMixer                                                ; переход, если поправка шума действует только в текущем тике

                LD (IX + FPT3Channel.NoiseAdjust), A

                ; -----------------------------------------
                ; микшер AY
                ; -----------------------------------------
.CalcMixer      LD A, B                                                         ; перенос флагов отключения тона и шума из строки сэмпла в микшер
                RRA
                AND PT3_SAMPLE_MIX_MASK

                ; обновление общего микшера и восстановление периода тона из стека
.UpdateMixer    LD HL, PlayerState.AYRegisters + Mixer
                OR (HL)
                RRCA
                LD (HL), A
                POP HL

                ; -----------------------------------------
                ; переключение звучания канала
                ; -----------------------------------------
                ; проверка, задано ли периодическое включение и выключение канала
                XOR A
                OR (IX + FPT3Channel.GateTicks)
                RET Z                                                           ; выход, если периодическое включение и выключение канала не задано

                ; проверка, закончился ли текущий интервал звучания или паузы
                DEC (IX + FPT3Channel.GateTicks)
                RET NZ                                                          ; выход, если до переключения канала остались тики

                ; переключение звучания и выбор длительности нового состояния
                XOR (IX + FPT3Channel.Flags)
                LD (IX + FPT3Channel.Flags), A
                RRA
                LD A, (IX + FPT3Channel.GateOnDelay)
                JR C, .SaveGateDelay                                            ; переход, если канал включён и нужна длительность звучания

                LD A, (IX + FPT3Channel.GateOffDelay)
.SaveGateDelay  LD (IX + FPT3Channel.GateTicks), A
                RET

                endif ; ~ _PLAYER_MUSIC_AY_RENDERCHANNEL_
