                ifndef _CHARACTER_UTILITIES_EQUIPMENT_
                define _CHARACTER_UTILITIES_EQUIPMENT_

                module Equipment
; -----------------------------------------
; определение слота экипировки по идентификатору предмета
; In:
;   D  - индекс персонажа
;   E  - идентификатор предмета
; Out:
;   HL - адрес идентификатора в найденном слоте
;   E  - индекс найденного слота или ITEM_ID_NONE
;   флаг переполнения установлен, если слот найден, иначе сброшен
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в странице 0
;   если слот не найден, HL указывает за пределы экипировки
; -----------------------------------------
FindSlot:       ; получение адреса персонажа
                LD A, D
                CALL Character.Utilities.GetAdr.HL

                ; получение адреса первого слота и сохранение идентификатора
                LD A, E
                LD DE, FCharacter.Equipment
                ADD HL, DE
                LD B, FCharacterEquipment
                LD C, #00

.Loop           ; проверка предмета в текущем слоте
                CP (HL)
                JR Z, .Found                                                    ; переход, если слот содержит указанный предмет

                ; переход к следующему слоту экипировки
                INC HL
                INC C
                DJNZ .Loop

                ; возврат признака отсутствия предмета в экипировке
                LD E, ITEM_ID_NONE
                OR A
                RET

.Found          ; возврат индекса найденного слота
                LD E, C
                SCF
                RET
; -----------------------------------------
; установка предмета в слот экипировки с возвратом прежнего предмета
; In:
;   D   - индекс персонажа
;   E   - идентификатор устанавливаемого предмета
;   IYL - индекс слота в FCharacterEquipment
; Out:
;   HL - адрес идентификатора в слоте экипировки
;   E  - прежний идентификатор предмета в слоте
;   A  - прежний идентификатор предмета в слоте
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в странице 0
; -----------------------------------------
Equip:          ; получение адреса персонажа
                LD A, D
                CALL Character.Utilities.GetAdr.HL

                ; расчёт адреса выбранного слота с сохранением предмета в A
                LD A, E
                LD BC, FCharacter.Equipment
                ADD HL, BC
                LD C, IYL
                ADD HL, BC

.SetSlot        ; замена предмета с возвратом прежнего идентификатора
                LD E, (HL)
                LD (HL), A
                LD A, E
                RET
; -----------------------------------------
; снятие предмета из указанного слота экипировки
; In:
;   DE - адрес идентификатора в слоте экипировки
; Out:
;   HL - адрес идентификатора в слоте экипировки
;   E  - идентификатор снятого предмета
;   A  - идентификатор снятого предмета
; Corrupt:
;   HL, DE, AF
; Note:
;   ℹ️ код расположен в странице 0
; -----------------------------------------
Unequip:        ; подготовка адреса освобождаемого слота
                LD H, D
                LD L, E

                ; освобождение слота с возвратом снятого предмета
                LD A, ITEM_ID_NONE
                JR Equip.SetSlot

                endmodule

                endif ; ~_CHARACTER_UTILITIES_EQUIPMENT_
