                ifndef _MODULE_INVENTORY_UTILITIES_DRAGGED_ITEM_
                define _MODULE_INVENTORY_UTILITIES_DRAGGED_ITEM_
                module DraggedItem
; -----------------------------------------
; получение размера изображения взятого предмета
; In:
; Out:
;   флаг переполнения установлен, если размер получен и поддерживается
; Corrupt:
;   HL, DE, BC, AF, AF'
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
GetSize:        ; чтение размера взятого предмета
                LD A, (Inventory.States.DraggedItem.ID)
                ; -----------------------------------------
                ; In:
                ;   A  - идентификатор экземпляра предмета
                ; Out:
                ;   BC - размер в знакоместах (B - y, C - x)
                ; Corrupt:
                ;   HL, DE, BC, AF, AF'
                ; -----------------------------------------
                CALL Inventory.Utilities.Item.ReadSize
; -----------------------------------------
; проверка и сохранение размера перетаскиваемого предмета
; In:
;   BC - размер в знакоместах (B - y, C - x)
; Out:
;   флаг переполнения установлен, если размер сохранён
; Corrupt:
;   AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
SetSize:        ; проверка допустимой высоты предмета
                LD A, B
                OR A
                RET Z                                                           ; выход, если высота предмета не задана
                CP SCR_ITEM_MAX_SIZE_Y + 1
                RET NC                                                          ; выход, если высота превышает вместимость буфера

                ; проверка допустимой ширины предмета
                LD A, C
                OR A
                RET Z                                                           ; выход, если ширина предмета не задана
                CP SCR_ITEM_MAX_SIZE_X + 1
                RET NC                                                          ; выход, если ширина превышает вместимость буфера
                AND #01
                RET NZ                                                          ; выход, если ширина не поддерживается сохранением фона

                ; сохранение размера перетаскиваемого предмета
                LD (Inventory.States.DraggedItem.Size), BC
                SCF                                                             ; установка флага переполнения, размер предмета получен и поддерживается
                RET
; -----------------------------------------
; подготовка точки захвата предмета из сетки или экипировки
; In:
;   HL - прежняя позиция предмета в ячейках сетки (H - y, L - x)
;   DE - состояние размещения и контейнер предмета
; Out:
;   IXL - прежнее состояние размещения предмета
;   флаг переполнения установлен, если точка захвата подготовлена
; Corrupt:
;   HL, DE, BC, AF, AF', IX
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
PrepareGrab:    ; сохранение исходного состояния размещения
                LD IXL, E

                ; проверка взятия из экипировки
                BIT ITEM_LOCATION_EQUIPPED_BIT, E
                JR NZ, .Equipment                                               ; переход, если предмет находится в экипировке

                ; проверка обычной позиции предмета в сетке
                BIT ITEM_ITEM_POSITION_CUSTOM_BIT, E
                JR NZ, .Rejected                                                ; переход, если предмет использует пользовательскую позицию вне экипировки

                ; расчёт левого края предмета в пикселях
                LD A, L
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                ADD A, A    ; x16
                ADD A, SCR_INVENTORY_POS_X << 3
                LD L, A

                ; расчёт верхнего края предмета в пикселях
                LD A, H
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                ADD A, A    ; x16
                ADD A, SCR_INVENTORY_POS_Y << 3
                LD H, A
                JR .CheckGrab

.Equipment      ; -----------------------------------------
                ; определение исходного положения предмета в экипировке
                ; -----------------------------------------
                
                ; определение слота под курсором в момент нажатия
                LD HL, (Inventory.States.DraggedItem.GrabOffset)
                PUSH IX                                                         ; сохранение исходного состояния размещения в IXL
                ; -----------------------------------------
                ; In:
                ;   HL - координаты в пикселях (H - y, L - x)
                ; Out:
                ;   E  - индекс слота или ITEM_ID_NONE
                ;   флаг переполнения установлен, если слот найден
                ; Corrupt:
                ;   DE, BC, AF, IX
                ; -----------------------------------------
                CALL Inventory.UI.Utilities.GetSlotByPoint
                POP IX
                JR NC, .Rejected                                                ; переход, если курсор находится вне слотов экипировки
                LD A, E

.SlotLocation   ; расчёт адреса положения слота под курсором
                LD HL, Inventory.States.Slots.Head + FInventorySlotStates.Location
                LD DE, FInventorySlotStates
                OR A
                JR Z, .ReadSlot                                                 ; переход, если предмет находится в первом слоте

                ; подготовка счётчика переходов к нужному слоту
                LD B, A

.SlotOffset     ADD HL, DE
                DJNZ .SlotOffset

.ReadSlot       ; чтение положения предмета в знакоместах
                LD E, (HL)
                INC HL                                                          ; переход к вертикальной координате слота
                LD D, (HL)

                ; расчёт левого края предмета в пикселях
                LD A, E
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD L, A

                ; расчёт верхнего края предмета в пикселях
                LD A, D
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD H, A
                ; -----------------------------------------

.CheckGrab      ; проверка горизонтальной позиции курсора внутри предмета
                LD A, (Inventory.States.DraggedItem.Size)
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD C, A
                LD DE, (Inventory.States.DraggedItem.GrabOffset)
                LD A, E
                SUB L
                JR C, .Rejected                                                 ; переход, если курсор находится левее предмета
                CP C
                JR NC, .Rejected                                                ; переход, если курсор находится правее предмета
                LD E, A

                ; проверка вертикальной позиции курсора внутри предмета
                LD A, (Inventory.States.DraggedItem.Size + FSize.Height)
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD C, A
                LD A, D
                SUB H
                JR C, .Rejected                                                 ; переход, если курсор находится выше предмета
                CP C
                JR NC, .Rejected                                                ; переход, если курсор находится ниже предмета
                LD D, A
                LD (Inventory.States.DraggedItem.GrabOffset), DE                ; сохранение локальной точки захвата

                SCF                                                             ; установка флага переполнения, точка захвата находится внутри предмета
                RET

.Rejected       OR A
                RET
; -----------------------------------------
; подготовка точки захвата предмета после обмена
; In:
;   HL  - позиция курсора в пикселях (H - y, L - x)
;   IXL - индекс слота
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
Grab:           ; сохранение позиции курсора на время определения положения слота
                PUSH HL

                ; расчёт адреса положения выбранного слота
                LD HL, Inventory.UI.Equipment + FUIElement.Location
                LD DE, FUIElement
                LD A, IXL
                OR A
                JR Z, .ReadOrigin                                               ; переход, если выбран первый слот

                ; подготовка счётчика переходов к нужному слоту
                LD B, A

.OriginLoop     ADD HL, DE
                DJNZ .OriginLoop

.ReadOrigin     ; чтение положения слота в пикселях
                LD E, (HL)
                INC HL                                                          ; переход к вертикальной координате слота
                LD D, (HL)
                POP HL

                ; расчёт точки захвата относительно положения слота
                LD A, L
                SUB E
                LD E, A
                LD A, H
                SUB D
                LD D, A
                LD BC, (Inventory.States.DraggedItem.Size)

                ; ограничение горизонтальной точки захвата размером заменённого предмета
                LD A, C
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                DEC A
                CP E
                JR NC, .GrabY                                                   ; переход, если горизонтальная точка захвата находится внутри предмета
                LD E, A

.GrabY          ; ограничение вертикальной точки захвата размером заменённого предмета
                LD A, B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                DEC A
                CP D
                JR NC, .SaveGrab                                                ; переход, если вертикальная точка захвата находится внутри предмета
                LD D, A

.SaveGrab       LD (Inventory.States.DraggedItem.GrabOffset), DE
                RET
; -----------------------------------------
; расчёт положения перетаскиваемого предмета в пределах экрана
; In:
; Out:
;   DE - положение предмета в знакоместах (D - y, E - x)
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
GetPosition:    ; инициализация
                LD HL, (Mouse.Position)                                         ; чтение позиции указателя
; -----------------------------------------
; расчёт положения предмета по сохранённой позиции курсора
; In:
;   HL - позиция курсора в пикселях (H - y, L - x)
; Out:
;   DE - положение предмета в знакоместах (D - y, E - x)
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
.ByCursor       LD DE, (Inventory.States.DraggedItem.GrabOffset)
                LD BC, (Inventory.States.DraggedItem.Size)                      ; чтение подготовленного размера предмета

                ; расчёт левого края предмета с ограничением по левой границе экрана
                LD A, L
                SUB E
                JR NC, .XReady                                                  ; переход, если левый край предмета находится внутри экрана
                XOR A

.XReady         ; перевод горизонтальной позиции в знакоместа
                SRL A
                SRL A
                SRL A
                LD E, A

                ; ограничение горизонтальной позиции шириной экрана
                LD A, SCREEN_CURSOR_X >> 3
                SUB C
                CP E
                JR NC, .CheckY                                                  ; переход, если предмет помещается до правой границы экрана
                LD E, A

.CheckY         ; расчёт верхнего края предмета с ограничением по верхней границе экрана
                LD A, H
                SUB D
                JR NC, .YReady                                                  ; переход, если верхний край предмета находится внутри экрана
                XOR A

.YReady         ; перевод вертикальной позиции в знакоместа
                SRL A
                SRL A
                SRL A
                LD D, A

                ; ограничение вертикальной позиции высотой экрана
                LD A, SCREEN_CURSOR_Y >> 3
                SUB B
                CP D
                JR NC, .Return                                                  ; переход, если предмет помещается до нижней границы экрана
                LD D, A

.Return         RET

                endmodule

                endif ; ~_MODULE_INVENTORY_UTILITIES_DRAGGED_ITEM_
