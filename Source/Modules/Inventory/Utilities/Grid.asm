                ifndef _MODULE_INVENTORY_UTILITIES_GRID_
                define _MODULE_INVENTORY_UTILITIES_GRID_
                module Grid
; -----------------------------------------
; определение позиции в сетке при частичном пересечении по одной оси
; In:
;   H - размер экрана в знакоместах
;   D - размер сетки в ячейках
;   E - смещение точки захвата в пикселях
;   B - размер предмета в знакоместах
;   C - начало сетки в знакоместах
;   A - позиция курсора в пикселях
; Out:
;   E - позиция размещения в ячейках
;   флаг переполнения установлен, если пересечения с сеткой нет
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
Axis:           ; ограничение положения предмета левой или верхней границей экрана
                SUB E
                JR NC, .AxisLeft                                                ; переход, если начало предмета находится внутри экрана
                XOR A

.AxisLeft       ; ограничение положения предмета правой или нижней границей экрана
                LD L, A
                LD A, H
                SUB B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                CP L
                JR NC, .AxisScreen                                              ; переход, если предмет целиком помещается на экране
                LD L, A

.AxisScreen     ; расчёт положения предмета относительно начала сетки
                LD A, C
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD C, A
                LD A, L
                SUB C
                JR NC, .AxisInside                                              ; переход, если начало предмета находится внутри сетки или после неё

                ; проверка пересечения при начале предмета перед сеткой
                NEG
                LD L, A
                LD A, B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                CP L
                RET C                                                           ; выход, если предмет заканчивается перед сеткой
                SCF                                                             ; установка флага переполнения для случая касания границы
                RET Z                                                           ; выход, если предмет только касается начала сетки
                XOR A
                JR .AxisClamp

.AxisInside     ; проверка пересечения с концом сетки
                LD L, A
                LD A, D
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                ADD A, A    ; x16
                CP L
                RET C                                                           ; выход, если предмет начинается после сетки
                SCF                                                             ; установка флага переполнения для случая касания границы
                RET Z                                                           ; выход, если предмет только касается конца сетки
                LD A, L

.AxisClamp      ; перевод положения в ячейки сетки
                SRL A
                SRL A
                SRL A
                SRL A
                LD E, A

                ; расчёт последней позиции для полного размещения предмета
                LD A, B
                INC A
                SRL A
                LD L, A
                LD A, D
                SUB L
                RET C                                                           ; выход, если размер предмета превышает размер сетки

                ; ограничение размещения последней допустимой позицией
                CP E
                RET NC                                                          ; выход, если позиция уже позволяет разместить предмет целиком
                LD E, A
                OR A
                RET
; -----------------------------------------
; проверка отсутствия пересечений с предметами в сетке
; In:
;   DE - позиция области в ячейках сетки (D - y, E - x)
;   BC - размер области в знакоместах (B - y, C - x)
; Out:
;   флаг переполнения установлен, если область свободна
; Corrupt:
;   HL, DE, BC, AF, AF', IY
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
CheckFree:      ; сохранение позиции проверяемой области
                LD (.Position), DE
.Position       EQU $+1                                                         ; позиция области в ячейках сетки
                LD DE, #0000

                ; сохранение размеров проверяемой области
                LD A, C
                LD (.CheckWidth), A
                LD A, B
                LD (.CheckHeight), A

                ; подготовка обхода экземпляров предметов
                LD A, (GameState.ItemsNum)
                LD IYL, A

.Loop           ; проверка оставшихся экземпляров
                LD A, IYL
                OR A
                SCF                                                             ; установка флага переполнения, пересечений с проверенными предметами нет
                RET Z                                                           ; выход, если все экземпляры проверены и область свободна

                ; копирование размещения очередного экземпляра в общий буфер
                DEC IYL
                LD A, IYL
                ; -----------------------------------------
                ; In:
                ;   A  - идентификатор предмета
                ; Out:
                ;   HL - адрес FItemLocation
                ;   A  - страница массива предметов
                ; Corrupt:
                ;   HL, BC, AF
                ; -----------------------------------------
                CALL Item.Utilities.GetLocAdr.HL                                ; получить адрес размещения предмета
                LD DE, Inventory.Utilities.Buffer
                LD BC, FItemLocation
                CALL Func.CopyFromPage
                LD HL, Inventory.Utilities.Buffer

                ; проверка размещения экземпляра в сетке
                LD A, (HL)
                AND ITEM_LOCATION_EQUIPPED | ITEM_ITEM_POSITION_CUSTOM | ITEM_LOCATION_DRAGGED
                JR NZ, .Loop                                                    ; переход, если предмет не размещён в сетке

                ; проверка принадлежности выбранному персонажу
                INC HL                                                          ; переход к полю FItemLocation.Container
                LD A, (GameState.PlayerActions + FPlayerActions.SelectedHeroID)
                CP (HL)
                JR NZ, .Loop                                                    ; переход, если предмет принадлежит другому контейнеру

                ; чтение позиции очередного предмета в ячейках сетки
                INC HL                                                          ; переход к полю FItemLocation.Position.X
                LD E, (HL)
                INC HL                                                          ; переход к полю FItemLocation.Position.Y
                LD D, (HL)

                ; расчёт правой границы проверяемой области в знакоместах
                LD A, (.Position)
                ADD A, A    ; x2
                LD L, A
.CheckWidth     EQU $+1                                                         ; ширина проверяемой области в знакоместах
                LD A, #00
                ADD A, L
                LD C, A

                ; проверка положения левого края очередного предмета
                LD A, E
                ADD A, A    ; x2
                CP C
                JR NC, .Loop                                                    ; переход, если предмет находится правее проверяемой области
                LD E, A

                ; расчёт нижней границы проверяемой области в знакоместах
                LD A, (.Position + 1)
                ADD A, A    ; x2
                LD L, A
.CheckHeight    EQU $+1                                                         ; высота проверяемой области в знакоместах
                LD A, #00
                ADD A, L
                LD B, A

                ; проверка положения верхнего края очередного предмета
                LD A, D
                ADD A, A    ; x2
                CP B
                JR NC, .Loop                                                    ; переход, если предмет находится ниже проверяемой области
                LD D, A

                ; чтение размеров очередного предмета с сохранением его положения
                PUSH DE
                LD A, IYL
                ; -----------------------------------------
                ; In:
                ;   A  - идентификатор экземпляра предмета
                ; Out:
                ;   BC - размер в знакоместах (B - y, C - x)
                ; Corrupt:
                ;   HL, DE, BC, AF, AF'
                ; -----------------------------------------
                CALL Inventory.Utilities.Item.ReadSize
                POP DE

                ; проверка пересечения по горизонтали
                LD A, (.Position)
                ADD A, A    ; x2
                SUB E
                JR C, .CheckY                                                   ; переход, если левый край области находится левее предмета
                CP C
                JR NC, .Loop                                                    ; переход, если предмет заканчивается левее проверяемой области

.CheckY         ; проверка пересечения по вертикали
                LD A, (.Position + 1)
                ADD A, A    ; x2
                SUB D
                CCF
                RET NC                                                          ; выход, если предмет пересекает область по обеим осям

                CP B
                CCF
                RET NC                                                          ; выход, если верхний край области находится внутри высоты предмета

                JR .Loop
; -----------------------------------------
; определение свободного места с учётом предварительно выбранной области
; In:
;   DE - первая проверяемая позиция в ячейках сетки (D - y, E - x)
;   A  - идентификатор размещаемого предмета
;   DE' - позиция первой выбранной области в ячейках сетки (D' - y, E' - x) при установленном Reserve
;   B'  - идентификатор первого предмета при установленном Reserve
;   FindFree.Reserve - флаг, учёта первой выбранной области
; Out:
;   DE - найденная позиция в ячейках сетки (D - y, E - x)
;   флаг переполнения установлен, если место найдено
; Corrupt:
;   HL, DE, BC, AF, AF', IX, IY
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
FindFree:       ; чтение размеров с сохранением начальной позиции проверки
                PUSH DE
                ; -----------------------------------------
                ; In:
                ;   A  - идентификатор экземпляра предмета
                ; Out:
                ;   BC - размер в знакоместах (B - y, C - x)
                ; Corrupt:
                ;   HL, DE, BC, AF, AF'
                ; -----------------------------------------
                CALL Inventory.Utilities.Item.ReadSize
                POP DE

                ; проверка необходимости учитывать первый выбранный предмет
.Reserve        FLAG_MODIFY 0                                                   ; флаг, предварительного резервирования первой области
                JR NC, .Limits                                                  ; переход, если предварительно выбранной области нет

                ; чтение размеров первого предмета для проверки второй области
                PUSH BC
                PUSH DE
                EXX
                LD A, B
                EXX
                ; -----------------------------------------
                ; In:
                ;   A  - идентификатор экземпляра предмета
                ; Out:
                ;   BC - размер в знакоместах (B - y, C - x)
                ; Corrupt:
                ;   HL, DE, BC, AF, AF'
                ; -----------------------------------------
                CALL Inventory.Utilities.Item.ReadSize
                PUSH BC
                POP IX
                POP DE
                POP BC

.Limits         ; перевод ширины предмета в ячейки с округлением вверх
                LD A, C
                INC A
                SRL A

                ; расчёт последнего допустимого столбца для размещения предмета
                NEG
                ADD A, SCR_INVENTORY_SIZE_X
                LD L, A

                ; перевод высоты предмета в ячейки с округлением вверх
                LD A, B
                INC A
                SRL A

                ; расчёт последней допустимой строки для размещения предмета
                NEG
                ADD A, SCR_INVENTORY_SIZE_Y

                ; упаковка пределов в IYH, старшая тетрада - строка, младшая - столбец
                RLCA    ; x2
                RLCA    ; x4
                RLCA    ; x8
                RLCA    ; x16
                OR L
                LD IYH, A

.CheckPosition  ; проверка правой границы очередной позиции
                LD A, IYH
                AND #0F
                CP E
                JR C, .NextRow                                                  ; переход, если текущая строка проверена до правого края

                ; проверка нижней границы очередной позиции
                LD A, IYH

                ; перенос предела строки из старшей тетрады в младшую
                RRCA
                RRCA
                RRCA
                RRCA
                AND #0F
                CP D
                CCF
                RET NC                                                          ; выход, если все допустимые позиции проверены

                ; проверка пересечений с размещёнными в сетке предметами
                PUSH BC
                PUSH DE
                ; -----------------------------------------
                ; In:
                ;   DE - позиция области в ячейках сетки (D - y, E - x)
                ;   BC - размер области в знакоместах (B - y, C - x)
                ; Out:
                ;   флаг переполнения установлен, если область свободна
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IY
                ; -----------------------------------------
                CALL CheckFree
                POP DE
                POP BC
                JR NC, .NextPosition                                            ; переход, если место занято предметом в сетке

                ; проверка пересечения с предварительно выбранной областью
                CHECK_FLAG_MODIFY .Reserve
                SCF                                                             ; установка флага переполнения, место свободно без дополнительного ограничения
                RET Z                                                           ; выход, если предварительно выбранной области нет
                CALL .CheckReserve
                RET C                                                           ; выход, если место свободно и не пересекает первую выбранную область

.NextPosition   ; переход к следующему столбцу сетки
                INC E
                JR .CheckPosition

.NextRow        ; переход к следующей строке сетки
                LD E, #00
                INC D
                JR .CheckPosition
; -----------------------------------------
; проверка пересечения с предварительно выбранной областью
; In:
;   DE  - проверяемая позиция в ячейках сетки (D - y, E - x)
;   BC  - размер проверяемого предмета в знакоместах (B - y, C - x)
;   DE' - позиция первого предмета в ячейках сетки (D' - y, E' - x)
;   IX  - размер первого предмета в знакоместах (IXH - y, IXL - x)
; Out:
;   флаг переполнения установлен, если области не пересекаются
; Corrupt:
;   HL, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
.CheckReserve   ; чтение позиции первой области без изменения альтернативных регистров
                EXX
                PUSH DE
                EXX
                POP HL

                ; проверка расстояния по горизонтали
                LD A, E
                SUB L
                JR C, .BeforeFirst                                              ; переход, если вторая область начинается левее первой
                ADD A, A    ; x2
                CP IXL
                CCF
                RET C                                                           ; выход, если области разнесены по горизонтали
                JR .ReserveY

.BeforeFirst    ; расчёт положительного расстояния до первой области по горизонтали
                NEG
                ADD A, A    ; x2
                CP C
                CCF
                RET C                                                           ; выход, если области разнесены по горизонтали

.ReserveY       ; проверка расстояния по вертикали
                LD A, D
                SUB H
                JR C, .AboveFirst                                               ; переход, если вторая область начинается выше первой
                ADD A, A    ; x2
                CP IXH
                CCF
                RET

.AboveFirst     ; расчёт положительного расстояния до первой области по вертикали
                NEG
                ADD A, A    ; x2
                CP B
                CCF
                RET
; -----------------------------------------
; подготовка мест в сетке для предметов, вытесняемых из обеих рук
; In:
;   BC' - идентификаторы предметов, B' - первый, C' - второй
; Out:
;   HL' - позиция второго предмета в ячейках сетки (H' - y, L' - x)
;   DE' - позиция первого предмета в ячейках сетки (D' - y, E' - x)
;   флаг переполнения установлен, если места для всех предметов найдены
; Corrupt:
;   HL, DE, BC, AF, HL', DE', AF', IY
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
;   ITEM_ID_NONE обозначает отсутствие вытесняемого предмета
; -----------------------------------------
PlanDisplaced:  ; сброс предварительного резервирования областей
                RES_FLAG_MODIFY FindFree.Reserve

                ; проверка наличия вытесняемых предметов
                EXX
                LD A, B
                EXX
                CP ITEM_ID_NONE
                JR Z, .Success                                                  ; переход, если обе руки свободны
                LD DE, #0000

.FirstPlace     ; определение очередного места для первого предмета
                PUSH IX
                EXX
                LD A, B
                EXX
                ; -----------------------------------------
                ; In:
                ;   DE - первая проверяемая позиция в ячейках сетки (D - y, E - x)
                ;   A  - идентификатор размещаемого предмета
                ;   DE' - позиция первой выбранной области в ячейках сетки (D' - y, E' - x) при установленном Reserve
                ;   B'  - идентификатор первого предмета при установленном Reserve
                ;   FindFree.Reserve - флаг, учёта первой выбранной области
                ; Out:
                ;   DE - найденная позиция в ячейках сетки (D - y, E - x)
                ;   флаг переполнения установлен, если место найдено
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, IY
                ; -----------------------------------------
                CALL FindFree
                POP IX
                JR NC, .Failure                                                 ; переход, если места для всех вытесняемых предметов нет

                ; сохранение позиции первого предмета
                PUSH DE
                EXX
                POP DE
                EXX

                ; проверка наличия второго уникального предмета
                EXX
                LD A, C
                EXX
                CP ITEM_ID_NONE
                JR Z, .Success                                                  ; переход, если вытесняется только один предмет

                ; резервирование первого места только на время проверки второго
                SET_FLAG_MODIFY FindFree.Reserve
                LD DE, #0000
                PUSH IX
                EXX
                LD A, C
                EXX
                ; -----------------------------------------
                ; In:
                ;   DE - первая проверяемая позиция в ячейках сетки (D - y, E - x)
                ;   A  - идентификатор размещаемого предмета
                ;   DE' - позиция первой выбранной области в ячейках сетки (D' - y, E' - x) при установленном Reserve
                ;   B'  - идентификатор первого предмета при установленном Reserve
                ;   FindFree.Reserve - флаг, учёта первой выбранной области
                ; Out:
                ;   DE - найденная позиция в ячейках сетки (D - y, E - x)
                ;   флаг переполнения установлен, если место найдено
                ; Corrupt:
                ;   HL, DE, BC, AF, AF', IX, IY
                ; -----------------------------------------
                CALL FindFree
                POP IX
                JR C, .SecondPlace                                              ; переход, если места для обоих предметов найдены

                ; продолжение проверки с другой позицией первого предмета
                RES_FLAG_MODIFY FindFree.Reserve
                EXX
                PUSH DE
                EXX
                POP DE
                INC E
                JR .FirstPlace

.SecondPlace    ; сохранение позиции второго предмета
                PUSH DE
                EXX
                POP HL
                EXX

.Success        ; подтверждение размещения всех вытесняемых предметов
                SCF                                                             ; установка флага переполнения, места для всех предметов найдены
                RET

.Failure        OR A
                RET
; -----------------------------------------
; формирование общей части размещения предмета в сетке
; In:
; Out:
; Corrupt:
;   AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
PrepareRecord:  ; установка контейнера персонажа без признаков экипировки
                XOR A
                LD (Inventory.Utilities.Buffer + FItemLocation.State), A
                LD A, (GameState.PlayerActions + FPlayerActions.SelectedHeroID)
                LD (Inventory.Utilities.Buffer + FItemLocation.Container), A
                RET

                endmodule

                endif ; ~_MODULE_INVENTORY_UTILITIES_GRID_
