                ifndef _MODULE_INVENTORY_GRAPHICS_UTILITIES_GRID_PATTERN_
                define _MODULE_INVENTORY_GRAPHICS_UTILITIES_GRID_PATTERN_
; -----------------------------------------
; наложение сетки AA55 на прямоугольную область экрана
; In:
;   DE - позиция в знакоместах (D - y, E - x)
;   BC - размер в знакоместах (B - y, C - x)
; Out:
; Corrupt:
;   HL, DE, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
;   основной экран должен быть выбран перед вызовом
;   размер ненулевой, область целиком помещается на экране
;   атрибуты области не изменяются
; -----------------------------------------
GridPattern:    LD A, #AA
; -----------------------------------------
; наложение чередующегося узора на прямоугольную область экрана
; In:
;   DE - позиция в знакоместах (D - y, E - x)
;   BC - размер в знакоместах (B - y, C - x)
;   A  - узор первой строки, AA для сетки или FF для сплошного заполнения
; Out:
; Corrupt:
;   HL, DE, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
;   основной экран должен быть выбран перед вызовом
;   размер ненулевой, область целиком помещается на экране
;   пиксели объединяются через OR, атрибуты не изменяются
; -----------------------------------------
.Fill           ; расчёт адреса первой пиксельной строки с сохранением узора
                PUSH AF
                CALL Convert.CharToScreen
                EX DE, HL
                POP AF
                LD E, A

                ; расчёт высоты области в пикселях
                LD A, B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD D, A

                ; расчёт входа в цикл по ширине области, четыре байта на знакоместо
                LD A, #20
                SUB C
                ADD A, A    ; x2
                ADD A, A    ; x4
                LD (.Entry), A

.Row            ; сохранение начала строки перед наложением узора
                PUSH HL
.Entry          EQU $+1                                                         ; смещение входа по ширине области
                JR .Bytes

                ; -----------------------------------------
.Bytes          ; наложение узора на байты пиксельной строки
                rept 32
                LD A, (HL)
                OR E
                LD (HL), A
                INC L
                endr
                ; -----------------------------------------
                POP HL

                ; проверка количества оставшихся пиксельных строк
                DEC D
                RET Z                                                           ; выход, если обработана вся высота области

                ; переход к следующей строке и смена узора AA55
                CALL .NextRow
                RLC E
                JP .Row
; -----------------------------------------
; переход к следующей пиксельной строке экрана
; In:
;   HL - адрес текущей пиксельной строки
; Out:
;   HL - адрес той же позиции в следующей пиксельной строке
; Corrupt:
;   AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
;   следующая строка должна находиться в пределах экрана
; -----------------------------------------
.NextRow        ; переход к следующей пиксельной строке знакоместа
                INC H

                ; проверка перехода за последнюю строку знакоместа
                LD A, H
                AND #07
                RET NZ                                                          ; выход, если следующая строка находится внутри знакоместа

                ; расчёт младшего байта адреса следующей строки знакомест
                LD A, L
                ADD A, #20
                LD L, A
                RET C                                                           ; выход, если следующая строка находится в новой трети экрана

                ; возврат к первой пиксельной строке в текущей трети экрана
                LD A, H
                SUB #08
                LD H, A
                RET

                endif ; ~_MODULE_INVENTORY_GRAPHICS_UTILITIES_GRID_PATTERN_
