
                ifndef _MODULE_INVENTORY_GRAPHICS_DISPLAY_DESCRIPTION_
                define _MODULE_INVENTORY_GRAPHICS_DISPLAY_DESCRIPTION_
; -----------------------------------------
; отображение описания указанного предмета
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ необходимо включить страницу модуля "инвентаря"
;   область полностью помещается на основном экране
; -----------------------------------------
Description:    ; проверка запроса рисования нового описания
                LD HL, Inventory.States.HoveredItem.Flags
                CHECK_FLAG INVENTORY_DESCRIPTION_BIT
                JR NZ, .Prepare                                                 ; переход, если запрошено новое описание

                ; проверка необходимости восстановления существующей плашки
                CHECK_MAIN_FLAG ML_UPDATE_BIT
                RET Z                                                           ; выход, если обновление экрана не запрошено

                JR .Redraw

.Prepare        ; сброс обрабатываемого запроса рисования описания
                RES_FLAG INVENTORY_DESCRIPTION_BIT

                ; проверка наличия предмета для отображения описания
                LD A, (Inventory.States.HoveredItem.ID)
                CP ITEM_ID_NONE
                RET Z                                                           ; выход, если предмет под курсором отсутствует

                ; выбор ширины области от 10 до 24 знакомест
                LD B, 15
                CALL .Sample
                ADD A, 10
                LD C, A                                                         ; C - ширина области в знакоместах

                ; выбор высоты области от 6 до 16 знакомест
                LD B, 11
                CALL .Sample
                ADD A, 6
                LD D, A                                                         ; D - высота области в знакоместах

                ; расчёт количества допустимых горизонтальных позиций
                LD A, 33
                SUB C
                LD B, A
                CALL .Sample
                LD E, A                                                         ; E - столбец левой границы области

                ; расчёт количества допустимых вертикальных позиций
                LD A, 25
                SUB D
                LD B, A
                CALL .Sample

                ; подготовка положения и высоты области
                LD B, D                                                         ; B - высота области в знакоместах
                LD D, A                                                         ; D - строка верхней границы области

                ; сохранение положения и размера новой области описания
                LD (Inventory.States.HoveredItem.Location), DE
                LD (Inventory.States.HoveredItem.Size), BC
; -----------------------------------------
; перерисовка области описания в сохранённых границах
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ необходимо включить страницу модуля "инвентаря"
;   положение и размер должны быть подготовлены методом Description
;   сохранённые границы не изменяются
;   у всех знакомест области сбрасывается BRIGHT
;   рамка толщиной один пиксель рисуется с отступом один пиксель внутрь области
;   у знакомест по периметру устанавливается PAPER WHITE без BRIGHT
; -----------------------------------------
.Redraw         ; проверка наличия предмета для перерисовки описания
                LD A, (Inventory.States.HoveredItem.ID)
                CP ITEM_ID_NONE
                RET Z                                                           ; выход, если предмет под курсором отсутствует

                ; чтение сохранённого положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт адреса левого верхнего знакоместа основного экрана
                CALL Convert.SetBaseScreen
                CALL Convert.CharToScreen
                EX DE, HL                                                       ; HL - адрес первой пиксельной строки области

                ; расчёт высоты области в пикселях
                LD A, B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD D, A                                                         ; D - количество оставшихся пиксельных строк
                LD E, #AA                                                       ; E - узор текущей пиксельной строки

.Row            ; сохранение адреса начала пиксельной строки
                PUSH HL
                LD B, C

.Byte           ; наложение узора сетки на текущий байт пиксельной строки
                LD A, (HL)
                OR E
                LD (HL), A
                ; LD (HL), E
                INC L
                DJNZ .Byte
                POP HL

                ; проверка количества оставшихся пиксельных строк
                DEC D
                JR Z, .Frame                                                    ; переход, если область полностью заполнена

                ; переход к следующей пиксельной строке
                CALL .NextRow

                ; смена узора следующей строки между #AA и #55
                LD A, E
                CPL
                LD E, A
                JR .Row
; -----------------------------------------
; отображение рамки с белым PAPER без BRIGHT по периметру области описания
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   основной экран должен быть выбран перед вызовом
;   границы берутся из состояния предмета под курсором
; -----------------------------------------
.Frame          ; сброс яркости знакомест области описания
                CALL .ClearBright

                ; установка цвета PAPER знакомест по периметру рамки
                CALL .FrameAttr

                ; чтение положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт пиксельного адреса левого верхнего знакоместа области
                CALL Convert.CharToScreen
                EX DE, HL

                ; расчёт высоты рамки с отступами по одному пикселю
                LD A, B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                SUB 2
                LD D, A                                                         ; D - количество строк между границами рамки включительно

                ; переход к верхней границе рамки с отступом один пиксель
                CALL .NextRow
                CALL .HLine

.VLine          ; вырезание левой вертикальной границы рамки
                RES 6, (HL)
                LD B, L                                                         ; B - младший байт адреса левой границы

                ; расчёт адреса байта правой границы рамки
                LD A, C
                DEC A
                ADD A, L
                LD L, A

                ; вырезание правой границы и возврат к левой границе
                RES 1, (HL)
                LD L, B

                ; проверка достижения нижней горизонтальной границы рамки
                DEC D
                JP Z, .HLine                                                    ; переход, если достигнута нижняя горизонтальная граница рамки

                ; переход к следующей строке вертикальных границ рамки
                CALL .NextRow
                JR .VLine
; -----------------------------------------
; вырезание горизонтальной границы рамки
; In:
;   HL - адрес левого байта пиксельной строки
;   C  - ширина области в знакоместах, не менее трёх
; Out:
;   HL - исходный адрес левого байта пиксельной строки
; Corrupt:
;   BC, AF
; Note:
;   крайние пиксели области не изменяются
; -----------------------------------------
.HLine          ; сохранение адреса левой границы
                PUSH HL

                ; вырезание первых семи пикселей рамки с сохранением левого отступа
                LD A, (HL)
                AND #80
                LD (HL), A
                INC L

                ; расчёт количества байтов между краями области
                LD B, C
                DEC B
                DEC B

.HByte          ; выключение всех пикселей внутреннего байта горизонтальной границы
                LD (HL), #00
                INC L
                DJNZ .HByte

                ; вырезание последних семи пикселей рамки с сохранением правого отступа
                LD A, (HL)
                AND #01
                LD (HL), A
                POP HL
                RET
; -----------------------------------------
; установка белого PAPER у знакомест по периметру рамки
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   основной экран должен быть выбран перед вызовом
;   BRIGHT должен быть сброшен методом ClearBright
;   INK, FLASH и атрибуты внутренних знакомест не изменяются
; -----------------------------------------
.FrameAttr      ; чтение положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт адреса атрибутов левого верхнего знакоместа
                CALL Convert.AttributeAdr
                EX DE, HL

                ; установка белого PAPER верхнего ряда рамки
                CALL .PaperRow
                LD DE, #20                                                      ; DE - шаг между строками атрибутов
                DEC B                                                           ; пропуск обработанного верхнего ряда

.PaperSides     ; переход к следующему ряду боковых границ рамки
                ADD HL, DE

                ; установка белого PAPER левого знакоместа рамки
                LD A, (HL)
                OR (WHITE << 3)
                LD (HL), A
                PUSH HL

                ; расчёт адреса правого знакоместа рамки
                LD A, C
                DEC A
                ADD A, L
                LD L, A

                ; установка белого PAPER правого знакоместа рамки
                LD A, (HL)
                OR (WHITE << 3)
                LD (HL), A
                POP HL
                DJNZ .PaperSides

                ; установка белого PAPER нижнего ряда рамки
                JP .PaperRow
; -----------------------------------------
; установка белого PAPER в ряду знакомест рамки
; In:
;   HL - адрес левого атрибута ряда
;   C  - ширина ряда в знакоместах
; Out:
;   HL - исходный адрес левого атрибута ряда
; Corrupt:
;   AF
; Note:
;   остальные биты атрибутов сохраняются
; -----------------------------------------
.PaperRow       ; сохранение адреса ряда и параметров обхода рамки
                PUSH HL
                PUSH BC
                LD B, C

.PaperByte      ; установка белого PAPER текущего знакоместа
                LD A, (HL)
                OR (WHITE << 3)
                LD (HL), A
                INC HL
                DJNZ .PaperByte
                POP BC
                POP HL
                RET
; -----------------------------------------
; сброс BRIGHT у знакомест области описания
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   основной экран должен быть выбран перед вызовом
;   остальные биты атрибутов сохраняются
; -----------------------------------------
.ClearBright    ; чтение положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт адреса атрибутов левого верхнего знакоместа
                CALL Convert.AttributeAdr
                EX DE, HL
                LD DE, #20                                                      ; DE - шаг между строками атрибутов

.AttrRow        ; сохранение начала строки и количества оставшихся строк
                PUSH HL
                PUSH BC
                LD B, C

.AttrByte       ; сброс яркости текущего знакоместа
                LD A, (HL)
                AND (~BRIGHT) & #FF
                LD (HL), A
                INC HL
                DJNZ .AttrByte

                ; восстановление начала строки и количества оставшихся строк
                POP BC
                POP HL

                ; расчёт адреса следующей строки атрибутов
                ADD HL, DE
                DJNZ .AttrRow
                RET
; -----------------------------------------
; переход к следующей пиксельной строке экрана
; In:
;   HL - адрес текущей пиксельной строки
; Out:
;   HL - адрес той же позиции в следующей пиксельной строке
; Corrupt:
;   AF
; Note:
;   следующая строка должна находиться в пределах экрана
; -----------------------------------------
.NextRow        ; переход к следующей пиксельной строке знакоместа
                INC H

                ; проверка перехода за последнюю пиксельную строку знакоместа
                LD A, H
                AND #07
                RET NZ                                                          ; выход, если следующая строка находится внутри знакоместа

                ; расчёт младшего байта адреса следующей строки знакомест
                LD A, L
                ADD A, #20
                LD L, A
                RET C                                                           ; выход, если следующая строка находится в новой трети экрана

                ; возврат к первой пиксельной строке в текущей трети экрана
                LD A, H
                SUB #08
                LD H, A
                RET
; -----------------------------------------
; получение меняющегося значения в заданном диапазоне для визуальной пробы
; In:
;   B  - количество допустимых значений, от 1 до 255
; Out:
;   A  - значение от 0 до B - 1
; Corrupt:
;   HL, AF
; -----------------------------------------
.Sample         ; получение значения из счётчика тиков и регистра R
                LD HL, TickCounterRef
                LD A, R
                XOR (HL)

.Limit          ; проверка попадания значения в допустимый диапазон
                CP B
                RET C                                                           ; выход, если значение меньше количества допустимых значений

                ; уменьшение значения на размер диапазона
                SUB B
                JR .Limit

                endif ; ~_MODULE_INVENTORY_GRAPHICS_DISPLAY_DESCRIPTION_
