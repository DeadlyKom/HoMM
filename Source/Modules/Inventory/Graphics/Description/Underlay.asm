
                ifndef _MODULE_INVENTORY_GRAPHICS_DESCRIPTION_UNDERLAY_
                define _MODULE_INVENTORY_GRAPHICS_DESCRIPTION_UNDERLAY_
; -----------------------------------------
; подготовка подложки по сохранённым размеру и положению
; In:
;   флаг O_DESC_UNDERLAY_BIT определяет тип подложки
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ необходимо включить страницу модуля "инвентаря"
;   ширина должна быть не менее трёх знакомест, высота не менее двух знакомест
; -----------------------------------------
.Underlay       ; чтение сохранённого положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт смещения входа в развёрнутый цикл, по четыре байта кода на знакоместо
                LD A, #20
                SUB C
                ADD A, A    ; x2
                ADD A, A    ; x4
                LD (.MiddleEntry), A

                ; расчёт адреса левого верхнего знакоместа основного экрана
                CALL Convert.SetBaseScreen
                CALL Convert.CharToScreen
                EX DE, HL                                                       ; HL - адрес первой пиксельной строки области

                ; расчёт высоты области в пикселях
                LD A, B
                ADD A, A    ; x2
                ADD A, A    ; x4
                ADD A, A    ; x8
                LD D, A                                                         ; D - количество оставшихся пиксельных строк

                ; проверка выбора непрозрачной подложки в настройках игры
                LD E, #AA                                                       ; E - узор текущей пиксельной строки
                CHECK_CONFIG_OPTIONS_FLAG_A O_DESC_UNDERLAY_BIT
                JR Z, .Top                                                      ; переход, если выбрана прозрачная подложка

                ; подготовка сплошной заливки непрозрачной подложки
                LD E, #FF                                                       ; E - заполнение всех пикселей строки

.Top            ; сохранение высоты области и узора подложки на время вывода верхнего края
                PUSH DE

                ; отображение внешней строки верхнего края единичными пикселями
                CALL .FullRow
                CALL .NextRow

                ; вырезание горизонтальной линии верхнего края
                LD E, #00
                CALL .BorderRow
                CALL .NextRow

                ; отображение двух внутренних строк верхнего края единичными пикселями
                LD E, #FF
                CALL .BorderRow
                CALL .NextRow
                CALL .BorderRow
                CALL .NextRow
                POP DE

                ; расчёт количества строк между верхним и нижним краями
                LD A, D
                SUB 8
                LD D, A                                                         ; D - количество строк средней части подложки

.Row            ; сохранение адреса начала пиксельной строки
                PUSH HL

                ; формирование левого края 1011 с сохранением четырёх внутренних пикселей
                LD A, (HL)
                OR E
                AND #0F
                OR #B0
                LD (HL), A
                INC L

                ; вход в развёрнутый цикл согласно количеству внутренних знакомест
.MiddleEntry    EQU $+1
                JR .MiddleBytes

                ; -----------------------------------------
.MiddleBytes    ; наложение узора подложки на внутренние байты строки
                rept 30
                LD A, (HL)
                OR E
                LD (HL), A
                INC L
                endr
                ; -----------------------------------------

                ; формирование правого края 1101 с сохранением четырёх внутренних пикселей
                LD A, (HL)
                OR E
                AND #F0
                OR #0D
                LD (HL), A
                POP HL

                ; проверка количества оставшихся строк средней части
                DEC D
                JR Z, .Bottom                                                   ; переход, если средняя часть подложки полностью обработана

                ; переход к следующей пиксельной строке
                CALL .NextRow

                ; смена узора AA55 или сохранение сплошной заливки FF
                RLC E
                JP .Row

.Bottom         ; переход к первой внутренней строке нижнего края
                CALL .NextRow

                ; отображение двух внутренних строк нижнего края единичными пикселями
                LD E, #FF
                CALL .BorderRow
                CALL .NextRow
                CALL .BorderRow
                CALL .NextRow

                ; вырезание горизонтальной линии нижнего края
                LD E, #00
                CALL .BorderRow
                CALL .NextRow

                ; отображение внешней строки нижнего края единичными пикселями
                CALL .FullRow
; -----------------------------------------
; подготовка атрибутов подложки и рамки
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   основной экран должен быть выбран перед вызовом
;   границы берутся из состояния предмета под курсором
; -----------------------------------------
.Frame          ; подготовка атрибутов всей области согласно типу подложки
                CALL .AreaAttr

                ; проверка необходимости отдельной окраски периметра прозрачной подложки
                CHECK_CONFIG_OPTIONS_FLAG_A O_DESC_UNDERLAY_BIT
                CALL Z, .FrameAttr                                              ; вызов, если выбрана прозрачная подложка
                RET
; -----------------------------------------
; заполнение пиксельной строки единичными пикселями
; In:
;   HL - адрес начала пиксельной строки
;   C  - ширина строки в знакоместах
; Out:
;   HL - исходный адрес начала пиксельной строки
; Corrupt:
;   BC, AF
; -----------------------------------------
.FullRow        ; сохранение адреса начала пиксельной строки
                PUSH HL
                LD B, C

.FullByte       ; включение всех пикселей текущего байта
                LD (HL), #FF
                INC L
                DJNZ .FullByte
                POP HL
                RET
; -----------------------------------------
; формирование горизонтальной строки края подложки
; In:
;   HL - адрес начала пиксельной строки
;   E  - заполнение строки, 00 для линии рамки или FF для внутренней полосы
;   C  - ширина строки в знакоместах, не менее трёх
; Out:
;   HL - исходный адрес начала пиксельной строки
; Corrupt:
;   BC, AF
; -----------------------------------------
.BorderRow      ; сохранение адреса начала пиксельной строки
                PUSH HL

                ; формирование левого байта с включённым внешним пикселем и выключенной рамкой
                LD A, E
                AND #3F
                OR #80
                LD (HL), A
                INC L

                ; расчёт количества байтов между краями области
                LD B, C
                DEC B
                DEC B

.BorderByte     ; заполнение внутреннего байта горизонтальной строки
                LD (HL), E
                INC L
                DJNZ .BorderByte

                ; формирование правого байта с включённым внешним пикселем и выключенной рамкой
                LD A, E
                AND #FC
                OR #01
                LD (HL), A
                POP HL
                RET
; -----------------------------------------
; установка белого PAPER у знакомест по периметру рамки
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   основной экран должен быть выбран перед вызовом
;   BRIGHT должен быть сброшен методом AreaAttr
;   INK, FLASH и атрибуты внутренних знакомест не изменяются
; -----------------------------------------
.FrameAttr      ; чтение положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт адреса атрибутов левого верхнего знакоместа
                CALL Convert.AttributeAdr
                EX DE, HL

                ; установка белого PAPER верхнего ряда рамки
                CALL .PaperRow
                LD DE, #20                                                      ; DE - шаг между строками атрибутов
                DEC B                                                           ; пропуск обработанного верхнего ряда

.PaperSides     ; переход к следующему ряду боковых границ рамки
                ADD HL, DE

                ; установка белого PAPER левого знакоместа рамки
                LD A, (HL)
                OR (WHITE << 3)
                LD (HL), A
                PUSH HL

                ; расчёт адреса правого знакоместа рамки
                LD A, C
                DEC A
                ADD A, L
                LD L, A

                ; установка белого PAPER правого знакоместа рамки
                LD A, (HL)
                OR (WHITE << 3)
                LD (HL), A
                POP HL
                DJNZ .PaperSides

                ; установка белого PAPER нижнего ряда рамки
                JP .PaperRow
; -----------------------------------------
; установка белого PAPER в ряду знакомест рамки
; In:
;   HL - адрес левого атрибута ряда
;   C  - ширина ряда в знакоместах
; Out:
;   HL - исходный адрес левого атрибута ряда
; Corrupt:
;   AF
; Note:
;   остальные биты атрибутов сохраняются
; -----------------------------------------
.PaperRow       ; сохранение адреса ряда и параметров обхода рамки
                PUSH HL
                PUSH BC
                LD B, C

.PaperByte      ; установка белого PAPER текущего знакоместа
                LD A, (HL)
                OR (WHITE << 3)
                LD (HL), A
                INC HL
                DJNZ .PaperByte
                POP BC
                POP HL
                RET
; -----------------------------------------
; подготовка атрибутов всей области подложки
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   основной экран должен быть выбран перед вызовом
;   у прозрачной подложки сбрасывается только BRIGHT
;   непрозрачная подложка заполняется атрибутом INK BLACK, PAPER WHITE без BRIGHT и FLASH
; -----------------------------------------
.AreaAttr       ; чтение положения и размера области описания
                LD DE, (Inventory.States.HoveredItem.Location)
                LD BC, (Inventory.States.HoveredItem.Size)

                ; расчёт адреса атрибутов левого верхнего знакоместа
                CALL Convert.AttributeAdr
                EX DE, HL

                ; проверка типа подложки для выбора преобразования атрибутов
                LD DE, (~BRIGHT) & #FF                                          ; D - нулевое дополнение, E - маска сброса BRIGHT
                CHECK_CONFIG_OPTIONS_FLAG_A O_DESC_UNDERLAY_BIT
                JR Z, .AttrRow                                                  ; переход, если требуется сохранить цвета прозрачной подложки

                ; подготовка атрибута сплошной заливки непрозрачной подложки
                LD DE, ((WHITE << 3) | BLACK) << 8                              ; D - атрибут заливки, E - нулевая маска сохранения

.AttrRow        ; сохранение начала строки и количества оставшихся строк
                PUSH HL
                PUSH BC
                LD B, C

.AttrByte       ; применение выбранного преобразования к атрибуту знакоместа
                LD A, (HL)
                AND E
                OR D
                LD (HL), A
                INC HL
                DJNZ .AttrByte

                ; восстановление начала строки и количества оставшихся строк
                POP BC
                POP HL

                ; расчёт адреса следующей строки атрибутов
                LD A, L
                ADD A, #20
                LD L, A
                JR NC, .NextAttr                                                ; переход, если следующий ряд находится в той же странице атрибутов
                INC H

.NextAttr       ; проверка количества оставшихся строк атрибутов
                DJNZ .AttrRow
                RET
; -----------------------------------------
; переход к следующей пиксельной строке экрана
; In:
;   HL - адрес текущей пиксельной строки
; Out:
;   HL - адрес той же позиции в следующей пиксельной строке
; Corrupt:
;   AF
; Note:
;   следующая строка должна находиться в пределах экрана
; -----------------------------------------
.NextRow        ; переход к следующей пиксельной строке знакоместа
                INC H

                ; проверка перехода за последнюю пиксельную строку знакоместа
                LD A, H
                AND #07
                RET NZ                                                          ; выход, если следующая строка находится внутри знакоместа

                ; расчёт младшего байта адреса следующей строки знакомест
                LD A, L
                ADD A, #20
                LD L, A
                RET C                                                           ; выход, если следующая строка находится в новой трети экрана

                ; возврат к первой пиксельной строке в текущей трети экрана
                LD A, H
                SUB #08
                LD H, A
                RET

                endif ; ~_MODULE_INVENTORY_GRAPHICS_DESCRIPTION_UNDERLAY_
