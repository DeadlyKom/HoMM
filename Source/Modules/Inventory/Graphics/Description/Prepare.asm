
                ifndef _MODULE_INVENTORY_GRAPHICS_DESCRIPTION_PREPARE_
                define _MODULE_INVENTORY_GRAPHICS_DESCRIPTION_PREPARE_
; -----------------------------------------
; правила формирования описания предмета
;
; 1. Источник данных
;    Подготовка читает готовые данные предмета.
;    Качество и аффиксы здесь не генерируются.
;
; 2. Качество и цвет названия
;    Качество берётся из FItem.Quality, число свойств его не определяет.
;    Цвет названия выбирается по качеству экземпляра.
;        обычное       - WHITE, BRIGHT = 1
;        магическое    - BLUE, BRIGHT = 1
;        редкое        - YELLOW, BRIGHT = 1
;        уникальное    - YELLOW, BRIGHT = 0
;    Кольца и амулеты имеют качество не ниже магического.
;
; 3. Аффиксы и уникальные предметы
;    Магическое качество допускает один префикс, один суффикс или оба.
;    Редкое качество допускает от двух до четырёх аффиксов.
;    Предел экземпляра составляет два префикса и два суффикса.
;    Число аффиксов не равно числу свойств или строк описания.
;    Уникальные предметы задаются геймдизайнером.
;    Величины их свойств могут выбираться из заданных диапазонов.
;
; 4. Предметы высшего качества и врождённые навыки
;    ITEM_FLAG_SUPERIOR - флаг, предмета высшего качества.
;    Признак высшего качества сам по себе не определяет цвет названия.
;    Без дополнительных преобразований название такого предмета белое.
;    При установленном флаге перед названием добавляется текст высшего качества.
;    При создании рунного слова бонусы высшего качества сохраняются,
;    а название рунного слова отображается отдельным цветом.
;        оружие - от 5 до 15 процентов урона и от 1 до 3 рейтинга атаки
;                 бонусы допускаются по отдельности или вместе
;        броня  - от 5 до 15 процентов защиты
;    Врождённые бонусы навыков не требуют магического качества.
;
; 5. Название и тип предмета
;    Первая строка содержит название предмета.
;        кольца и амулеты - тип и название в кавычках в одной строке
;        оружие - название и отдельная строка одноручного или двуручного типа
;        остальные предметы, включая маски - без отдельной строки типа
;    Строка одноручного или двуручного типа всегда белая, BRIGHT = 1.
;
; 6. Строки свойств
;    Сначала идут базовые свойства, затем фактические свойства экземпляра.
;    Внутри каждого массива сохраняется порядок записей.
;    Предел четырёх аффиксов не ограничивает количество базовых свойств.
;    Строка содержит знак, фактическую величину и текст по типу свойства.
;    Цвет задаётся INVENTORY_DESCRIPTION_PROPERTY_COLOR.
;    Все тексты берутся из ресурса, включая знаки, кавычки и единицы измерения.
;
; 7. Ограничения описания
;    Предел строк - INVENTORY_DESCRIPTION_LINES_MAX, включая название и тип.
;    Вместимость текстов - Prepare.Size.
;    При исчерпании строк или буфера оставшиеся свойства не выводятся.
;
; 8. Размер, положение и отображение
;    8.1. Подготовка размера
;         Ширина строки с кернингом измеряется один раз и сохраняется в слоте.
;         Размер подложки определяется по максимальной ширине и числу строк.
;
;    8.2. Границы курсора
;         Обе координаты читаются вместе, учитывается размер всех кадров курсора.
;         Границы округляются наружу до знакомест.
;
;    8.3. Первое размещение
;         Плашка центрируется по горизонтали относительно курсора.
;         У краёв экрана горизонтальное положение ограничивается его границами.
;         Сначала проверяется место над курсором, затем под курсором.
;
;    8.4. Боковое размещение
;         Если сверху и снизу места нет, проверяются положения справа и слева.
;         Из угловых положений выбирается минимальная площадь перекрытия курсора.
;         При равенстве действует порядок углов.
;             первый  - правый верхний
;             второй  - правый нижний
;             третий  - левый верхний
;             четвёртый - левый нижний
;
;    8.5. Сохранение результата
;         Подложка целиком помещается на экране.
;         Положение рассчитывается при подготовке нового описания.
;         Повторное отображение использует сохранённые положение и размер.
;         Текст выводится по готовым слотам, их ширине, адресам и цветам.
;
; 9. Исключённые и отложенные механики
;    Прочность и врождённый бонус посохов против нежити не используются.
;    Требуемый уровень и сетовые бонусы пока не формируются.
;    Рунные слова пока не реализованы.
; -----------------------------------------
; -----------------------------------------
; подготовка данных предмета, размера и положения подложки описания
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF, AF', IX, IY
; Note:
;   ℹ️ необходимо включить страницу модуля "инвентаря"
; -----------------------------------------
.Prepare        ; сброс количества подготовленных строк описания
                XOR A
                LD (Inventory.States.Description.Num), A
                LD IY, Inventory.States.Description.Lines

                ; -----------------------------------------
                ; получение копии экземпляра предмета под курсором
                LD A, (Inventory.States.HoveredItem.ID)
                LD DE, .Prepare.Buffer
                CALL Inventory.SharedCode.Utilities.GetItem

                ; сохранение флагов экземпляра до перезаписи временного буфера
                LD A, (.Prepare.Buffer + FItem.Flags)                           ; чтение флагов из FItem.Flags
                LD IXL, A

                ; сохранение копии экземпляра на стеке до формирования его свойств
                LD DE, FItem - 1
                ADD HL, DE
                LD B, FItem / 2

.SaveItem       ; сохранение очередной пары байтов от конца экземпляра к началу
                LD D, (HL)
                DEC HL                                                          ; переход к младшему байту сохраняемой пары
                LD E, (HL)
                DEC HL                                                          ; переход к старшему байту предыдущей пары
                PUSH DE
                DJNZ .SaveItem

                ; возврат к началу экземпляра после сохранения копии
                INC HL

                ; сохранение индекса базового описания экземпляра
                LD A, (HL)                                                      ; чтение индекса базового описания из FItem.BaseItem
                PUSH AF

                ; получение цвета названия по качеству экземпляра
                INC HL                                                          ; переход к полю FItem.Quality
                LD E, (HL)
                LD D, #00
                LD HL, .NameColors
                ADD HL, DE
                LD A, (HL)
                POP BC                                                          ; B - индекс базового описания экземпляра
                PUSH AF                                                         ; сохранение цвета названия предмета

                ; получение базового описания со свойствами в тот же буфер
                LD A, B
                LD DE, .Prepare.Buffer
                CALL Inventory.SharedCode.Utilities.GetBaseItem

                ; восстановление цвета названия после копирования базового описания
                POP AF
                LD C, A

                ; чтение количества базовых свойств
                LD DE, FBaseItem.PropertiesNum
                ADD HL, DE
                LD A, (HL)

                ; ограничение копии свойств числом доступных строк после названия
                CP INVENTORY_DESCRIPTION_LINES_MAX
                JR C, .BaseCount                                                ; переход, если количество свойств помещается в отведённый предел
                LD A, INVENTORY_DESCRIPTION_LINES_MAX - 1

.BaseCount      ; расчёт адреса последнего байта сохраняемых базовых свойств
                LD B, A
                LD E, A
                LD D, #00
                SLA E
                RL D
                SLA E
                RL D
                ADD HL, DE

                ; проверка наличия базовых свойств для сохранения
                OR A
                JR Z, .BaseSaved                                                ; переход, если базовых свойств нет

.SaveBase       ; сохранение свойства на стеке в исходном порядке его полей
                LD D, (HL)
                DEC HL                                                          ; переход к полю FItemProperty.Value.High
                LD E, (HL)
                DEC HL                                                          ; переход к полю FItemProperty.Value.Low
                PUSH DE
                LD D, (HL)
                DEC HL                                                          ; переход к полю FItemProperty.Type
                LD E, (HL)
                DEC HL                                                          ; переход к байту перед текущим свойством
                PUSH DE
                DJNZ .SaveBase

.BaseSaved      ; сохранение количества свойств и восстановление цвета названия
                LD B, A
                PUSH BC
                LD A, C
                PUSH AF
                LD HL, .Prepare.Buffer                                          ; адрес копии базового описания предмета

                ; -----------------------------------------
                ; чтение двухбайтовой ссылки на название из базового описания
                LD C, (HL)                                                      ; чтение индекса строки из FBaseItem.Name
                INC HL                                                          ; переход к полю FBaseItem.ListName
                LD B, (HL)                                                      ; чтение индекса списка из FBaseItem.ListName
                PUSH BC                                                         ; сохранение ссылки на название предмета

                ; получение типа предмета после поля ListName
                LD DE, FBaseItem.Type - FBaseItem.ListName
                ADD HL, DE                                                      ; переход к полю FBaseItem.Type
                LD A, (HL)
                LD C, A                                                         ; C - тип предмета
                PUSH BC

                ; получение ссылки на дополнительную строку по типу предмета
                ADD A, A    ; x2
                LD E, A
                LD D, #00
                LD HL, .Types
                ADD HL, DE
                LD E, (HL)                                                      ; чтение индекса строки дополнительного текста
                INC HL                                                          ; переход к индексу списка дополнительного текста
                LD D, (HL)
                EX DE, HL                                                       ; HL - ссылка на дополнительную строку
                POP BC                                                          ; C - тип предмета
                POP DE                                                          ; DE - ссылка на название предмета

                ; проверка объединения названия амулета с его типом
                LD A, C
                CP ITEM_TYPE_AMULET
                JR Z, .JewelryName                                              ; переход, если предмет является амулетом

                ; проверка объединения названия кольца с его типом
                CP ITEM_TYPE_RING
                JR Z, .JewelryName                                              ; переход, если предмет является кольцом

                ; сохранение цвета названия и ссылки на дополнительную строку
                POP AF                                                          ; восстановление цвета названия
                PUSH HL                                                         ; сохранение ссылки на дополнительную строку
                PUSH AF
                EX DE, HL                                                       ; HL - ссылка на название предмета
                LD DE, .Prepare.Buffer

                ; проверка признака предмета высшего качества
                LD A, IXL
                AND ITEM_FLAG_SUPERIOR
                JR Z, .NameText                                                 ; переход, если приставка высшего качества не требуется

                ; копирование приставки с сохранением ссылки на название предмета
                PUSH HL
                LD HL, Text.Items.Description.Superior
                CALL Inventory.SharedCode.Utilities.GetText
                DEC DE                                                          ; переход к завершающему нулю приставки
                POP HL

.NameText       ; копирование названия после приставки или в начало строки
                CALL Inventory.SharedCode.Utilities.GetText
                LD HL, .Prepare.Buffer
                LD DE, .Prepare.Buffer
                POP AF
                CALL .AddLine

                ; проверка наличия дополнительной строки для категории предмета
                POP HL
                LD A, H
                OR L
                JR Z, .Properties                                               ; переход, если дополнительная строка не задана

                ; добавление строки одноручного или двуручного типа белым цветом
                LD A, INVENTORY_DESCRIPTION_TYPE_COLOR
                CALL .AddText
                JR .Properties

.JewelryName    ; формирование единой строки с типом и именем украшения
                CALL .JoinName
                POP AF                                                          ; восстановление цвета названия
                LD DE, .Prepare.Buffer
                CALL .AddLine

                ; -----------------------------------------
                ; формирование строк фактических свойств предмета
.Properties     ; проверка количества сохранённых базовых свойств
                POP BC
                LD IXH, B
                LD A, B
                OR A
                JR Z, .ItemProps                                                ; переход, если базовых свойств нет

.BaseProps      ; чтение типа и величины очередного базового свойства
                POP BC                                                          ; C - тип свойства, B - младший байт величины
                POP HL                                                          ; L - старший байт величины, H - резерв
                LD A, L
                LD L, B
                LD H, A
                LD A, C
                CALL .AddProperty

                ; проверка оставшихся базовых свойств
                DEC IXH
                JR NZ, .BaseProps                                               ; переход, если обработаны не все базовые свойства

.ItemProps      ; расчёт адреса количества свойств в сохранённой копии экземпляра
                LD HL, FItem.PropertiesNum
                ADD HL, SP
                LD A, (HL)

                ; переход к массиву свойств в сохранённой копии экземпляра
                rept FItem.Properties / 2
                POP BC
                endr
                LD IXH, A                                                       ; IXH - количество необработанных свойств экземпляра
                LD IXL, (FItem - FItem.Properties) / FItemProperty              ; IXL - количество оставшихся записей в копии массива

.ItemProp       ; чтение очередной записи свойства экземпляра
                POP BC                                                          ; C - тип свойства, B - младший байт величины
                POP HL                                                          ; L - старший байт величины, H - резерв

                ; проверка принадлежности записи заполненной части массива
                LD A, IXH
                OR A
                JR Z, .NextProp                                                 ; переход, если все фактические свойства экземпляра обработаны

                ; формирование строки из фактического типа и величины свойства
                LD A, L
                LD L, B
                LD H, A
                LD A, C
                CALL .AddProperty
                DEC IXH

.NextProp       ; проверка завершения чтения сохранённого массива свойств
                DEC IXL
                JR NZ, .ItemProp                                                ; переход, если в копии массива остались записи
                ; -----------------------------------------

                ; -----------------------------------------
.Measure        ; подготовка обхода заполненных слотов для определения ширины
                LD A, (Inventory.States.Description.Num)
                LD B, A
                LD HL, Inventory.States.Description.Lines
                LD C, #00                                                       ; C - максимальная ширина строки в пикселях

.MaxWidth       ; проверка ширины очередной строки относительно максимальной
                LD A, (HL)
                CP C
                JR C, .NextLine                                                 ; переход, если строка короче максимальной

                LD C, A

.NextLine       ; расчёт адреса следующего слота строки
                LD DE, INVENTORY_DESCRIPTION_LINE_SIZE
                ADD HL, DE
                DJNZ .MaxWidth

                ; расчёт ширины текста в знакоместах с округлением вверх
                LD L, C
                LD H, #00
                LD DE, 7
                ADD HL, DE
                SRL H
                RR L
                SRL H
                RR L
                SRL H
                RR L

                ; расчёт ширины плашки с отступом по одному знакоместу с краёв
                LD A, L
                ADD A, 2

                ; проверка минимальной ширины для рисования рамки
                CP 3
                JR NC, .WidthReady                                              ; переход, если ширина не меньше трёх знакомест

                LD A, 3

.WidthReady     ; сохранение рассчитанной ширины плашки
                LD C, A                                                         ; C - ширина области в знакоместах

                ; расчёт высоты по числу строк с шагом и отступами в знакоместах
                LD A, (Inventory.States.Description.Num)
                ADD A, A    ; x2
                ADD A, 2
                LD D, A                                                         ; D - высота области в знакоместах
                ; -----------------------------------------

                ; расчёт положения плашки относительно курсора
                LD B, D                                                         ; B - высота области в знакоместах
                CALL .Position                                                  ; определение положения без выхода за границы экрана

                ; сохранение положения и размера новой области описания
                LD (Inventory.States.HoveredItem.Location), DE
                LD (Inventory.States.HoveredItem.Size), BC
                RET

.Prepare.Buffer EQU Adr.RenderBuffer                                            ; адрес буфера строк и временных данных предмета
.Prepare.Size   EQU Size.RenderBuffer + Size.TilemapBuffer                      ; вместимость единого буфера описания
.PropertyMax    EQU Text.Items.Property.MaxLength + 7                           ; максимальная длина строки с пятью цифрами, знаком и завершающим нулём
; -----------------------------------------
; объединение текстов типа и имени украшения с кавычками
; In:
;   HL - ссылка на текст типа с пробелом и открывающей кавычкой
;   DE - ссылка на имя предмета
; Out:
;   HL - адрес объединённой строки во временном буфере
;   DE - адрес свободного участка после завершающего нуля
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
.JoinName       ; копирование типа украшения с сохранением ссылки на имя
                PUSH DE
                LD DE, .Prepare.Buffer
                CALL Inventory.SharedCode.Utilities.GetText

                ; добавление имени вместо завершающего нуля текста типа
                DEC DE
                POP HL
                CALL Inventory.SharedCode.Utilities.GetText

                ; добавление закрывающей кавычки из текстового ресурса
                DEC DE
                LD HL, Text.Items.Description.CloseQuote
                CALL Inventory.SharedCode.Utilities.GetText
                LD HL, .Prepare.Buffer
                RET
; -----------------------------------------
; получение текста из ресурса и добавление строки в описание
; In:
;   HL - двухбайтовая ссылка на строку
;   DE - адрес свободного участка временного буфера
;   A  - атрибут цвета строки
;   IY - адрес свободного слота строки
; Out:
;   DE - адрес свободного участка после скопированной строки
;   IY - адрес следующего слота строки
; Corrupt:
;   HL, DE, BC, AF, AF', IY
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
.AddText        ; получение текста с сохранением цвета и адреса назначения
                PUSH AF
                PUSH DE
                CALL Inventory.SharedCode.Utilities.GetText
                POP DE
                POP AF
                JP .AddLine

; -----------------------------------------
; формирование строки фактического свойства предмета
; In:
;   HL - величина свойства со знаком
;   DE - адрес свободного участка буфера описания
;   A  - тип свойства ITEM_PROPERTY_
;   IY - адрес свободного слота строки
; Out:
;   DE - адрес свободного участка после добавленной строки
;   IY - адрес следующего слота при добавлении строки
; Corrupt:
;   HL, DE, BC, AF, AF', IY
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
;   IX сохраняется для обхода копий свойств
; -----------------------------------------
.AddProperty    ; проверка наличия описания для типа свойства
                CP ITEM_PROPERTY_ID_COUNTER
                RET NC                                                          ; выход, если тип свойства не имеет описания
                LD B, A

                ; проверка наличия свободного слота строки
                LD A, (Inventory.States.Description.Num)
                CP INVENTORY_DESCRIPTION_LINES_MAX
                RET NC                                                          ; выход, если все слоты строк заполнены
                LD A, B

                ; проверка вместимости строки свойства в оставшуюся часть буфера
                PUSH HL
                LD HL, .Prepare.Buffer + .Prepare.Size - .PropertyMax
                OR A
                SBC HL, DE
                POP HL
                RET C                                                           ; выход, если оставшегося места недостаточно для строки свойства

                ; сохранение типа, величины и адреса формируемой строки
                PUSH AF
                PUSH HL
                PUSH DE

                ; выбор текста знака по фактической величине свойства
                BIT 7, H
                LD HL, Text.Items.Description.SignPlus
                JR Z, .SignReady                                                ; переход, если величина свойства неотрицательная
                LD HL, Text.Items.Description.SignMinus

.SignReady      ; копирование знака в начало формируемой строки
                CALL Inventory.SharedCode.Utilities.GetText
                DEC DE                                                          ; переход к завершающему нулю знака

                ; восстановление величины с сохранением типа и начала строки
                POP BC
                POP HL
                POP AF
                PUSH BC
                PUSH AF

                ; проверка знака перед получением модуля величины
                BIT 7, H
                JR Z, .NumberReady                                              ; переход, если величина свойства неотрицательная

                ; расчёт модуля отрицательной величины, включая значение -32768
                XOR A
                SUB L
                LD L, A
                SBC A, A
                SUB H
                LD H, A

.NumberReady    ; преобразование модуля величины в десятичную строку
                PUSH DE
                CALL Convert.BinaryToDecimal.x16
                POP DE
                CALL String.Copy
                DEC DE                                                          ; переход к завершающему нулю числа

                ; добавление текста свойства с единицами измерения из ассета
                POP AF                                                          ; восстановление типа свойства
                LD L, A
                LD H, Text.Items.Property
                CALL Inventory.SharedCode.Utilities.GetText

                ; добавление сформированной строки в описание
                POP DE
                LD H, D
                LD L, E
                LD A, INVENTORY_DESCRIPTION_PROPERTY_COLOR
                JP .AddLine
; -----------------------------------------
; добавление строки в очередной слот описания
; In:
;   HL - адрес исходной строки
;   DE - адрес свободного участка временного буфера
;   A  - атрибут цвета строки
;   IY - адрес свободного слота строки
; Out:
;   DE - адрес свободного участка после скопированной строки
;   IY - адрес следующего слота строки
; Corrupt:
;   HL, DE, BC, AF, AF', IY
; Note:
;   ℹ️ код расположен в модуле "инвентаря"
; -----------------------------------------
.AddLine        ; копирование строки с сохранением цвета и адреса начала
                PUSH AF
                PUSH DE
                CALL String.Copy
                POP HL
                PUSH DE
                PUSH HL

                ; измерение ширины строки из общего буфера
                EX DE, HL
                CALL_IN_PAGE Page.Font, Font.GetWidth
                LD (IY + FInventoryDescriptionLine.Width), E

                ; заполнение адреса строки в текущем слоте
                POP DE
                LD (IY + FInventoryDescriptionLine.Text), E
                LD (IY + FInventoryDescriptionLine.Text + 1), D
                POP BC                                                          ; BC - адрес свободного участка буфера
                POP AF
                LD (IY + FInventoryDescriptionLine.Attribute), A

                ; переход к свободному участку буфера и следующему слоту
                LD D, B
                LD E, C
                LD BC, INVENTORY_DESCRIPTION_LINE_SIZE
                ADD IY, BC

                ; обновление количества подготовленных строк
                LD HL, Inventory.States.Description.Num
                INC (HL)
                RET
; -----------------------------------------
; расчёт положения плашки относительно курсора
; In:
;   B  - высота плашки в знакоместах
;   C  - ширина плашки в знакоместах
; Out:
;   DE - положение плашки, D строка, E столбец в знакоместах
; Corrupt:
;   HL, DE, AF, IX, IY
; Note:
;   ширина не больше 32 знакомест, высота не больше 24 знакомест
;   границы курсора охватывают все кадры Builder/Assets/Graphics/Original/Cursor/Pack.inc
;   при равном перекрытии порядок углов, правый верхний, правый нижний, левый верхний, левый нижний
; -----------------------------------------
.Position       ; чтение положения курсора, L координата X, H координата Y в пикселях
                LD HL, (Mouse.Position)

                ; -----------------------------------------
                ; центрирование плашки по горизонтали
                ; расчёт столбца плашки с центром около курсора
                LD A, C
                SRL A
                LD D, A
                LD A, L
                RRCA
                RRCA
                RRCA
                AND #1F
                SUB D
                JR NC, .CenterLeft                                              ; переход, если левый край плашки не выходит за экран

                XOR A

.CenterLeft     ; ограничение положения правой границей экрана
                LD E, A
                LD A, SCREEN_CURSOR_X >> 3
                SUB C
                CP E
                JR NC, .CurBounds                                               ; переход, если правый край плашки помещается на экране

                LD E, A

                ; -----------------------------------------

                ; -----------------------------------------
                ; границы курсора в знакоместах
.CurBounds      ; расчёт левой границы всех кадров курсора с округлением вниз
                LD A, L
                SUB .CURSOR_LEFT
                JR NC, .CurLeft                                                 ; переход, если левая граница курсора не выходит за экран

                XOR A

.CurLeft        RRCA
                RRCA
                RRCA
                AND #1F
                LD IXH, A                                                       ; IXH - левый столбец области курсора

                ; расчёт правой границы курсора с округлением вверх
                LD A, L
                ADD A, .CURSOR_RIGHT + 7
                JR C, .RightLimit                                               ; переход, если правая граница достигла края экрана

                RRCA
                RRCA
                RRCA
                AND #1F
                JR .RightBound

.RightLimit     LD A, SCREEN_CURSOR_X >> 3

.RightBound     LD IXL, A                                                       ; IXL - столбец после правой границы курсора

                ; расчёт верхней границы всех кадров курсора с округлением вниз
                LD A, H
                SUB .CURSOR_TOP
                JR NC, .CurTop                                                  ; переход, если верхняя граница курсора не выходит за экран

                XOR A

.CurTop         RRCA
                RRCA
                RRCA
                AND #1F
                LD IYH, A                                                       ; IYH - верхняя строка области курсора

                ; расчёт нижней границы курсора с округлением вверх
                LD A, H
                ADD A, .CURSOR_BOTTOM + 7
                RRCA
                RRCA
                RRCA
                AND #1F
                ; проверка нижней границы курсора относительно края экрана
                CP SCREEN_CURSOR_Y >> 3
                JR C, .BottomBound                                              ; переход, если нижняя граница находится внутри экрана

                LD A, SCREEN_CURSOR_Y >> 3

.BottomBound    LD IYL, A                                                       ; IYL - строка после нижней границы курсора

                ; -----------------------------------------

                ; -----------------------------------------
                ; размещение над курсором или под курсором
                ; проверка размещения плашки над курсором
                LD A, IYH
                SUB B
                JR C, .Below                                                    ; переход, если над курсором недостаточно места

                LD D, A
                RET

.Below          ; проверка размещения плашки под курсором
                LD A, IYL
                LD D, A
                ADD A, B
                CP (SCREEN_CURSOR_Y >> 3) + 1
                RET C                                                           ; выход, если плашка целиком помещается под курсором

                ; -----------------------------------------

                ; -----------------------------------------
                ; боковое размещение с минимальным перекрытием
                ; расчёт крайнего правого положения плашки
                LD A, SCREEN_CURSOR_X >> 3
                SUB C
                LD E, A

                ; проверка свободного места справа от курсора
                CP IXL
                JR C, .LeftCheck                                                ; переход, если справа недостаточно места

                LD E, IXL
                LD D, #00
                RET

.LeftCheck      ; проверка свободного места слева от курсора
                LD A, IXH
                SUB C
                JR C, .SideOverlap                                              ; переход, если слева недостаточно места

                LD E, A
                LD D, #00
                RET

.SideOverlap    ; расчёт начала горизонтального пересечения для правого положения
                LD A, E
                CP IXH
                JR NC, .RightStart                                              ; переход, если плашка начинается внутри области курсора

                LD A, IXH

.RightStart     LD D, A
                LD A, IXL
                SUB D
                LD D, A                                                         ; D - ширина пересечения справа в знакоместах

                ; расчёт ширины пересечения для левого положения
                LD A, C
                CP IXL
                JR C, .LeftEnd                                                  ; переход, если плашка заканчивается внутри области курсора

                LD A, IXL

.LeftEnd        SUB IXH
                ; проверка преимущества левого положения по ширине пересечения
                CP D
                JR NC, .Vertical                                                ; переход, если правое положение имеет не большее пересечение

                LD E, #00

.Vertical       ; расчёт высоты пересечения при расположении у верхнего края экрана
                LD A, B
                CP IYL
                JR C, .TopEnd                                                   ; переход, если плашка заканчивается внутри области курсора

                LD A, IYL

.TopEnd         SUB IYH
                LD L, A                                                         ; L - высота пересечения сверху в знакоместах

                ; расчёт крайнего нижнего положения плашки
                LD A, SCREEN_CURSOR_Y >> 3
                SUB B
                LD H, A

                ; расчёт начала пересечения при расположении у нижнего края экрана
                LD A, IYH
                CP H
                JR NC, .BottomStart                                             ; переход, если область курсора начинается внутри плашки

                LD A, H

.BottomStart    LD D, A
                LD A, IYL
                SUB D

                ; проверка преимущества нижнего положения по высоте пересечения
                CP L
                JR NC, .PosTop                                                  ; переход, если верхнее положение имеет не большее пересечение

                LD D, H
                RET

.PosTop         LD D, #00
                RET

                ; -----------------------------------------

.CURSOR_LEFT    EQU 2                                                           ; смещение левой границы относительно точки курсора в пикселях
.CURSOR_RIGHT   EQU 22                                                          ; смещение правой границы относительно точки курсора в пикселях
.CURSOR_TOP     EQU 3                                                           ; смещение верхней границы относительно точки курсора в пикселях
.CURSOR_BOTTOM  EQU 22                                                          ; смещение нижней границы относительно точки курсора в пикселях

                ; -----------------------------------------
                ; цвета названия по значениям ITEM_QUALITY_
.NameColors     DB INVENTORY_DESCRIPTION_NORMAL_COLOR                           ; ITEM_QUALITY_NORMAL
                DB INVENTORY_DESCRIPTION_MAGIC_COLOR                            ; ITEM_QUALITY_MAGIC
                DB INVENTORY_DESCRIPTION_RARE_COLOR                             ; ITEM_QUALITY_RARE
                DB INVENTORY_DESCRIPTION_UNIQUE_COLOR                           ; ITEM_QUALITY_UNIQUE
                DB INVENTORY_DESCRIPTION_SET_COLOR                              ; ITEM_QUALITY_SET
                ; -----------------------------------------

                ; -----------------------------------------
                ; тексты типов по значениям ITEM_TYPE_
.Types          DW #0000                                                        ; ITEM_TYPE_HEAD
                DW #0000                                                        ; ITEM_TYPE_BREAST
                DW Text.Items.Description.TypeAmulet                            ; ITEM_TYPE_AMULET
                DW Text.Items.Description.TypeRing                              ; ITEM_TYPE_RING
                DW #0000                                                        ; ITEM_TYPE_LEFT_HAND
                DW Text.Items.Description.TypeOneHand                           ; ITEM_TYPE_RIGHT_HAND
                DW Text.Items.Description.TypeTwoHand                           ; ITEM_TYPE_TWO_HANDED
                DW #0000                                                        ; ITEM_TYPE_BELT
                DW #0000                                                        ; ITEM_TYPE_SHOULDER_PAD
                DW #0000                                                        ; ITEM_TYPE_BOOT
                ; -----------------------------------------

                endif ; ~_MODULE_INVENTORY_GRAPHICS_DESCRIPTION_PREPARE_
