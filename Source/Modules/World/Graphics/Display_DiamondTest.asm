                ifndef _MODULE_WORLD_DISPLAY_DIAMOND_TEST_
                define _MODULE_WORLD_DISPLAY_DIAMOND_TEST_
; -----------------------------------------
; тестовая прокрутка текстуры времени суток
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF, DE'
; Note:
;   ℹ️ необходимо включить страницу модуля "мира"
;   фаза меняется каждые 25 прерываний независимо от игрового времени
;   начальная фаза соответствует текстуре, отображённой при запуске
; -----------------------------------------
DiamondTest:    ; чтение текущей и последней отображённой фазы
                LD HL, (.Phase)
.LastPhase      EQU $+1
                LD DE, #0080

                ; проверка изменения фазы текстуры
                OR A
                SBC HL, DE
                RET Z                                                           ; выход, если текущая фаза уже отображена

                ; восстановление и сохранение фазы текущей отрисовки
                ADD HL, DE
                LD (.LastPhase), HL

                ; преобразование половины цикла во флаг направления
                LD A, H
                RRCA
                LD A, L
                LD HL, (Kernel.Modules.World.MemoryAddress)
                CALL DiamondTexture                                             ; отображение новой фазы на основном экране

                ; установка запроса переноса обновлённого ромба
                SET_FLAG_MODIFY World.Base.Render.PipelineHexagons.DiamondFlag
                RET
; -----------------------------------------
; отсчёт тестового интервала в прерывании
; In:
; Out:
; Corrupt:
;   HL, AF
; Note:
;   ℹ️ необходимо включить страницу модуля "мира"
;   25 прерываний при частоте 50 Гц соответствуют 0.5 секунды
; -----------------------------------------
.Tick           ; уменьшение счётчика до следующей фазы
.Counter        EQU $+1
                LD A, 25
                DEC A
                LD (.Counter), A

                ; проверка завершения интервала смены фазы
                RET NZ                                                          ; выход, если интервал в 25 прерываний ещё не завершён

                ; подготовка следующего интервала
                LD A, 25
                LD (.Counter), A

                ; расчёт следующей фазы цикла из двух половин по 256 шагов
.Phase          EQU $+1
                LD HL, #0080
                INC HL
                RES 1, H                                                        ; ограничение фазы диапазоном 0..511
                LD (.Phase), HL
                RET

                endif                                                           ; ~_MODULE_WORLD_DISPLAY_DIAMOND_TEST_
