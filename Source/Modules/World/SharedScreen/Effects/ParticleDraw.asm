                ifndef _WORLD_EFFECTS_PARTICLE_DRAW_
                define _WORLD_EFFECTS_PARTICLE_DRAW_
                module ParticleDraw
                ; специализированные XOR-рисовалки перенесены из рабочего снега
                ; запись FTornadoParticle сохраняет координаты текущего рисунка и основного снимка
; -----------------------------------------
; XOR формы по явно переданным координатам в выбранном экране
; In:
;   DE - экранная позиция, D по Y, E по X
;   IX - запись FTornadoParticle с выбранной формой
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   центр DE находится внутри игрового окна, края многопиксельных форм отсекаются
; -----------------------------------------
ShapeAt:        ; выбор формы в теневом экране
                BIT 5, (IX + FTornadoParticle.Shown)
                JP Z, PixelFast                                                 ; переход, если частица рисуется одной точкой

                LD B, 0
                JR .Bounds

.Base           ; выбор формы в основном экране
                BIT 5, (IX + FTornadoParticle.Shown)
                JP Z, PixelBaseFast                                             ; переход, если частица рисуется одной точкой

                LD B, #80
.Bounds         ; проверка полного размещения формы с запасом по одному пикселю
                LD A, E
                SUB RAIN_MIN_X + 1
                CP RAIN_RANGE_X - 2
                JP NC, .Generic                                                 ; переход, если форма касается горизонтальной границы окна

                LD A, D
                SUB RAIN_MIN_Y + 1
                CP RAIN_RANGE_Y - 2
                JP NC, .Generic                                                 ; переход, если форма касается вертикальной границы окна

                ; проверка пересечения правой границы пиксельного байта
                LD A, E
                AND 7
                CP 7
                JP Z, .Generic                                                  ; переход, если форма пересекает правую границу байта

                ; расчёт адреса и выбор экрана для двух строк квадрата
.Address        CALL PixelAddress
                LD C, (HL)
                BIT 7, B
                JR Z, .CubeFast                                                 ; переход, если адрес уже указывает на теневой экран

                RES 7, D
.CubeFast       ; объединение соседних пикселей в двух строках квадрата
                LD A, C
                RRCA
                OR C
                LD C, A
                CALL .Pair
                CALL .Down
                JP .Pair

.Pair           ; XOR объединённой маски в выбранном экране
                LD A, (DE)
                XOR C
                LD (DE), A
                RET

.Down           ; расчёт адреса следующей пиксельной строки Spectrum
                INC D
                LD A, D
                AND 7
                RET NZ                                                          ; выход, если адрес остаётся в пределах восьми пиксельных строк

                LD A, E
                ADD A, #20
                LD E, A
                RET C                                                           ; выход, если переход пересёк границу трети экрана

                LD A, D
                SUB 8
                LD D, A
                RET

.Generic        ; вывод квадрата с отсечением на границе окна или байта
                LD HL, .Cube
                BIT 7, B
                JP Z, DrawPattern                                               ; переход, если квадрат рисуется в теневом экране

                JP PatternBase

.Cube           DB 4, 0, 0, 1, 0, 0, 1, 1, 1                                    ; квадрат 2 на 2, число пикселей и пары X, Y

; -----------------------------------------
; XOR шаблона в основном экране с отсечением каждого пикселя
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   HL указывает на число точек и пары смещений, DE содержит центр
; -----------------------------------------
PatternBase:    LD B, (HL)
                INC HL
.Loop           PUSH BC
                PUSH DE

                ; расчёт положения очередной точки относительно центра частицы
                LD A, (HL)
                ADD A, E
                LD E, A
                INC HL
                LD A, (HL)
                ADD A, D
                LD D, A
                INC HL
                PUSH HL
                CALL PixelBase
                POP HL
                POP DE
                POP BC
                DJNZ .Loop
                RET
; -----------------------------------------
; XOR одной точки основного экрана с отсечением по игровому окну
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   DE содержит экранные координаты, D по Y, E по X
; -----------------------------------------
PixelBase:      ; проверка размещения точки внутри игрового окна
                CALL World.SharedScreen.Effects.ParticleDraw.InView
                RET C                                                           ; выход, если точка находится за пределами игрового окна

; -----------------------------------------
; XOR точки основного экрана без отсечения по существующим таблицам
; In:
; Out:
; Corrupt:
;   HL, DE, AF
; Note:
;   DE содержит координаты внутри окна, D по Y, E по X
; -----------------------------------------
PixelBaseFast:  CALL World.SharedScreen.Effects.ParticleDraw.PixelAddress
                RES 7, D
                LD A, (DE)
                XOR (HL)
                LD (DE), A
                RET
; -----------------------------------------
; общие отсечение и адресация по штатным таблицам экрана
; -----------------------------------------
InView:         ; проверка горизонтальных границ игрового окна
                LD A, E
                SUB RAIN_MIN_X
                CP RAIN_RANGE_X
                CCF
                RET C                                                           ; выход, если пиксель находится вне горизонтальных границ

                ; проверка вертикальных границ игрового окна
                LD A, D
                SUB RAIN_MIN_Y
                CP RAIN_RANGE_Y
                CCF
                RET

Pixel:          ; отсечение и XOR пикселя теневого экрана
                ; проверка границ перед обращением к таблицам и записи пикселя
                CALL InView
                RET C                                                           ; выход, если пиксель находится за пределами игрового окна

                CALL PixelAddress

.Shadow         ; XOR точки только в теневом экране
                LD A, (DE)
                XOR (HL)
                LD (DE), A
                RET

; -----------------------------------------
; прямой XOR точки в теневом экране без отсечения и выбора обработчика
; In:
;   DE - экранная позиция, D по Y, E по X, точка внутри игрового окна
; Out:
; Corrupt:
;   HL, DE, AF
; Note:
;   включена страница 7, вызов при закрытом CursorMemcpyGate
; -----------------------------------------
PixelFast:      ; расчёт адреса точки и выбор её битовой маски
                LD H, HIGH Adr.ScrAdrTable
                LD L, D
                LD A, (HL)
                INC H
                LD D, (HL)
                INC H
                LD L, E
                OR (HL)
                LD E, A
                INC H

                ; XOR точки только в теневом экране
                LD A, (DE)
                XOR (HL)
                LD (DE), A
                RET

; -----------------------------------------
; общий расчёт адреса и битовой маски точки без отсечения и записи
; In:
;   DE - экранная позиция, D по Y, E по X, точка внутри игрового окна
; Out:
;   HL - адрес битовой маски пикселя
;   DE - адрес байта теневого экрана
; Corrupt:
;   HL, DE, AF
; -----------------------------------------
PixelAddress:   ; получение адреса строки и байта по готовым таблицам
                LD H, HIGH Adr.ScrAdrTable
                LD L, D
                LD A, (HL)
                INC H
                LD D, (HL)
                INC H
                LD L, E
                OR (HL)
                LD E, A
                INC H

                RET
; -----------------------------------------
; следующий байт псевдослучайной последовательности
; In:
; Out:
;   A - очередное значение
; Corrupt:
;   AF
Random:         ; продвижение ненулевого восьмибитного регистра с обратной связью
                LD A, (Seed)
                ADD A, A
                JR NC, .Store                                                   ; переход, если старший бит прежнего значения был сброшен

                XOR #1D
.Store          LD (Seed), A
                RET
; -----------------------------------------
; XOR шаблона точек теневого экрана, общий вход для всплесков и снежинок
; In:
;   HL - число точек и пары знаковых смещений X, Y
;   DE - экранная позиция центра, D - y, E - x в пикселях
; Out:
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   отсечение по игровому окну выполняется существующей процедурой Pixel
DrawPattern:    ; чтение количества пикселей выбранной фазы
                LD B, (HL)
                INC HL
.Loop           PUSH BC
                PUSH DE

                ; расчёт положения брызги относительно точки удара
                LD A, (HL)
                ADD A, E
                LD E, A
                INC HL
                LD A, (HL)
                ADD A, D
                LD D, A
                INC HL
                PUSH HL
                CALL Pixel
                POP HL
                POP DE
                POP BC
                DJNZ .Loop
                RET

Seed            DB #A7                                                          ; состояние прежнего генератора случайных чисел дождя
                endmodule
                endif                                                           ; ~_WORLD_EFFECTS_PARTICLE_DRAW_
