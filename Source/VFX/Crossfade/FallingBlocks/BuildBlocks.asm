
                ifndef _VFX_CROSSFADE_FALLING_BLOCKS_BUILD_BLOCKS_
                define _VFX_CROSSFADE_FALLING_BLOCKS_BUILD_BLOCKS_
; -----------------------------------------
; преобразование базового экрана в блоки 16x16
; In:
; Out:
;   буфер Const.BufferAdr заполнен графикой 192 блоков
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в странице 7
;   блоки расположены слева направо и сверху вниз
;   каждый блок занимает 36 байт и состоит из двух половин
;   первая половина содержит строки 0-7, затем два атрибута
;   вторая половина содержит строки 15-8, затем два атрибута
;   в каждой паре сначала хранится левый байт, затем правый
; -----------------------------------------
BuildBlocks:    ; подготовка адресов базового экрана, буфера и количества рядов блоков
                LD HL, SCR_ADR_BASE
                LD DE, Const.BufferAdr
                LD B, #0C

.Row            ; подготовка количества блоков в текущем ряду
                LD C, #10

.Block          ; сохранение счётчиков и начала исходного блока
                PUSH BC
                PUSH HL

                ; копирование графики и атрибутов текущего блока
                CALL .CopyBlock
                POP HL
                POP BC

                ; расчёт адреса следующего блока по горизонтали
                INC L
                INC L

                ; проверка оставшихся блоков текущего ряда
                DEC C
                JP NZ, .Block                                                   ; переход, если в текущем ряду остались блоки

                ; расчёт начала следующего ряда высотой 16 пикселей
                LD A, L
                ADD A, #20
                LD L, A
                JP NC, .NextRow                                                 ; переход, если следующий ряд остался в текущей трети

                ; расчёт старшего байта адреса следующей трети экрана
                LD A, H
                ADD A, #08
                LD H, A

.NextRow        ; переход к обработке следующего ряда блоков
                DJNZ .Row
                RET

.CopyBlock      ; копирование первых семи строк верхней половины сверху вниз
                rept 7
                FB_COPY_ROW
                INC H
                endr
                FB_COPY_ROW

                ; копирование атрибутов верхней половины с сохранением пиксельного адреса
                PUSH HL
                CALL .Attributes
                POP HL

                ; расчёт адреса последней строки нижней половины
                LD A, L
                ADD A, #20
                LD L, A

                ; копирование первых семи строк нижней половины снизу вверх
                rept 7
                FB_COPY_ROW
                DEC H
                endr
                FB_COPY_ROW

.Attributes     ; копирование атрибутов нижней половины
                FB_TO_ATTR                                                      ; преобразование пиксельного адреса в атрибутный

                ; копирование левого и правого атрибутов половины блока
                LDI
                LDI
                RET

                endif ; ~_VFX_CROSSFADE_FALLING_BLOCKS_BUILD_BLOCKS_
