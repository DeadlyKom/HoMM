
                ifndef _INVENTORY_RENDER_ITEMS_
                define _INVENTORY_RENDER_ITEMS_
; -----------------------------------------
; отображение предмета выбранного персонажа
; In:
;   A  - идентификатор экземпляра предмета
;   DE - координаты в знакоместах (D - y, E - x)
;        у предмета необходимо вкл флаг ITEM_ITEM_POSITION_CUSTOM_BIT
; Out:
;   D  - тип отображённого предмета или ITEM_ID_NONE, если предмет не отображён
;   IX - размер изображения в знакоместах (IXH - y, IXL - x)
;   IY - позиция изображения в знакоместах (IYH - y, IYL - x)
; Corrupt:
;   HL, DE, BC, AF, AF', IX, IY
; Note:
;   ℹ️ код расположен в "общей памяти"
; -----------------------------------------
Item:           ; сохранение идентификатора экземпляра
                LD B, A
                EX AF, AF'

                ; подготовка восстановления страницы при выходе
                PUSH_PAGE
                LD HL, SetPageInStack
                PUSH HL

                ; получение размещения и проверка владельца
                LD A, B
                CALL .Location
                JR NZ, .NotDrawn                                                ; переход, если предмет перетаскивается или не принадлежит выбранному персонажу

                ; проверка режима заданной экранной позиции
                BIT ITEM_ITEM_POSITION_CUSTOM_BIT, C
                JR NZ, .Position                                                ; переход, если позиция передана в DE
                JR .GridPosition

.NotDrawn       ; возврат признака отсутствия отображённого предмета
                LD D, ITEM_ID_NONE
                RET
; -----------------------------------------
; отображение предмета в сетке выбранного персонажа
; In:
;   A  - идентификатор экземпляра предмета
; Out:
; Corrupt:
;   HL, DE, BC, AF, AF', IX, IY
; Note:
;   ℹ️ код расположен в "общей памяти"
; -----------------------------------------
.Grid           ; сохранение идентификатора экземпляра
                LD B, A
                EX AF, AF'

                ; подготовка восстановления страницы при выходе
                PUSH_PAGE
                LD HL, SetPageInStack
                PUSH HL

                ; получение размещения и проверка владельца
                LD A, B
                CALL .Location
                RET NZ                                                          ; выход, если предмет перетаскивается или не принадлежит выбранному персонажу

                ; проверка размещения предмета в сетке
                LD A, C
                AND ITEM_LOCATION_EQUIPPED | ITEM_ITEM_POSITION_CUSTOM
                RET NZ                                                          ; выход, если предмет экипирован или использует пользовательскую позицию

.GridPosition   ; -----------------------------------------
                ; перевод позиции предмета из ячеек сетки в экранные знакоместа
                ; -----------------------------------------

                ; чтение позиции предмета в ячейках сетки
                INC HL                                                          ; FItemLocation.Container
                LD E, (HL)
                INC HL
                LD D, (HL)

                ; расчёт горизонтальной позиции на экране в знакоместах
                LD A, E
                ADD A, A                                                        ; x2
                ADD A, SCR_INVENTORY_POS_X
                LD E, A

                ; расчёт вертикальной позиции на экране в знакоместах
                LD A, D
                ADD A, A                                                        ; x2
                ADD A, SCR_INVENTORY_POS_Y
                LD D, A

.Position       ; получение экземпляра для отображения
                EX AF, AF'
                CALL Item.Utilities.GetAdr.HL                                   ; получить адрес экземпляра предмета

                ; чтение индекса базового описания экземпляра
                LD A, (HL)                                                      ; чтение индекса базового описания из FItem.BaseItem
                EX AF, AF'

                ; включение страницы базовых описаний
.Metadata.Page  EQU $+1                                                         ; операнд с номером страницы метаданных
                LD A, #00
                SET_PAGE_A

                ; получение адреса базовых описаний
.Metadata.Adr   EQU $+1                                                         ; операнд с адресом ресурса метаданных
                LD HL, #0000
                EX AF, AF'                                                      ; восстановление индекса базового предмета

                ; получение базового описания с сохранением экранной позиции
                PUSH DE
                CALL Item.Utilities.GetBaseAdr.HL                               ; получить адрес базового описания предмета
                POP DE

                ; сохранение типа предмета на время отображения
                PUSH HL
                LD BC, FBaseItem.Type
                ADD HL, BC
                LD A, (HL)
                POP HL
                PUSH AF

                ; чтение индекса визуала базового предмета
                INC HL                                                          ; переход к полю FBaseItem.ListName
                INC HL                                                          ; переход к полю FBaseItem.Visual
                LD L, (HL)
                LD H, #00

                ; расчёт смещения заголовка FItemVisual по индексу
                ADD HL, HL                                                      ; x2
                ADD HL, HL                                                      ; x4

                ; расчёт адреса заголовка внутри графического ресурса
.Address        EQU $+1                                                         ; операнд с адресом графического ресурса
                LD BC, #0000
                ADD HL, BC

                ; включение страницы графики предметов
.Page           EQU $+1                                                         ; операнд с номером страницы графики
                LD A, #00
                SET_PAGE_A

                ; сохранение позиции и размера изображения на время отображения
                LD C, (HL)
                INC HL
                LD B, (HL)
                PUSH DE
                PUSH BC

                ; расчёт адреса данных спрайта
                INC HL                                                          ; переход к полю FItemVisual.Offset
                LD C, (HL)
                INC HL
                LD B, (HL)
                ADD HL, BC

                ; расчёт горизонтальной позиции в пикселях
                LD A, E
                ADD A, A                                                        ; x2
                ADD A, A                                                        ; x4
                ADD A, A                                                        ; x8
                LD E, A

                ; расчёт вертикальной позиции в пикселях
                LD A, D
                ADD A, A                                                        ; x2
                ADD A, A                                                        ; x4
                ADD A, A                                                        ; x8
                LD D, A

                ; подготовка функции вывода спрайта без указания блока спрайтов (FSpriteBlock)
                LD BC, #0000                                                    ; значение счётчиков и флагов для полного вывода
                LD (Kernel.Boundary.Functions.VHCounters), BC                   ; установка счётчиков полного вывода спрайта
                LD IX, Kernel.Boundary.Functions.OR_XOR_ATTR                    ; выбор обработчика OR/XOR с атрибутами

                ; отображение спрайта с возвратом к восстановлению регистров
                LD BC, .RestoreRegs                                             ; адрес возврата после отображения спрайта
                PUSH BC
                PUSH HL                                                         ; адрес данных спрайта для чтения со стека
                JP Kernel.Boundary.Functions.Draw

.RestoreRegs    ; восстановление размера, позиции и типа отображённого предмета
                POP IX                                                          ; размер изображения в знакоместах (IXH - y, IXL - x)
                POP IY                                                          ; позиция изображения в знакоместах (IYH - y, IYL - x)
                POP DE                                                          ; D - тип предмета из сохранённой пары AF
                RET                                                             ; восстановление страницы и возврат вызывающему коду
; -----------------------------------------
; получение размещения предмета и проверка владельца
; In:
;   A  - идентификатор экземпляра предмета
; Out:
;   HL - адрес FItemLocation.Container, если установлен флаг Z
;   C  - состояние FItemLocation.State
;   флаг Z установлен, если предмет принадлежит выбранному персонажу и не перетаскивается
; Corrupt:
;   HL, BC, AF
; Note:
;   ⚠️ ВАЖНО ⚠️
;   меняет страницу памяти
;   при выходе включена страница массива предметов
; -----------------------------------------
.Location       ; получение адреса размещения экземпляра
                CALL Item.Utilities.GetLocAdr.HL                                ; получить адрес размещения предмета
                SET_PAGE_A

                ; чтение состояния размещения предмета
                LD C, (HL)

                ; проверка перетаскивания предмета
                BIT ITEM_LOCATION_DRAGGED_BIT, C
                RET NZ                                                          ; выход, если предмет перетаскивается

                INC HL                                                          ; переход к полю FItemLocation.Container

                ; проверка принадлежности выбранному персонажу
                LD A, (GameState.PlayerActions + FPlayerActions.SelectedHeroID)
                CP (HL)
                RET
; -----------------------------------------
; отображение перетаскиваемого предмета в заданной позиции
; In:
;   DE - координаты в знакоместах (D - y, E - x)
;   A  - идентификатор экземпляра предмета
; Out:
; Corrupt:
;   HL, DE, BC, AF, AF', IX, IY
; Note:
;   ℹ️ код расположен в "общей памяти"
;   основной экран должен быть выбран перед вызовом
;   область предмета должна целиком помещаться на экране
;   страница вызывающего кода восстанавливается при выходе
; -----------------------------------------
.Dragged        ; сохранение идентификатора перетаскиваемого предмета
                EX AF, AF'

                ; подготовка восстановления страницы при выходе
                PUSH_PAGE
                LD HL, SetPageInStack
                PUSH HL

                ; включение страницы массива предметов
                LD A, (GameState.Inventory.Page)
                SET_PAGE_A
                JR .Position

                display " - Display inventory item:\t\t\t\t", /A, Item, "\t= busy [ ", /D, $-Item, " byte(s) ]"

                endif                                                           ; ~_INVENTORY_RENDER_ITEMS_
