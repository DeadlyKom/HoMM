
                ifndef _INVENTORY_UTILITIES_GET_TEXT_
                define _INVENTORY_UTILITIES_GET_TEXT_
; -----------------------------------------
; получение копии строки по индексу списка и индексу строки
; In:
;   HL - ссылка на строку, H - индекс списка, L - индекс строки
;   DE - адрес временного буфера в общей памяти
; Out:
;   HL - адрес скопированной строки
;   DE - адрес свободного участка после завершающего нуля
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   ℹ️ код расположен в "общей памяти"
;   перед вызовом необходимо включить страницу модуля "инвентаря"
;   при выходе восстановлена страница вызывающего кода
; -----------------------------------------
GetText:        ; сохранение страницы, адреса назначения и ссылки на строку
                PUSH_PAGE
                PUSH DE
                PUSH HL

                ; включение страницы текстового ресурса
                LD HL, (Inventory.States.Resource.Description.Item.Adr)
                LD A, (Inventory.States.Resource.Description.Item.Page)
                SET_PAGE_A
                POP BC                                                          ; B - индекс списка, C - индекс строки
                PUSH DE                                                         ; сохранение адреса назначения на время определения строки

                ; расчёт адреса двухбайтовой записи списка в начале ресурса
                LD E, B
                LD D, #00
                SLA E
                RL D
                ADD HL, DE

                ; получение адреса списка из смещения относительно старшего байта записи
                LD E, (HL)
                INC HL                                                          ; переход к старшему байту смещения
                LD D, (HL)
                ADD HL, DE

                ; получение адреса строки по локальному индексу
                LD A, C
                CALL String.GetStringID

                ; копирование выбранной строки во временный буфер
                POP DE
                CALL String.Copy
                POP HL                                                          ; восстановление адреса начала скопированной строки
                JP_POP_PAGE                                                     ; восстановление страницы вызывающего кода

                endif                                                           ; ~_INVENTORY_UTILITIES_GET_TEXT_

