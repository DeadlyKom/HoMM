                ifndef _SUBMODULES_CONTOUR_LAUNCH_ALLOCATE_
                define _SUBMODULES_CONTOUR_LAUNCH_ALLOCATE_
; -----------------------------------------
; выделение рабочего буфера сабмодуля "обводки"
; In:
; Out:
;   HL - адрес таблицы расширения
; Corrupt:
;   DE, BC, AF, AF', IX
; Note:
;   ℹ️ необходимо включить страницу сабмодуля "обводки"
; -----------------------------------------
Allocate:       ; расчёт адреса рабочего буфера после памяти ресурса
                LD A, (Kernel.Submodules.Contour.Page)
                LD D, A
                LD IX, GameState.Assets

                ; -----------------------------------------
                ; расчёт адреса первого блока после ресурса
                ; In:
                ;   IX - адрес структуры FAssets
                ; Out:
                ;   HL - адрес блока, выровненный на 256 байт
                ;   A  - номер страницы (0-31)
                ; Corrupt:
                ;   HL, BC, AF
                ; -----------------------------------------
                CALL_IN_PAGE Page.AssetManager, AssetsManager.CalcNextBlock
                ; проверка на ошибки не требуется,                                   
                ; т.к. архивный загрузчик гарантирует наличие этого блока в странице ресурса

                ; сохранение старшего байта адреса рабочего буфера
                LD A, H
                LD (Release.Buffer), A

                ; выделение служебных 256 байт для рабочего буфера
                LD E, #01
                SET_REGISTER IX, HL

                ; -----------------------------------------
                ; выделение участка памяти (обёртка)
                ; In:
                ;   D  - номер страницы и режим выделения
                ;   E  - количество блоков по 256 байт
                ;   IX - адрес первого блока
                ; Out:
                ;   D  - номер страницы (0-31)
                ;   E  - количество блоков по 256 байт
                ;   F' - флаг переполнения установлен, если выделение памяти не удалось
                ;   IX - адрес первого блока (#C000-#FF00)
                ; Corrupt:
                ;   HL, BC, AF, AF'
                ; -----------------------------------------
                CALL_IN_PAGE Page.AssetManager, AssetsManager.MemAllocation.Wrap

                ; расчёт адреса таблицы перед рабочим буфером
                SET_REGISTER HL, IX
                LD A, H
                SUB HIGH Submodules.Contour.Size.Tables
                LD H, A
                RET
; -----------------------------------------
; освобождение рабочего буфера сабмодуля "обводки"
; In:
; Out:
; Corrupt:
;   HL, DE, BC, AF, AF', IX
; Note:
;   ℹ️ необходимо включить страницу сабмодуля "обводки"
; -----------------------------------------
Release:        ; освобождение рабочего буфера размером 256 байт
.Buffer         EQU $+1
                LD D, #00                                                       ; старший байт адреса рабочего буфера
                LD A, (Kernel.Submodules.Contour.Page)                          ; страница рабочего буфера
                LD E, A

                ; -----------------------------------------
                ; освобождение участка памяти (ранее выделенной через MemAllocation) (обёртка)
                ; In:
                ;   D  - старший байт адреса внутри выделенной области
                ;   E  - номер физической страницы (0-31)
                ; Out:
                ;   флаг переполнения установлен, если выделенная область не найдена
                ; Corrupt:
                ;   HL, DE, BC, AF
                ; -----------------------------------------
                JP_IN_PAGE Page.AssetManager, AssetsManager.MemRelease.Wrap

                endif ; ~_SUBMODULES_CONTOUR_LAUNCH_ALLOCATE_
